"""#317 — AIA progress billing: G702 Application and Certificate for Payment + G703
Continuation Sheet, on top of the invoice model (#315) and the invoice documents (#326).

Model
-----
* `billing_sov` — the BILLING schedule of values per project: item no, description,
  scheduled value, kind (`base` line or `change_order`). This is the money breakdown the
  client approved; it is NOT the drop-plan quantity model in `sov_line_items` (unit rates
  for field tracking), though a project can import those descriptions as a starting point.
* `pay_application` — one Application for Payment: number (sequential per project),
  billing period, application date, retainage percentages, and — once issued — the
  `progress` invoice it became. Its status IS the invoice's status (draft until issued;
  issued / paid / void follow the invoice), so Payments and Receivables stay one truth.
* `pay_application_line` — per SOV item on an application: work completed THIS period
  and materials presently stored. "From previous application" is computed from the
  earlier issued / paid applications, never stored, so a voided application drops out.

G702 arithmetic (every line rounded to cents)
  1 original contract sum        = Σ scheduled value of base items
  2 net change by change orders  = Σ scheduled value of change-order items
  3 contract sum to date         = 1 + 2
  4 total completed & stored     = Σ G703 column G
  5 retainage                    = a) % of completed work (D + E) + b) % of stored (F)
  6 total earned less retainage  = 4 − 5
  7 less previous certificates   = line 6 of the previous issued / paid application
  8 current payment due          = 6 − 7        -> the invoice amount
  9 balance to finish incl. ret. = 3 − 6

G703 columns: A item · B description · C scheduled value · D from previous application ·
E this period · F materials presently stored · G total completed and stored (D+E+F) ·
% (G/C) · H balance to finish (C−G) · I retainage.

Rules: one draft application per project at a time; a line may not bill past its
scheduled value (D+E+F ≤ C); an application with an invoice is read-only; a draft can be
deleted, an issued one only voided (through its invoice). The invoice document, PDF,
email, private link and view tracking are the #326 ones — for an application invoice the
document IS the G702 + G703.
"""
