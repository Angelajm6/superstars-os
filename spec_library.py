# ---------------------------------------------------------------- helpers
def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def _err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


def _wrap(data, **meta):
    m = {"generated_at": _now()}
    if isinstance(data, list):
        m["count"] = len(data)
    m.update(meta)
    return jsonify({"data": data, "meta": m})


def _user() -> dict:
    return current_user() or {}


def _has_column(conn, table: str, column: str) -> bool:
    if db_layer.is_postgres():
        return bool(conn.execute(
            "SELECT 1 AS x FROM information_schema.columns WHERE table_name = ? AND column_name = ?",
            (table, column)).fetchone())
    return any(r["name"] == column for r in conn.execute(f"PRAGMA table_info({table})").fetchall())


def _clean(v, n: int) -> Optional[str]:
    v = str(v or "").strip()
    return v[:n] or None


# ---------------------------------------------------------------- schema
def ensure_schema(conn) -> None:
    """Idempotent on both backends (boot + tests)."""
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS spec_products ("
        f"  {pk},"
        f"  manufacturer TEXT NOT NULL DEFAULT 'Sika',"
        f"  category     TEXT NOT NULL,"
        f"  product_line TEXT,"
        f"  product_name TEXT NOT NULL,"
        f"  product_code TEXT,"
        f"  description  TEXT,"
        f"  spec_url     TEXT,"
        f"  tags         TEXT,"
        f"  created_at   TEXT,"
        f"  updated_at   TEXT,"
        f"  UNIQUE(manufacturer, product_name)"
        f")")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS project_document_specs ("
        f"  {pk},"
        f"  project_code    TEXT NOT NULL,"
        f"  spec_product_id INTEGER NOT NULL,"
        f"  added_at        TEXT,"
        f"  added_by        TEXT,"
        f"  notes           TEXT,"
        f"  UNIQUE(project_code, spec_product_id)"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_pds_project ON project_document_specs(project_code)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_pds_spec ON project_document_specs(spec_product_id)")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS spec_product_file ("
        f"  {pk},"
        f"  spec_product_id INTEGER NOT NULL,"
        f"  kind            TEXT NOT NULL,"
        f"  file_name       TEXT NOT NULL,"
        f"  file_path       TEXT NOT NULL,"
        f"  file_size       INTEGER,"
        f"  mime            TEXT,"
        f"  uploaded_by     INTEGER,"
        f"  uploaded_at     TEXT NOT NULL"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_spec_product_file ON spec_product_file(spec_product_id, kind)")
    for col, ddl in (("is_favorite", "INTEGER NOT NULL DEFAULT 0"), ("notes", "TEXT"), ("created_by", "INTEGER")):
        if not _has_column(conn, "spec_products", col):
            conn.execute(f"ALTER TABLE spec_products ADD COLUMN {col} {ddl}")
    conn.commit()
    _seed_if_empty(conn)
    for line, summary in LINE_SUMMARY.items():
        conn.execute("UPDATE spec_products SET description = ? WHERE manufacturer = 'Sika' AND product_line = ? "
                     "AND (description IS NULL OR description = '')", (summary, line))
    conn.commit()


def _seed_if_empty(conn) -> None:
    if (_one(conn.execute("SELECT COUNT(*) AS n FROM spec_products")) or {}).get("n"):
        return
    import apply_spec_products_seed as seed
    now = _now()
    for category, line, name, url, tags in seed.SEED:
        conn.execute("INSERT OR IGNORE INTO spec_products (manufacturer, category, product_line, product_name, spec_url, "
                     "tags, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?)",
                     (seed.MFR, category, line, name, url, tags, now, now))
    conn.commit()
    log.info("spec library: seeded %d catalog products", len(seed.SEED))


# ---------------------------------------------------------------- catalog
def _file_public(r: dict) -> dict:
    return {"id": r["id"], "kind": r["kind"], "file_name": r["file_name"], "file_size": r.get("file_size"),
            "uploaded_at": r.get("uploaded_at"),
            "file_url": f"/api/spec-products/{r['spec_product_id']}/files/{r['kind']}"}


def _files_by_product(conn, ids=None) -> dict:
    sql = "SELECT id, spec_product_id, kind, file_name, file_size, uploaded_at FROM spec_product_file"
    params: list = []
    if ids is not None:
        if not ids:
            return {}
        sql += f" WHERE spec_product_id IN ({','.join('?' * len(ids))})"
        params = list(ids)
    out: dict = {}
    for r in _rows(conn.execute(sql + " ORDER BY id", params)):
        out.setdefault(r["spec_product_id"], {})[r["kind"]] = _file_public(r)   # newest id wins
    return out


def list_products(conn, *, manufacturer=None, category="", product_line="", tag="", search="") -> list:
    where, params = [], []
    if manufacturer:
        where.append("manufacturer = ?")
        params.append(manufacturer)
    for col, v in (("category", category), ("product_line", product_line), ("tags", tag)):
        if v:
            where.append(f"{col} = ?")
            params.append(v)
    if search:
        where.append("(LOWER(product_name) LIKE ? OR LOWER(COALESCE(product_code,'')) LIKE ?)")
        like = f"%{search.lower()}%"
        params += [like, like]
    sql = ("SELECT id, manufacturer, category, product_line, product_name, product_code, description, spec_url, tags, "
           "COALESCE(is_favorite, 0) AS is_favorite, notes FROM spec_products"
           + (" WHERE " + " AND ".join(where) if where else "")
           + " ORDER BY manufacturer, category, product_line, product_name")
    items = _rows(conn.execute(sql, params))
    files = _files_by_product(conn)
    jobs: dict = {}
    for r in _rows(conn.execute("SELECT spec_product_id, project_code, notes FROM project_document_specs "
                                "ORDER BY project_code")):
        jobs.setdefault(r["spec_product_id"], []).append({"project_code": r["project_code"], "where": r["notes"] or ""})
    for p in items:
        p["is_favorite"] = bool(p["is_favorite"])
        f = files.get(p["id"], {})
        p["files"] = {k: f.get(k) for k in KINDS}
        p["jobs"] = jobs.get(p["id"], [])
    return items


def get_product(conn, pid: int) -> Optional[dict]:
    r = _one(conn.execute("SELECT id FROM spec_products WHERE id = ?", (pid,)))
    if not r:
        return None
    return next((p for p in list_products(conn) if p["id"] == pid), None)


def categories(conn) -> list:
    return [r["category"] for r in _rows(conn.execute(
        "SELECT DISTINCT category FROM spec_products ORDER BY category"))]


def create_product(conn, body: dict, uid=None) -> tuple:
    name = _clean(body.get("product_name"), 120)
    if not name:
        return None, "Give the product a name."
    mfr = _clean(body.get("manufacturer"), 80) or "Sika"
    cat = _clean(body.get("category"), 120) or OTHER_CATEGORY
    if cat not in categories(conn) and cat != OTHER_CATEGORY:
        return None, "Pick one of the catalog's categories."
    url = _clean(body.get("spec_url"), 500)
    if url and not re.match(r"^https?://", url):
        return None, "The manufacturer page must start with https://"
    if _one(conn.execute("SELECT id FROM spec_products WHERE LOWER(manufacturer) = ? AND LOWER(product_name) = ?",
                         (mfr.lower(), name.lower()))):
        return None, f"{name} is already in the catalog."
    now = _now()
    cur = conn.execute(
        "INSERT INTO spec_products (manufacturer, category, product_line, product_name, product_code, description, "
        "spec_url, notes, is_favorite, created_by, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
        (mfr, cat, _clean(body.get("product_line"), 80), name, _clean(body.get("product_code"), 60),
         _clean(body.get("description"), 300), url, _clean(body.get("notes"), 2000),
         1 if body.get("is_favorite") else 0, uid, now, now))
    conn.commit()
    pid = cur.lastrowid or _one(conn.execute("SELECT id FROM spec_products WHERE manufacturer = ? AND product_name = ?",
                                             (mfr, name)))["id"]
    return get_product(conn, int(pid)), None


def update_product(conn, pid: int, body: dict) -> tuple:
    if not _one(conn.execute("SELECT id FROM spec_products WHERE id = ?", (pid,))):
        return None, "not found"
    sets, params = [], []
    if "is_favorite" in body:
        sets.append("is_favorite = ?")
        params.append(1 if body.get("is_favorite") else 0)
    if "notes" in body:
        sets.append("notes = ?")
        params.append(_clean(body.get("notes"), 2000))
    if "description" in body:
        sets.append("description = ?")
        params.append(_clean(body.get("description"), 300))
    if not sets:
        return None, "nothing to change"
    conn.execute(f"UPDATE spec_products SET {', '.join(sets)}, updated_at = ? WHERE id = ?", params + [_now(), pid])
    conn.commit()
    return get_product(conn, pid), None


# ---------------------------------------------------------------- files
def add_file(conn, pid: int, kind: str, fs, *, uploaded_by=None) -> dict:
    if kind not in KINDS:
        raise ValueError("kind must be tds or sds")
    if not _one(conn.execute("SELECT id FROM spec_products WHERE id = ?", (pid,))):
        raise LookupError("product not found")
    name = Path(fs.filename or "file.pdf").name[:200]
    if Path(name).suffix.lower() != ".pdf":
        raise ValueError("Upload the data sheet as a PDF.")
    base = _FILE_BASE.resolve()
    ddir = _FILE_BASE / str(int(pid))
    if not ddir.resolve().is_relative_to(base):
        raise ValueError("invalid path")
    ddir.mkdir(parents=True, exist_ok=True)
    fpath = ddir / (uuid.uuid4().hex + ".pdf")
    fs.save(str(fpath))
    size = fpath.stat().st_size
    head = fpath.read_bytes()[:5] if size else b""
    problem = ("The file is empty." if size == 0 else "The file is larger than 25 MB." if size > MAX_FILE_BYTES
               else "That file isn't a PDF." if head != b"%PDF-" else None)
    if problem:
        fpath.unlink(missing_ok=True)
        raise ValueError(problem)
    old = _rows(conn.execute("SELECT id, file_path FROM spec_product_file WHERE spec_product_id = ? AND kind = ?",
                             (pid, kind)))
    try:
        conn.execute("INSERT INTO spec_product_file (spec_product_id, kind, file_name, file_path, file_size, mime, "
                     "uploaded_by, uploaded_at) VALUES (?,?,?,?,?,?,?,?)",
                     (pid, kind, name, ssc_paths.store_rel(fpath), size, "application/pdf", uploaded_by, _now()))
        for o in old:   # one current file per kind: the replaced one goes
            conn.execute("DELETE FROM spec_product_file WHERE id = ?", (o["id"],))
        conn.execute("UPDATE spec_products SET updated_at = ? WHERE id = ?", (_now(), pid))
        conn.commit()
    except Exception:
        fpath.unlink(missing_ok=True)
        raise
    for o in old:
        _unlink(o["file_path"])
    return _files_by_product(conn, [pid]).get(pid, {}).get(kind)


def _unlink(stored) -> None:
    try:
        p = ssc_paths.resolve_data_path(stored)
        if p.resolve().is_relative_to(_FILE_BASE.resolve()):
            p.unlink(missing_ok=True)
    except Exception as e:
        log.warning("spec library file not removed from disk: %s", e)


def file_path(conn, pid: int, kind: str) -> Optional[tuple]:
    """(path, file_name) for a gated read, or None. Path-contained under the library base."""
    r = _one(conn.execute("SELECT file_path, file_name FROM spec_product_file WHERE spec_product_id = ? AND kind = ? "
                          "ORDER BY id DESC", (pid, kind)))
    if not r or not r["file_path"]:
        return None
    p = ssc_paths.resolve_data_path(r["file_path"])
    if not (p.resolve().is_relative_to(_FILE_BASE.resolve()) and p.exists()):
        return None
    return p, r["file_name"]


def delete_file(conn, pid: int, kind: str) -> bool:
    rows = _rows(conn.execute("SELECT id, file_path FROM spec_product_file WHERE spec_product_id = ? AND kind = ?",
                              (pid, kind)))
    if not rows:
        return False
    conn.execute("DELETE FROM spec_product_file WHERE spec_product_id = ? AND kind = ?", (pid, kind))
    conn.commit()
    for r in rows:
        _unlink(r["file_path"])
    return True


def datasheet_text(conn, pid: int, kind: str = "tds", limit: int = 40000) -> Optional[str]:
    """Plain text of a product's PDF on file (for Claude), or None."""
    got = file_path(conn, pid, kind)
    if not got:
        return None
    try:
        import pypdf
        reader = pypdf.PdfReader(str(got[0]))
        parts = []
        for i, page in enumerate(reader.pages[:30]):
            parts.append(f"[page {i + 1}]\n{(page.extract_text() or '').strip()}")
        return "\n\n".join(parts)[:limit]
    except Exception as e:
        log.info("data sheet text not read: %s", type(e).__name__)
        return ""


# ---------------------------------------------------------------- a job's products
def _project(conn, code: str) -> Optional[dict]:
    return _one(conn.execute("SELECT project_code, name, address, city_zip FROM projects WHERE project_code = ?", (code,)))


def job_products(conn, code: str) -> list:
    rows = _rows(conn.execute(
        "SELECT pds.id AS link_id, pds.added_at, pds.notes, sp.id AS spec_product_id, sp.manufacturer, sp.category, "
        "sp.product_line, sp.product_name, sp.product_code, sp.description, sp.spec_url "
        "FROM project_document_specs pds JOIN spec_products sp ON sp.id = pds.spec_product_id "
        "WHERE pds.project_code = ? ORDER BY sp.category, sp.product_line, sp.product_name", (code,)))
    files = _files_by_product(conn, [r["spec_product_id"] for r in rows])
    q = code.replace("/", "")
    for r in rows:
        r["where"] = r.pop("notes") or ""
        f = files.get(r["spec_product_id"], {})
        r["files"] = {k: ({"file_name": f[k]["file_name"], "file_size": f[k]["file_size"],
                           "file_url": f"/api/projects/{q}/document-specs/{r['spec_product_id']}/files/{k}"}
                          if f.get(k) else None) for k in KINDS}
    return rows


def attach(conn, code: str, pid: int, where=None, added_by=None) -> tuple:
    if not _project(conn, code):
        return None, "Project not found", 404
    if not _one(conn.execute("SELECT id FROM spec_products WHERE id = ?", (pid,))):
        return None, "spec_product_id not found", 404
    cur = conn.execute("INSERT OR IGNORE INTO project_document_specs (project_code, spec_product_id, added_at, added_by, "
                       "notes) VALUES (?,?,?,?,?)", (code, pid, _now(), added_by, _clean(where, 300)))
    created = bool(cur.rowcount)
    conn.commit()
    row = _one(conn.execute("SELECT id, project_code, spec_product_id, added_at, added_by, notes FROM project_document_specs "
                            "WHERE project_code = ? AND spec_product_id = ?", (code, pid)))
    return row, None, (201 if created else 200)


