def _render_cover(html: str) -> bytes:
    """HTML -> PDF bytes through the app's headless engine (seam for tests)."""
    import pdf_export
    with tempfile.TemporaryDirectory() as td:
        hp, pp = Path(td) / "cover.html", Path(td) / "cover.pdf"
        hp.write_text(html, encoding="utf-8")
        res = pdf_export.render_html_to_pdf(hp, pp, timeout_sec=90)
        if not res.get("ok") or not pp.exists():
            raise RuntimeError(res.get("error") or "the cover sheet did not render")
        return pp.read_bytes()


def submittal_pdf(conn, code: str) -> tuple:
    """(pdf bytes, file name) — cover sheet + every data sheet (then SDS) on file, in list order."""
    import pypdf
    job = _project(conn, code)
    if not job:
        raise LookupError("Project not found")
    items = job_products(conn, code)
    if not items:
        raise ValueError("Add products to this job first.")
    out = pypdf.PdfWriter()
    for page in pypdf.PdfReader(io.BytesIO(_render_cover(cover_html(job, items)))).pages:
        out.add_page(page)
    for p in items:
        for kind in KINDS:
            got = file_path(conn, p["spec_product_id"], kind) if p["files"].get(kind) else None
            if not got:
                continue
            try:
                for page in pypdf.PdfReader(str(got[0])).pages:
                    out.add_page(page)
            except Exception as e:   # one unreadable PDF should not sink the package
                log.warning("submittal: %s %s skipped (%s)", p["spec_product_id"], kind, type(e).__name__)
    buf = io.BytesIO()
    out.write(buf)
    return buf.getvalue(), f"{code} product data submittal.pdf"


