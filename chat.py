def _worker(conn, b):
    """The signed-in worker for this request, from the worker app's shift token (same checks as
    server._worker_session: hash match, not revoked, not expired, the same employee)."""
    token, eid = b.get("session_token"), b.get("employee_id")
    if not isinstance(token, str) or len(token) < 32:
        raise ChatError("Sign in again to use chat.", 401)
    row = _one(conn, "SELECT employee_id, expires_at FROM worker_app_session WHERE token_hash = ? AND revoked_at IS NULL",
               (hashlib.sha256(token.encode("utf-8")).hexdigest(),))
    if not row or str(row["expires_at"]) <= _now() or (eid and row["employee_id"] != eid):
        raise ChatError("Sign in again to use chat.", 401)
    return worker_me(conn, row["employee_id"])


