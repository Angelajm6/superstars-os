def staff_me(user) -> dict:
    return {"key": f"u:{int(user['id'])}", "uid": int(user["id"]), "role": user.get("role"),
            "name": user.get("display_name") or user.get("full_name") or "", "worker": False}


def worker_me(conn, employee_id) -> dict:
    r = _one(conn, "SELECT name FROM employees WHERE employee_id = ?", (employee_id,))
    return {"key": f"e:{employee_id}", "eid": employee_id, "role": "worker",
            "name": (r or {}).get("name") or "", "worker": True}


def _staff_rows(conn) -> list:
    marks = ",".join("?" * len(STAFF_ROLES))
    return _rows(conn.execute(
        "SELECT id, COALESCE(NULLIF(display_name, ''), NULLIF(full_name, ''), email) AS name, role, employee_id_link "
        f"FROM users WHERE role IN ({marks}) AND COALESCE(is_active, 1) = 1 AND COALESCE(status, 'active') = 'active' "
        "AND COALESCE(is_system, 0) = 0 ORDER BY name", STAFF_ROLES))


ROLE_LABEL = {"admin": "Admin", "c_suite": "C-suite", "pm": "Project Manager", "super": "Superintendent",
              "estimator": "Estimator"}


def directory(conn) -> dict:
    """Everyone who can be in chat: {key: {key, name, role, field}}. Workers linked to an
    active login are listed once, as the login."""
    out, linked = {}, set()
    for r in _staff_rows(conn):
        out[f"u:{r['id']}"] = {"key": f"u:{r['id']}", "name": r["name"], "role": ROLE_LABEL.get(r["role"], r["role"]),
                               "field": False}
        if r.get("employee_id_link"):
            linked.add(r["employee_id_link"])
    try:
        ws = _rows(conn.execute("SELECT employee_id, name, trade, worker_id FROM v_active_workers ORDER BY name"))
    except Exception:
        conn.rollback()
        ws = []
    for w in ws:
        if w["employee_id"] in linked:
            continue
        label = " · ".join(x for x in ((w.get("trade") or "").strip().title(), w.get("worker_id") or "") if x)
        out[f"e:{w['employee_id']}"] = {"key": f"e:{w['employee_id']}", "name": w["name"] or "Worker",
                                        "role": label or "Field", "field": True}
    return out


def _name_of(conn, key, people) -> dict:
    if key in people:
        return people[key]
    if key.startswith("u:"):
        r = _one(conn, "SELECT COALESCE(NULLIF(display_name, ''), NULLIF(full_name, ''), email) AS name FROM users "
                       "WHERE id = ?", (int(key[2:]),))
    else:
        r = _one(conn, "SELECT name FROM employees WHERE employee_id = ?", (key[2:],))
    p = {"key": key, "name": (r or {}).get("name") or "Former member", "role": "", "field": key.startswith("e:"),
         "gone": True}
    people[key] = p
    return p


# ------------------------------------------------------------------ access
def _open_projects(conn) -> dict:
    try:
        rows = _rows(conn.execute("SELECT project_code, name, address, COALESCE(status, 'active') AS status "
                                  "FROM projects"))
    except Exception:
        conn.rollback()
        rows = _rows(conn.execute("SELECT project_code, name, address FROM projects"))
    return {r["project_code"]: r for r in rows if (r.get("status") or "active") != "closed"}


def visible_jobs(conn, me) -> set:
    """Project codes whose job channel `me` may open."""
    jobs = _open_projects(conn)
    if me["worker"]:
        rows = conn.execute("SELECT DISTINCT project_code FROM project_assignments WHERE employee_id = ? "
                            "AND status = 'active'", (me["eid"],)).fetchall()
        return {r[0] for r in rows} & set(jobs)
    role = me["role"]
    if role in COMPANY or role == "super":
        return set(jobs)
    if role == "pm":
        rows = conn.execute("SELECT project_code FROM pm_project_assignment WHERE user_id = ?", (me["uid"],)).fetchall()
        return {r[0] for r in rows} & set(jobs)
    return set()


def _is_member(conn, conv_id, key) -> bool:
    return bool(conn.execute("SELECT 1 FROM chat_member WHERE conv_id = ? AND member = ?", (conv_id, key)).fetchone())


def can_see(conn, me, conv, jobs=None) -> bool:
    if not conv or conv.get("archived_at"):
        return False
    if conv["kind"] == "job":
        return conv["project_code"] in (jobs if jobs is not None else visible_jobs(conn, me))
    if conv["kind"] == "channel" and conv["everyone"]:
        return True
    if _is_member(conn, conv["id"], me["key"]):
        return True
    return conv["kind"] == "channel" and not conv["is_private"] and not me["worker"]


def members_of(conn, conv) -> list:
    """Member keys as shown in the People panel (everyone-channels list nobody: it is the whole company)."""
    if conv["kind"] == "job":
        keys = [f"u:{r[0]}" for r in conn.execute(
            "SELECT user_id FROM pm_project_assignment WHERE project_code = ?", (conv["project_code"],)).fetchall()]
        linked = {r[1]: r[0] for r in conn.execute(
            "SELECT id, employee_id_link FROM users WHERE employee_id_link IS NOT NULL").fetchall()}
        for r in conn.execute("SELECT DISTINCT employee_id FROM project_assignments WHERE project_code = ? "
                              "AND status = 'active'", (conv["project_code"],)).fetchall():
            keys.append(f"u:{linked[r[0]]}" if r[0] in linked else f"e:{r[0]}")
        return list(dict.fromkeys(keys))
    if conv["everyone"]:
        return []
    return [r[0] for r in conn.execute("SELECT member FROM chat_member WHERE conv_id = ? ORDER BY id",
                                       (conv["id"],)).fetchall()]


def ensure_job_convs(conn, codes) -> None:
    """Make the chat of each open job the first time someone can see it (only the missing ones: on
    Postgres an INSERT that conflicts still spends an id)."""
    have = {r[0] for r in conn.execute("SELECT project_code FROM chat_conv WHERE kind = 'job'").fetchall()}
    missing = [c for c in codes if c not in have]
    if not missing:
        return
    for code in missing:
        conn.execute("INSERT OR IGNORE INTO chat_conv (kind, project_code, conv_key, created_by, created_at, last_at) "
                     "VALUES ('job', ?, ?, 'system', ?, ?)", (code, f"job:{code}", _now(), _now()))
    conn.commit()


# ------------------------------------------------------------------ conversations
class ChatError(Exception):
    def __init__(self, msg, code=400):
        super().__init__(msg)
        self.code = code


def _conv(conn, conv_id):
    try:
        return _one(conn, "SELECT * FROM chat_conv WHERE id = ?", (int(conv_id),))
    except (TypeError, ValueError):
        return None


def _get_visible(conn, me, conv_id):
    c = _conv(conn, conv_id)
    if not can_see(conn, me, c):
        raise ChatError("That chat isn't available to you.", 404)
    return c


def _title(conn, conv, me, people, projects) -> dict:
    if conv["kind"] == "job":
        p = projects.get(conv["project_code"]) or {}
        place = p.get("address") or p.get("name") or ""
        return {"title": f"{conv['project_code']} · {place}" if place else conv["project_code"],
                "sub": "Job channel · the crew and PM are added automatically"}
    if conv["kind"] == "channel":
        return {"title": conv["name"], "sub": conv.get("topic") or (
            "Everyone in the company" if conv["everyone"] else
            ("Private channel" if conv["is_private"] else "Channel"))}
    others = [k for k in members_of(conn, conv) if k != me["key"]]
    names = [_name_of(conn, k, people)["name"] for k in others]
    if len(names) > 1:
        names = [n.split(" ")[0] for n in names]
    return {"title": ", ".join(names) or "Just you", "sub": "",
            "with": [_name_of(conn, k, people) for k in others]}


def _read_id(conn, conv, me) -> int:
    r = conn.execute("SELECT last_read_id FROM chat_read WHERE conv_id = ? AND member = ?",
                     (conv["id"], me["key"])).fetchone()
    if r is not None:
        return int(r[0])
    # first look at a shared channel: start from now (no backlog of old unread)
    start = conv["last_msg_id"] if (conv["kind"] == "job" or conv["everyone"]) else 0
    conn.execute("INSERT OR IGNORE INTO chat_read (conv_id, member, last_read_id) VALUES (?, ?, ?)",
                 (conv["id"], me["key"], start))
    return int(start)


NOTIFY = ("all", "mentions", "off")


def default_notify(conv) -> str:
    """Private and group messages alert on every message; job chats, channels and #general only on an @mention."""
    return "all" if conv["kind"] == "dm" else "mentions"


def notify_of(conn, conv, me) -> str:
    r = conn.execute("SELECT notify FROM chat_read WHERE conv_id = ? AND member = ?", (conv["id"], me["key"])).fetchone()
    return (r[0] if r and r[0] in NOTIFY else None) or default_notify(conv)


def set_notify(conn, me, conv_id, mode) -> dict:
    c = _get_visible(conn, me, conv_id)
    if mode not in NOTIFY:
        raise ChatError("Pick all messages, mentions only, or mute.")
    _read_id(conn, c, me)
    conn.execute("UPDATE chat_read SET notify = ? WHERE conv_id = ? AND member = ?", (mode, c["id"], me["key"]))
    conn.commit()
    return {"notify": mode}


def alerts(conn, me, after) -> dict:
    """New messages that should pop up for `me` since message id `after` (None = just tell me where "now" is).
    A message pops up when its chat is set to all messages, or it @mentions me in a chat not muted."""
    latest = int(conn.execute("SELECT MAX(id) FROM chat_msg").fetchone()[0] or 0)
    if after is None:
        return {"latest": latest, "alerts": []}
    after = max(int(after), latest - 200)   # never replay a long backlog
    rows = _rows(conn.execute("SELECT * FROM chat_msg WHERE id > ? AND author <> ? AND deleted_at IS NULL "
                              "ORDER BY id LIMIT 50", (after, me["key"])))
    if not rows:
        return {"latest": latest, "alerts": []}
    people, projects, jobs, seen, out = directory(conn), _open_projects(conn), visible_jobs(conn, me), {}, []
    for m in rows:
        cid = m["conv_id"]
        if cid not in seen:
            c = _conv(conn, cid)
            seen[cid] = (c, notify_of(conn, c, me)) if can_see(conn, me, c, jobs) else (None, "off")
        c, mode = seen[cid]
        mentioned = f",{me['key']}," in (m["mentions"] or "")
        if not c or mode == "off" or (mode == "mentions" and not mentioned):
            continue
        if c["kind"] == "channel" and not c["everyone"] and not _is_member(conn, cid, me["key"]):
            continue   # a public channel you haven't joined
        a = _name_of(conn, m["author"], people)
        img = conn.execute("SELECT id FROM chat_file WHERE msg_id = ? AND kind = 'image' ORDER BY id LIMIT 1",
                           (m["id"],)).fetchone()
        nfiles = conn.execute("SELECT COUNT(*) FROM chat_file WHERE msg_id = ?", (m["id"],)).fetchone()[0]
        t = _title(conn, c, me, people, projects)
        where = ("# " + t["title"]) if c["kind"] == "channel" else t["title"] if c["kind"] == "job" else (
            "Group · " + t["title"] if len(t.get("with") or []) > 1 else "Private message")
        out.append({"id": m["id"], "conv_id": cid, "kind": c["kind"], "where": where, "who": a["name"],
                    "author": m["author"], "body": (m["body"] or "")[:300], "mention": mentioned,
                    "dm": c["kind"] == "dm", "image_id": img[0] if img else None, "files": int(nfiles)})
    conn.commit()
    return {"latest": max(latest, rows[-1]["id"]), "alerts": out[-10:]}


def _preview(conn, m, me, people, conv) -> str:
    if not m:
        return ""
    if m["deleted_at"]:
        text = "Message deleted"
    else:
        text = (m["body"] or "").strip().replace("\n", " ")
        if not text:
            n = conn.execute("SELECT kind FROM chat_file WHERE msg_id = ?", (m["id"],)).fetchall()
            text = ("Photo" if n and n[0][0] == "image" else "File") if n else ""
            if len(n) > 1:
                text = f"{len(n)} files"
    if m["author"] == me["key"]:
        who = "You: "
    elif conv["kind"] != "dm" or len(members_of(conn, conv)) > 2:
        who = _name_of(conn, m["author"], people)["name"].split(" ")[0] + ": "
    else:
        who = ""
    return (who + text)[:140]


def list_convs(conn, me) -> list:
    jobs = visible_jobs(conn, me)
    ensure_job_convs(conn, jobs)
    people, projects = directory(conn), _open_projects(conn)
    marks = ",".join("?" * len(jobs)) or "''"
    cand = _rows(conn.execute(
        "SELECT * FROM chat_conv WHERE archived_at IS NULL AND ("
        "(kind = 'channel' AND everyone = 1) "
        f"OR (kind = 'job' AND project_code IN ({marks})) "
        "OR id IN (SELECT conv_id FROM chat_member WHERE member = ?) "
        + ("" if me["worker"] else "OR (kind = 'channel' AND is_private = 0) ") + ")",
        tuple(jobs) + (me["key"],)))
    out = []
    for c in cand:
        joined = c["kind"] == "job" or c["everyone"] or _is_member(conn, c["id"], me["key"])
        if c["kind"] == "dm" and not c["last_msg_id"] and c["created_by"] != me["key"]:
            continue   # an empty chat someone else opened: not shown until it has a message
        rid = _read_id(conn, c, me) if joined else c["last_msg_id"]
        mode = notify_of(conn, c, me) if joined else default_notify(c)
        unread = 0 if mode == "off" else conn.execute("SELECT COUNT(*) FROM chat_msg WHERE conv_id = ? AND id > ? AND author <> ? "
                              "AND deleted_at IS NULL", (c["id"], rid, me["key"])).fetchone()[0] if joined else 0
        mention = bool(unread) and bool(conn.execute(
            "SELECT 1 FROM chat_msg WHERE conv_id = ? AND id > ? AND author <> ? AND deleted_at IS NULL "
            "AND mentions LIKE ?", (c["id"], rid, me["key"], f"%,{me['key']},%")).fetchone())
        last = _one(conn, "SELECT * FROM chat_msg WHERE id = ?", (c["last_msg_id"],)) if c["last_msg_id"] else None
        t = _title(conn, c, me, people, projects)
        out.append({"id": c["id"], "kind": c["kind"], "group": c["kind"] == "dm" and len(t.get("with") or []) > 1,
                    "title": t["title"], "sub": t["sub"], "with": t.get("with"), "project_code": c["project_code"],
                    "everyone": bool(c["everyone"]), "private": bool(c["is_private"]), "joined": bool(joined),
                    "unread": int(unread), "mention": mention, "last_at": (last or {}).get("created_at") or c["last_at"],
                    "preview": _preview(conn, last, me, people, c), "last_msg_id": c["last_msg_id"],
                    "notify": mode})
    conn.commit()
    out.sort(key=lambda x: x["last_at"] or "", reverse=True)
    return out


def unread_total(conn, me) -> dict:
    convs = list_convs(conn, me)
    return {"unread": sum(c["unread"] for c in convs), "mention": any(c["mention"] for c in convs)}


def conv_detail(conn, me, conv_id) -> dict:
    c = _get_visible(conn, me, conv_id)
    people, projects = directory(conn), _open_projects(conn)
    t = _title(conn, c, me, people, projects)
    keys = members_of(conn, c)
    can_manage = (not me["worker"] and c["kind"] == "channel" and not c["everyone"]
                  and (c["created_by"] == me["key"] or me["role"] in COMPANY or _is_member(conn, c["id"], me["key"])))
    return {"id": c["id"], "kind": c["kind"], "title": t["title"], "sub": t["sub"], "project_code": c["project_code"],
            "everyone": bool(c["everyone"]), "private": bool(c["is_private"]),
            "members": [_name_of(conn, k, people) for k in keys], "member_count": len(keys) or len(people),
            "can_add": can_manage, "can_leave": c["kind"] == "channel" and not c["everyone"]
            and _is_member(conn, c["id"], me["key"]), "joined": c["kind"] == "job" or bool(c["everyone"])
            or _is_member(conn, c["id"], me["key"]), "can_task": not me["worker"],
            "notify": notify_of(conn, c, me)}


def _file_public(f) -> dict:
    return {"id": f["id"], "name": f["name"], "kind": f["kind"], "size": f["size"], "ext": (f["ext"] or "").lstrip("."),
            "width": f["width"], "height": f["height"]}


def _msg_public(conn, m, me, people) -> dict:
    a = _name_of(conn, m["author"], people)
    out = {"id": m["id"], "author": m["author"], "name": a["name"], "role": a.get("role") or "",
           "field": a.get("field"), "mine": m["author"] == me["key"], "at": m["created_at"],
           "deleted": bool(m["deleted_at"]), "body": "" if m["deleted_at"] else (m["body"] or ""),
           "files": [], "reacts": [], "reply": None}
    if m["deleted_at"]:
        return out
    out["files"] = [_file_public(f) for f in _rows(conn.execute(
        "SELECT * FROM chat_file WHERE msg_id = ? ORDER BY id", (m["id"],)))]
    rs = {}
    for r in conn.execute("SELECT emoji, member FROM chat_react WHERE msg_id = ? ORDER BY id", (m["id"],)).fetchall():
        e = rs.setdefault(r[0], {"emoji": r[0], "count": 0, "mine": False, "who": []})
        e["count"] += 1
        e["mine"] = e["mine"] or r[1] == me["key"]
        e["who"].append(_name_of(conn, r[1], people)["name"])
    out["reacts"] = list(rs.values())
    if m["reply_to"]:
        q = _one(conn, "SELECT id, author, body, deleted_at FROM chat_msg WHERE id = ? AND conv_id = ?",
                 (m["reply_to"], m["conv_id"]))
        if q:
            out["reply"] = {"id": q["id"], "name": _name_of(conn, q["author"], people)["name"],
                            "body": "Message deleted" if q["deleted_at"] else (q["body"] or "Attachment")[:160]}
    return out


def messages(conn, me, conv_id, before=None) -> dict:
    c = _get_visible(conn, me, conv_id)
    people = directory(conn)
    args = [c["id"]]
    sql = "SELECT * FROM chat_msg WHERE conv_id = ?"
    if before:
        sql += " AND id < ?"
        args.append(int(before))
    rows = _rows(conn.execute(sql + " ORDER BY id DESC LIMIT ?", tuple(args) + (PAGE + 1,)))
    more = len(rows) > PAGE
    rows = list(reversed(rows[:PAGE]))
    joined = c["kind"] == "job" or c["everyone"] or _is_member(conn, c["id"], me["key"])
    read = _read_id(conn, c, me) if joined else c["last_msg_id"]
    conn.commit()
    return {"messages": [_msg_public(conn, m, me, people) for m in rows], "more": more, "read_id": read}


def mark_read(conn, me, conv_id, last_id) -> None:
    c = _get_visible(conn, me, conv_id)
    last_id = min(int(last_id or 0), int(c["last_msg_id"] or 0))
    _read_id(conn, c, me)
    conn.execute("UPDATE chat_read SET last_read_id = ? WHERE conv_id = ? AND member = ? AND last_read_id < ?",
                 (last_id, c["id"], me["key"], last_id))
    conn.commit()


def send(conn, me, conv_id, body, file_ids=(), reply_to=None, mentions=()) -> dict:
    c = _get_visible(conn, me, conv_id)
    body = (body or "").strip()
    if len(body) > MAX_BODY:
        raise ChatError(f"Messages can be up to {MAX_BODY} characters. Split it into two.")
    ids = []
    for f in list(file_ids or [])[:MAX_FILES + 1]:
        try:
            ids.append(int(f))
        except (TypeError, ValueError):
            raise ChatError("One of the attachments is missing. Attach it again.")
    if len(ids) > MAX_FILES:
        raise ChatError(f"Send up to {MAX_FILES} files at a time.")
    files = []
    for fid in ids:
        f = _one(conn, "SELECT * FROM chat_file WHERE id = ? AND uploader = ? AND conv_id = ? AND msg_id IS NULL",
                 (fid, me["key"], c["id"]))
        if not f:
            raise ChatError("One of the attachments is missing. Attach it again.")
        files.append(f)
    if not body and not files:
        raise ChatError("Write a message or attach a file.")
    if reply_to:
        if not conn.execute("SELECT 1 FROM chat_msg WHERE id = ? AND conv_id = ?", (int(reply_to), c["id"])).fetchone():
            reply_to = None
    if c["kind"] == "channel" and not c["everyone"] and not _is_member(conn, c["id"], me["key"]):
        _add(conn, c["id"], me["key"], me["key"])   # posting in a public channel joins it
    people = directory(conn)
    allowed = set(people)   # anyone at the company; it only lights up for someone who can see this chat
    ment = [k for k in dict.fromkeys(mentions or []) if isinstance(k, str) and k in allowed and k != me["key"]]
    mid = _insert(conn, "INSERT INTO chat_msg (conv_id, author, body, reply_to, mentions, created_at) "
                        "VALUES (?, ?, ?, ?, ?, ?)",
                  (c["id"], me["key"], body, int(reply_to) if reply_to else None,
                   ("," + ",".join(ment) + ",") if ment else None, _now()), "chat_msg")
    for f in files:
        conn.execute("UPDATE chat_file SET msg_id = ? WHERE id = ?", (mid, f["id"]))
    conn.execute("UPDATE chat_conv SET last_msg_id = ?, last_at = ? WHERE id = ?", (mid, _now(), c["id"]))
    _read_id(conn, c, me)
    conn.execute("UPDATE chat_read SET last_read_id = ? WHERE conv_id = ? AND member = ?", (mid, c["id"], me["key"]))
    _changed(conn, c["id"])
    conn.commit()
    log.info("chat message %s in conv %s (%s files, %s mentions)", mid, c["id"], len(files), len(ment))
    m = _one(conn, "SELECT * FROM chat_msg WHERE id = ?", (mid,))
    return _msg_public(conn, m, me, people)


def _msg_for(conn, me, msg_id):
    m = _one(conn, "SELECT * FROM chat_msg WHERE id = ?", (int(msg_id),))
    if not m or not can_see(conn, me, _conv(conn, m["conv_id"])):
        raise ChatError("That message isn't available.", 404)
    return m


def react(conn, me, msg_id, emoji) -> None:
    if emoji not in EMOJI:
        raise ChatError("Pick one of the reactions.")
    m = _msg_for(conn, me, msg_id)
    if m["deleted_at"]:
        raise ChatError("That message was deleted.")
    if conn.execute("SELECT 1 FROM chat_react WHERE msg_id = ? AND member = ? AND emoji = ?",
                    (m["id"], me["key"], emoji)).fetchone():
        conn.execute("DELETE FROM chat_react WHERE msg_id = ? AND member = ? AND emoji = ?", (m["id"], me["key"], emoji))
    else:
        conn.execute("INSERT OR IGNORE INTO chat_react (msg_id, member, emoji) VALUES (?, ?, ?)",
                     (m["id"], me["key"], emoji))
    _changed(conn, m["conv_id"])
    conn.commit()


def delete_msg(conn, me, msg_id) -> None:
    m = _msg_for(conn, me, msg_id)
    if m["author"] != me["key"] and me.get("role") not in COMPANY:
        raise ChatError("You can delete only your own messages.", 403)
    for f in _rows(conn.execute("SELECT * FROM chat_file WHERE msg_id = ?", (m["id"],))):
        _unlink(f)
    conn.execute("DELETE FROM chat_file WHERE msg_id = ?", (m["id"],))
    conn.execute("DELETE FROM chat_react WHERE msg_id = ?", (m["id"],))
    conn.execute("UPDATE chat_msg SET body = '', mentions = NULL, deleted_at = ? WHERE id = ?", (_now(), m["id"]))
    _changed(conn, m["conv_id"])
    conn.commit()
    log.info("chat message %s deleted", m["id"])


def _add(conn, conv_id, key, by) -> None:
    conn.execute("INSERT OR IGNORE INTO chat_member (conv_id, member, added_by, added_at) VALUES (?, ?, ?, ?)",
                 (conv_id, key, by, _now()))
    conn.execute("INSERT OR IGNORE INTO chat_read (conv_id, member, last_read_id) VALUES (?, ?, 0)", (conv_id, key))


def _reachable(conn, me) -> dict:
    """People `me` may start a chat with. Office: everyone. Worker: the office, and the crews of their jobs."""
    people = directory(conn)
    if not me["worker"]:
        return people
    jobs = visible_jobs(conn, me)
    mates = set()
    if jobs:
        marks = ",".join("?" * len(jobs))
        mates = {f"e:{r[0]}" for r in conn.execute(
            f"SELECT DISTINCT employee_id FROM project_assignments WHERE status = 'active' AND project_code IN ({marks})",
            tuple(jobs)).fetchall()}
    return {k: p for k, p in people.items() if not p["field"] or k in mates}


def start_dm(conn, me, keys) -> int:
    reach = _reachable(conn, me)
    keys = sorted({k for k in (keys or []) if isinstance(k, str) and k != me["key"]})
    if not keys:
        raise ChatError("Pick at least one person.")
    if any(k not in reach for k in keys):
        raise ChatError("One of those people can't be messaged from here.", 403)
    if len(keys) > 30:
        raise ChatError("A group can have up to 30 people. Make a channel instead.")
    ck = "dm:" + "|".join(sorted(keys + [me["key"]]))
    hit = conn.execute("SELECT id FROM chat_conv WHERE conv_key = ?", (ck,)).fetchone()
    if hit:
        return int(hit[0])
    cid = _insert(conn, "INSERT INTO chat_conv (kind, conv_key, created_by, created_at, last_at) "
                        "VALUES ('dm', ?, ?, ?, ?)", (ck, me["key"], _now(), _now()), "chat_conv")
    for k in keys + [me["key"]]:
        _add(conn, cid, k, me["key"])
    conn.commit()
    log.info("chat dm %s started (%s people)", cid, len(keys) + 1)
    return cid


def create_channel(conn, me, name, keys, private=False, topic=None) -> int:
    if me["worker"]:
        raise ChatError("Channels are made from the office.", 403)
    slug = re.sub(r"[^a-z0-9]+", "-", (name or "").strip().lower()).strip("-")[:40]
    if len(slug) < 2:
        raise ChatError("Give the channel a name of at least 2 letters.")
    if conn.execute("SELECT 1 FROM chat_conv WHERE kind = 'channel' AND name = ? AND archived_at IS NULL",
                    (slug,)).fetchone():
        raise ChatError(f"There is already a #{slug} channel. Pick another name.", 409)
    people = directory(conn)
    keys = [k for k in dict.fromkeys(keys or []) if k in people and k != me["key"]]
    cid = _insert(conn, "INSERT INTO chat_conv (kind, name, topic, is_private, conv_key, created_by, created_at, last_at) "
                        "VALUES ('channel', ?, ?, ?, ?, ?, ?, ?)",
                  (slug, (topic or "").strip()[:200] or None, 1 if private else 0, f"ch:{secrets.token_hex(8)}",
                   me["key"], _now(), _now()), "chat_conv")
    for k in keys + [me["key"]]:
        _add(conn, cid, k, me["key"])
    _changed(conn, cid)
    conn.commit()
    log.info("chat channel %s created (%s people, private=%s)", cid, len(keys) + 1, bool(private))
    return cid


def add_members(conn, me, conv_id, keys) -> int:
    d = conv_detail(conn, me, conv_id)
    if not d["can_add"]:
        raise ChatError("People can be added to channels only.", 403)
    people = directory(conn)
    keys = [k for k in dict.fromkeys(keys or []) if k in people]
    for k in keys:
        _add(conn, d["id"], k, me["key"])
    _changed(conn, d["id"])
    conn.commit()
    return len(keys)


def leave(conn, me, conv_id) -> None:
    d = conv_detail(conn, me, conv_id)
    if not d["can_leave"]:
        raise ChatError("You can't leave this chat.", 403)
    conn.execute("DELETE FROM chat_member WHERE conv_id = ? AND member = ?", (d["id"], me["key"]))
    conn.commit()


def poll(conn) -> int:
    r = conn.execute("SELECT MAX(id) FROM chat_change").fetchone()
    return int(r[0] or 0)


# ------------------------------------------------------------------ files
def _size(n) -> str:
    return f"{n / 1048576:.1f} MB" if n >= 1048576 else f"{max(1, round(n / 1024))} KB"


def _write(data: bytes) -> str:
    d = ssc_paths.under_root("data_room", "chat_files", datetime.now().strftime("%Y-%m"))
    d.mkdir(parents=True, exist_ok=True)
    p = d / (secrets.token_hex(16) + ".bin")
    try:
        blob = secret_box.encrypt_bytes(data)
    except secret_box.SecretBoxUnavailable:
        log.error("chat file not stored: the encryption key is not set on this server")
        raise ChatError("Files can't be saved right now. Tell the office; the message itself can still be sent.", 503)
    p.write_bytes(blob)
    return ssc_paths.store_rel(p)


def _unlink(f) -> None:
    for k in ("path", "thumb_path"):
        if f.get(k):
            try:
                ssc_paths.resolve_data_path(f[k]).unlink(missing_ok=True)
            except OSError:
                pass


def _prune(conn, key) -> None:
    cut = (datetime.now() - ORPHAN_AGE).isoformat(timespec="seconds")
    for f in _rows(conn.execute("SELECT * FROM chat_file WHERE uploader = ? AND msg_id IS NULL AND created_at < ?",
                                (key, cut))):
        _unlink(f)
        conn.execute("DELETE FROM chat_file WHERE id = ?", (f["id"],))


def store_file(conn, me, conv_id, filename, data) -> dict:
    c = _get_visible(conn, me, conv_id)
    name = re.sub(r"[\x00-\x1f/\\]", "", (filename or "").strip())[-150:] or "file"
    ext = ("." + name.rsplit(".", 1)[-1].lower()) if "." in name else ""
    if not data:
        raise ChatError("That file is empty.")
    if len(data) > MAX_BYTES:
        raise ChatError(f"{name} is {_size(len(data))}. Files can be up to 25 MB.")
    _prune(conn, me["key"])
    thumb, w, h = None, None, None
    if ext in IMAGE_EXT:
        import field_photos
        try:
            img = field_photos.process_image(data, name)
        except field_photos.SkipImage:
            raise ChatError(f"{name} could not be opened as a photo. Try another one.")
        data, mime, kind = img["display_bytes"], img.get("mime") or "image/jpeg", "image"
        w, h = img.get("width"), img.get("height")
        if mime == "image/jpeg" and not name.lower().endswith((".jpg", ".jpeg")):
            name = name.rsplit(".", 1)[0] + ".jpg"
            ext = ".jpg"
        thumb = _write(img["thumb_bytes"]) if img.get("thumb_bytes") else None
    elif ext in GIF_EXT:
        mime, kind = GIF_EXT[ext], "image"
    elif ext in FILE_EXT:
        mime, kind = FILE_EXT[ext], "file"
    else:
        raise ChatError("Send photos, PDF, Word, Excel, PowerPoint, CSV, text, DWG, video or ZIP files.")
    rel = _write(data)
    fid = _insert(conn, "INSERT INTO chat_file (conv_id, uploader, name, ext, mime, size, kind, path, thumb_path, "
                        "width, height, created_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                  (c["id"], me["key"], name, ext, mime, len(data), kind, rel, thumb, w, h, _now()), "chat_file")
    conn.commit()
    log.info("chat file %s stored in conv %s (%s, %s bytes)", fid, c["id"], kind, len(data))
    return _file_public(_one(conn, "SELECT * FROM chat_file WHERE id = ?", (fid,)))


def file_for(conn, me, file_id) -> dict:
    f = _one(conn, "SELECT * FROM chat_file WHERE id = ?", (int(file_id),))
    if not f:
        raise ChatError("not found", 404)
    if f["msg_id"] is None:
        if f["uploader"] != me["key"]:
            raise ChatError("not found", 404)
    elif not can_see(conn, me, _conv(conn, f["conv_id"])):
        raise ChatError("not found", 404)
    return f


def file_bytes(f, thumb=False) -> bytes:
    p = f["thumb_path"] if thumb and f.get("thumb_path") else f["path"]
    try:
        return secret_box.decrypt_bytes(ssc_paths.resolve_data_path(p).read_bytes())
    except (OSError, secret_box.SecretBoxError, secret_box.SecretBoxUnavailable):
        log.error("chat file %s could not be read", f["id"])
        raise ChatError("That file can't be opened right now.", 404)


def drop_file(conn, me, file_id) -> None:
    f = file_for(conn, me, file_id)
    if f["msg_id"] is not None or f["uploader"] != me["key"]:
        raise ChatError("That file was already sent.", 409)
    _unlink(f)
    conn.execute("DELETE FROM chat_file WHERE id = ?", (f["id"],))
    conn.commit()


def files_of(conn, me, conv_id) -> list:
    c = _get_visible(conn, me, conv_id)
    rows = _rows(conn.execute("SELECT f.*, m.author, m.created_at AS sent_at FROM chat_file f JOIN chat_msg m "
                              "ON m.id = f.msg_id WHERE f.conv_id = ? AND m.deleted_at IS NULL "
                              "ORDER BY f.id DESC LIMIT 200", (c["id"],)))
    people = directory(conn)
    return [dict(_file_public(f), at=f["sent_at"], by=_name_of(conn, f["author"], people)["name"]) for f in rows]


def _file_response(f, data, thumb=False):
    inline = (f["kind"] == "image" or f["ext"] == ".pdf") and request.args.get("download") != "1"
    resp = send_file(io.BytesIO(data), mimetype=("image/jpeg" if thumb and f.get("thumb_path") else f["mime"])
                     or "application/octet-stream", as_attachment=not inline, download_name=f["name"] or "file")
    resp.headers["Cache-Control"] = "private, no-store"
    resp.headers["X-Content-Type-Options"] = "nosniff"
    resp.headers["Content-Security-Policy"] = "default-src 'none'; img-src 'self' data:; style-src 'unsafe-inline'; sandbox"
    return resp


# ------------------------------------------------------------------ make a task from a message
def make_task(conn, me, msg_id, title, assignee, due_date) -> int:
    if me["worker"]:
        raise ChatError("Tasks are made from the office.", 403)
    m = _msg_for(conn, me, msg_id)
    c = _conv(conn, m["conv_id"])
    import team_items
    people = directory(conn)
    t = _title(conn, c, me, people, _open_projects(conn))
    who = _name_of(conn, m["author"], people)["name"]
    detail = f"From chat ({t['title']}), {who}:\n{(m['body'] or '').strip()}\n\nOpen: /chat#c{c['id']}"
    try:
        tid = team_items.create(conn, {"kind": "task", "title": (title or m["body"] or "Follow up").strip()[:120],
                                       "detail": detail[:4000], "due_date": due_date or None,
                                       "assignee_user_id": assignee or me["uid"],
                                       "project_code": c["project_code"] if c["kind"] == "job" else None},
                                actor=me["uid"])
    except (ValueError, LookupError) as e:
        raise ChatError(str(e).capitalize() + ".")
    log.info("chat message %s made into task %s", m["id"], tid)
    return int(tid)


