def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _one(conn, sql, args=()):
    r = conn.execute(sql, args).fetchone()
    return dict(r) if r else None


# ------------------------------------------------------------------ schema
def _has_column(conn, table, col) -> bool:
    if db_layer.is_postgres():
        return bool(conn.execute("SELECT 1 FROM information_schema.columns WHERE table_name = ? AND column_name = ?",
                                 (table, col)).fetchone())
    return any(r[1] == col for r in conn.execute(f"PRAGMA table_info({table})").fetchall())


def ensure(conn) -> None:
    """Idempotent: every table, index and the #general channel."""
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_conv ({pk}, kind TEXT NOT NULL, name TEXT, topic TEXT, "
                 "project_code TEXT, is_private INTEGER NOT NULL DEFAULT 0, everyone INTEGER NOT NULL DEFAULT 0, "
                 "conv_key TEXT, created_by TEXT, created_at TEXT, last_msg_id INTEGER NOT NULL DEFAULT 0, "
                 "last_at TEXT, archived_at TEXT)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_chat_conv_key ON chat_conv(conv_key)")
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_member ({pk}, conv_id INTEGER NOT NULL, member TEXT NOT NULL, "
                 "added_by TEXT, added_at TEXT)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_chat_member ON chat_member(conv_id, member)")
    conn.execute("CREATE INDEX IF NOT EXISTS ix_chat_member_m ON chat_member(member)")
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_read ({pk}, conv_id INTEGER NOT NULL, member TEXT NOT NULL, "
                 "last_read_id INTEGER NOT NULL DEFAULT 0)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_chat_read ON chat_read(conv_id, member)")
    if not _has_column(conn, "chat_read", "notify"):   # alerts (2026-11-16): all / mentions / off; NULL = the chat's default
        conn.execute("ALTER TABLE chat_read ADD COLUMN notify TEXT")
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_msg ({pk}, conv_id INTEGER NOT NULL, author TEXT NOT NULL, "
                 "body TEXT, reply_to INTEGER, mentions TEXT, created_at TEXT, deleted_at TEXT)")
    conn.execute("CREATE INDEX IF NOT EXISTS ix_chat_msg_conv ON chat_msg(conv_id, id)")
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_file ({pk}, conv_id INTEGER NOT NULL, msg_id INTEGER, "
                 "uploader TEXT NOT NULL, name TEXT, ext TEXT, mime TEXT, size INTEGER, kind TEXT, path TEXT, "
                 "thumb_path TEXT, width INTEGER, height INTEGER, created_at TEXT)")
    conn.execute("CREATE INDEX IF NOT EXISTS ix_chat_file_msg ON chat_file(msg_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS ix_chat_file_conv ON chat_file(conv_id)")
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_react ({pk}, msg_id INTEGER NOT NULL, member TEXT NOT NULL, "
                 "emoji TEXT NOT NULL)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_chat_react ON chat_react(msg_id, member, emoji)")
    # one row per change (message, reaction, delete): the poll compares MAX(id) and refetches on a change
    conn.execute(f"CREATE TABLE IF NOT EXISTS chat_change ({pk}, conv_id INTEGER, at TEXT)")
    conn.execute("INSERT OR IGNORE INTO chat_conv (kind, name, topic, everyone, conv_key, created_by, created_at, last_at) "
                 "VALUES ('channel', 'general', 'Everyone at Superstars, office and field', 1, 'general', 'system', ?, ?)",
                 (_now(), _now()))
    conn.commit()


def _insert(conn, sql, args, table) -> int:
    cur = conn.execute(sql, args)
    rid = getattr(cur, "lastrowid", None)
    if not rid:
        rid = conn.execute(f"SELECT MAX(id) FROM {table}").fetchone()[0]
    return int(rid)


def _changed(conn, conv_id) -> None:
    conn.execute("INSERT INTO chat_change (conv_id, at) VALUES (?, ?)", (conv_id, _now()))


