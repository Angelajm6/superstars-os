def register(app) -> None:
    conn = _conn()
    try:
        ensure_schema(conn)
        db_layer._PKMAP_CACHE.clear()
    except Exception as e:
        log.warning("#319 payable schema ensure skipped: %s", e)
    finally:
        conn.close()
    import company_portal
    gate = requires_section(company_portal.SECTION)
    base = "/api/company/portal/payables"
    app.add_url_rule(base, "payables_list", gate(_api_list), methods=["GET"])
    app.add_url_rule(base, "payables_create", gate(_api_create), methods=["POST"])
