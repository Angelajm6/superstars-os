#!/usr/bin/env python3
"""#319 — accounts payable + the 30-day cash view: behavioral guard.

Boots the real app (`import server`) on an ISOLATED database. Proves:
  * schema idempotent; migration script runs
  * gates: anon -> 401; pm / client -> 403 (company-portal section)
  * bills: validation; create (due defaults to +30 days); edit while open; partial
    payment keeps it open with the right balance; overpayment -> 400; final payment ->
    paid with paid_at; a paid bill cannot be voided or edited; a bill with payments
    cannot be voided; an untouched bill voids
  * feeds: a scanned receipt is offered once, logs as a `receipt` bill, then is neither
    offered nor loggable again; a subscription renewal inside the look-ahead is offered,
    logs at seats × unit cost due on the renewal date, once
  * the cash view: overdue bill counted; money in = issued client invoices due inside
    30 days; money out = open bills due inside 30 days + unlogged renewals; net; the
    upcoming list carries all three kinds in date order
  * the Overview payload carries the payables summary; the served portal has the card
    and the nav reads Dashboard (console tab too, ES "Panel")
Run:  venv/bin/python tests/smoke_payables_319.py
"""
