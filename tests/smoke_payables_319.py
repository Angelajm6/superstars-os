TAG = "pay319"
PW = "PayablesSmoke2026"
ROLES = ("c_suite", "pm", "client")
PROJ = "PAY319-A"
TODAY = date.today()


def D(n: int) -> str:
    return (TODAY + timedelta(days=n)).isoformat()


def _db():
    return db_layer.connect(pragma_fk=False)


def _ensure_subscriptions(conn) -> None:
    pg = db_layer.is_postgres()
    pk = "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if pg else "id INTEGER PRIMARY KEY AUTOINCREMENT"
    conn.execute(f"CREATE TABLE IF NOT EXISTS subscriptions ({pk}, service_name TEXT NOT NULL, provider TEXT NOT NULL, "
                 "category TEXT NOT NULL, owner_email TEXT NOT NULL DEFAULT 'x@example.com', billing_email TEXT NOT NULL DEFAULT 'x@example.com', "
                 "plan_tier TEXT, seats INTEGER DEFAULT 1, unit_cost_usd REAL, billing_cycle TEXT NOT NULL, start_date TEXT, "
                 "renewal_date TEXT, status TEXT NOT NULL DEFAULT 'active', mfa_method TEXT, admin_url TEXT, account_id TEXT, "
                 "payment_method TEXT, notes TEXT)")


def _seed() -> dict:
    ids = {}
    conn = _db()
    try:
        for role in ROLES:
            email = f"{TAG}.{role}@example.com"
            conn.execute("DELETE FROM users WHERE email = ?", (email,))
            conn.execute("INSERT INTO users (email, password_hash, role, full_name, is_active, status, "
                         "must_reset_password, is_system) VALUES (?, ?, ?, ?, 1, 'active', 0, 1)",
                         (email, auth.hash_password(PW), role, f"Smoke {role}"))
        conn.execute("DELETE FROM crm_organization WHERE name LIKE 'Pay319 %'")
        ids["org"] = crm.create_org(conn, name="Pay319 Owners", relationship_type="client")
        conn.execute("DELETE FROM projects WHERE project_code = ?", (PROJ,))
        conn.execute("INSERT INTO projects (project_code, name, address, status, client_org_id) VALUES (?, 'Pay319 Facade', "
                     "'3 Pay319 Ct', 'active', ?)", (PROJ, ids["org"]))
        conn.execute("DELETE FROM expenses WHERE vendor LIKE 'Pay319 %'")
        conn.execute("INSERT INTO expenses (project_code, vendor, doc_type, doc_number, expense_date, category, total, status, "
                     "payment_method) VALUES (?, 'Pay319 Supply Co', 'invoice', 'S-778', ?, 'materials', 1250.5, 'reviewed', 'account')",
                     (PROJ, D(-5)))
        ids["expense"] = conn.execute("SELECT id FROM expenses WHERE vendor = 'Pay319 Supply Co'").fetchone()["id"]
        _ensure_subscriptions(conn)
        conn.execute("DELETE FROM subscriptions WHERE service_name LIKE 'Pay319 %'")
        conn.execute("INSERT INTO subscriptions (service_name, provider, category, seats, unit_cost_usd, billing_cycle, renewal_date, status) "
                     "VALUES ('Pay319 Workspace', 'Pay319 Cloud', 'Productivity', 4, 18.0, 'monthly', ?, 'active')", (D(10),))
        ids["sub"] = conn.execute("SELECT id FROM subscriptions WHERE service_name = 'Pay319 Workspace'").fetchone()["id"]
        conn.commit()
        # a client invoice due in 20 days: money IN
        inv = invoices.create(conn, {"kind": "progress", "client_org_id": ids["org"], "project_code": PROJ, "amount": 9000,
                                     "description": "Pay319 progress"})
        invoices.issue(conn, inv["id"], issued_on=D(0), due_on=D(20))
        ids["invoice"] = inv["id"]
    finally:
        conn.close()
    return ids


def _cleanup():
    conn = _db()
    try:
        conn.execute("DELETE FROM payable WHERE vendor LIKE 'Pay319 %' OR description LIKE 'Pay319 %'")
        conn.execute("DELETE FROM expenses WHERE vendor LIKE 'Pay319 %'")
        try:
            conn.execute("DELETE FROM subscriptions WHERE service_name LIKE 'Pay319 %'")
        except Exception:
            conn.rollback()
        org_ids = [r["id"] for r in conn.execute("SELECT id FROM crm_organization WHERE name LIKE 'Pay319 %'").fetchall()]
        ph = ",".join("?" * len(org_ids)) or "NULL"
        inv_ids = [r["id"] for r in conn.execute(f"SELECT id FROM invoice WHERE client_org_id IN ({ph})", org_ids).fetchall()]
        purge(conn, "invoice_payment", "invoice_id", inv_ids)
        purge(conn, "invoice", "id", inv_ids)
        conn.execute("DELETE FROM projects WHERE project_code = ?", (PROJ,))
        for t, col in (("crm_activity", "entity_id"), ("crm_task", "entity_id"), ("crm_contact", "org_id")):
            purge(conn, t, col, org_ids)
        purge(conn, "crm_organization", "id", org_ids)
        uids = [r["id"] for r in conn.execute("SELECT id FROM users WHERE email LIKE ?", (f"{TAG}.%",)).fetchall()]
        conn.commit()
        purge_users(conn, uids)
        conn.commit()
    finally:
        conn.close()
    shutil.rmtree(_TMP, ignore_errors=True)


def _login(role):
    c = server.app.test_client()
    r = c.post("/api/auth/login", json={"email": f"{TAG}.{role}@example.com", "password": PW})
    assert r.status_code == 200, (role, r.status_code)
    return c


API = "/api/company/portal/payables"


def main() -> int:
    ids = _seed()
    passed = 0

    conn = _db()
    try:
        payables.ensure_schema(conn); payables.ensure_schema(conn)
    finally:
        conn.close()
    import apply_payables_319 as mig
    assert mig.main() == 0
    passed += 1; print("  schema ok")

    cs = _login("c_suite")
    assert server.app.test_client().get(API).status_code == 401
    assert _login("pm").get(API).status_code == 403 and _login("client").get(API).status_code == 403
    passed += 1; print("  gates ok")

    # ---- bills
    assert cs.post(API, json={"amount": 10}).status_code == 400
    assert cs.post(API, json={"vendor": "Pay319 X", "amount": 0}).status_code == 400
    assert cs.post(API, json={"vendor": "Pay319 X", "amount": 10, "project_code": "NOPE-319"}).status_code == 400
    r = cs.post(API, json={"vendor": "Pay319 Scaffold LLC", "doc_number": "SC-1", "amount": "2,400.00", "project_code": PROJ,
                           "category": "equipment", "description": "Pay319 pipe scaffold, September"})
    assert r.status_code == 201, r.get_json()
    b1 = r.get_json()["data"]
    assert b1["status"] == "open" and b1["amount"] == 2400.0 and b1["balance"] == 2400.0 and b1["due_at"] == D(30)
    assert b1["project_name"] == "Pay319 Facade" and b1["source"] == "bill"
    r = cs.patch(f"{API}/{b1['id']}", json={"amount": 2500, "due_at": D(3)})
    assert r.status_code == 200 and r.get_json()["data"]["amount"] == 2500.0 and r.get_json()["data"]["due_at"] == D(3)
    r = cs.post(f"{API}/{b1['id']}/pay", json={"amount": 2600})
    assert r.status_code == 400 and "more than" in r.get_json()["error"]
    r = cs.post(f"{API}/{b1['id']}/pay", json={"amount": 1000, "paid_on": D(0), "method": "check", "reference": "1042"})
    assert r.status_code == 200
    b1 = r.get_json()["data"]
    assert b1["status"] == "open" and b1["paid_amount"] == 1000.0 and b1["balance"] == 1500.0 and b1["payment_ref"] == "1042"
    assert cs.post(f"{API}/{b1['id']}/void", json={}).status_code == 409, "a bill with payments cannot be voided"
    r = cs.post(f"{API}/{b1['id']}/pay", json={})     # the rest
    b1 = r.get_json()["data"]
    assert b1["status"] == "paid" and b1["balance"] == 0.0 and b1["paid_at"] == D(0)
    assert cs.patch(f"{API}/{b1['id']}", json={"amount": 1}).status_code == 409
    assert cs.post(f"{API}/{b1['id']}/void", json={}).status_code == 409
    r = cs.post(API, json={"vendor": "Pay319 Rent Co", "amount": 3000, "due_at": D(-2), "category": "rent", "description": "Pay319 yard rent"})
    b2 = r.get_json()["data"]
    assert b2["overdue"] and b2["days_overdue"] == 2
    r = cs.post(API, json={"vendor": "Pay319 Later Inc", "amount": 700, "due_at": D(45), "description": "Pay319 beyond horizon"})
    b3 = r.get_json()["data"]
    r = cs.post(API, json={"vendor": "Pay319 Oops", "amount": 50, "description": "Pay319 void me"})
    bv = r.get_json()["data"]
    r = cs.post(f"{API}/{bv['id']}/void", json={"reason": "duplicate"})
    assert r.status_code == 200 and r.get_json()["data"]["status"] == "void" and "duplicate" in r.get_json()["data"]["notes"]
    passed += 1; print("  bills ok")

    # ---- feeds
    d = cs.get(API).get_json()["data"]
    assert any(c["id"] == ids["expense"] for c in d["candidates"]["receipts"]), "receipt offered"
    assert any(c["id"] == ids["sub"] for c in d["candidates"]["renewals"]), "renewal offered"
    r = cs.post(f"{API}/from-receipt/{ids['expense']}", json={"due_at": D(12)})
    assert r.status_code == 201, r.get_json()
    br = r.get_json()["data"]
    assert br["source"] == "receipt" and br["amount"] == 1250.5 and br["vendor"] == "Pay319 Supply Co" and br["due_at"] == D(12) and br["project_code"] == PROJ
    assert cs.post(f"{API}/from-receipt/{ids['expense']}", json={}).status_code == 409
    assert cs.post(f"{API}/from-receipt/999999", json={}).status_code == 404
    r = cs.post(f"{API}/from-subscription/{ids['sub']}", json={})
    assert r.status_code == 201, r.get_json()
    bs = r.get_json()["data"]
    assert bs["source"] == "subscription" and bs["amount"] == 72.0 and bs["due_at"] == D(10) and bs["category"] == "software"
    assert cs.post(f"{API}/from-subscription/{ids['sub']}", json={}).status_code == 409
    d = cs.get(API).get_json()["data"]
    assert not any(c["id"] == ids["expense"] for c in d["candidates"]["receipts"])
    assert not any(c["id"] == ids["sub"] for c in d["candidates"]["renewals"])
    passed += 1; print("  feeds ok")

    # ---- the cash view
    s = d["summary"]; p = s["payables"]; c30 = s["cash_30"]
    # open: b2 3000 (overdue, due -2) · b3 700 (due +45) · receipt 1250.5 (due +12) · sub 72 (due +10)
    assert p["open_count"] == 4 and p["open_value"] == 5022.5, p
    assert p["overdue_count"] == 1 and p["overdue_value"] == 3000.0
    assert p["due_30_value"] == 4322.5 and p["due_30_count"] == 3
    assert p["renewals_30_value"] == 0.0, "the renewal is logged now, so it is a bill, not a projection"
    assert p["paid_ytd_value"] == 2500.0 and p["paid_ytd_count"] == 1
    assert s["receivables"]["due_30_value"] >= 9000.0
    assert c30["out"] == 4322.5 and c30["in"] >= 9000.0 and c30["net"] == round(c30["in"] - c30["out"], 2)
    kinds = {u["kind"] for u in s["upcoming"]}
    assert kinds == {"payable", "receivable"}, kinds
    whens = [u["when"] for u in s["upcoming"]]
    assert whens == sorted(whens) and s["upcoming"][0]["overdue"]
    mine = [u for u in s["upcoming"] if u["kind"] == "receivable" and u["what"] and u["amount"] == 9000.0]
    assert mine and mine[0]["direction"] == "in"
    # a renewal NOT logged is a projection in "out"
    conn = _db()
    try:
        conn.execute("INSERT INTO subscriptions (service_name, provider, category, seats, unit_cost_usd, billing_cycle, renewal_date, status) "
                     "VALUES ('Pay319 Storage', 'Pay319 Cloud', 'Cloud', 1, 30.0, 'monthly', ?, 'active')", (D(5),))
        conn.commit()
    finally:
        conn.close()
    s = cs.get(API).get_json()["data"]["summary"]
    assert s["payables"]["renewals_30_value"] == 30.0 and s["cash_30"]["out"] == 4352.5
    assert any(u["kind"] == "renewal" and u["amount"] == 30.0 for u in s["upcoming"])
    # list filters
    assert all(r["overdue"] for r in cs.get(API + "?status=overdue").get_json()["data"]["items"])
    assert all(r["status"] == "paid" for r in cs.get(API + "?status=paid").get_json()["data"]["items"])
    assert all("scaffold" in (r["vendor"] + (r["description"] or "")).lower() for r in cs.get(API + "?status=all&search=scaffold").get_json()["data"]["items"])
    passed += 1; print("  cash view ok")

    # ---- overview payload + served pages + the Dashboard rename
    ov = cs.get("/api/company/portal/overview").get_json()["data"]
    assert ov["payables"]["cash_30"]["horizon_days"] == 30 and ov["payables"]["payables"]["open_count"] == 4
    html = cs.get("/company").get_data(as_text=True)
    assert 'id="pb-card"' in html and 'id="pb-new-overlay"' in html and "loadPayables" in html
    assert 'data-company-nav' in html and ">Overview<" not in html and "overview: 'Dashboard'" in html
    nav = (ROOT / "static" / "js" / "company_nav.js").read_text(encoding="utf-8")
    assert "label: 'Dashboard'" in nav and "Overview" not in nav   # #339: one sidebar for every company page
    con = cs.get("/", follow_redirects=True).get_data(as_text=True)
    assert 'data-company-nav' in con and ">Overview<" not in con
    for page in ("/admin/projects", "/admin/users", "/estimating", "/admin/labor-rates"):
        h = cs.get(page, follow_redirects=True).get_data(as_text=True)
        assert 'data-company-nav' in h and '>Overview</a>' not in h, page
    passed += 1; print("  overview + rename ok")

    print(f"PASS smoke_payables_319 ({passed} groups)")
    return 0


if __name__ == "__main__":
    try:
        code = main()
    finally:
        _cleanup()
    raise SystemExit(code)
