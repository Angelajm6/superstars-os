"""Documents drop zone — the pending-review holding area.

A file dropped on a project's Documents tab is SAVED at once (so a refresh or a
phone going to sleep never loses it), read by Claude, and waits in
project_doc_intake with Claude's suggestion until someone approves the tag.
Approving moves it into project_documents (same on-disk file, no copy);
removing deletes the row and the file.

  project_doc_intake  — one row per dropped file awaiting approval.
                        file_path is on-disk ONLY, never serialized.
                        status: 'ready' (Claude read it) | 'unread' (no AI / failed).
                        content_sha256: the same file dropped twice waits once.
  project_documents   + type_key   (doc_types key — the approved tag)
                      + ai_extract (JSON: summary, key_facts, fields, confidence, model, related)
                      + party / party_name (whose record it is: our company, a
                        subcontractor, the owner — several can share one checklist item)
  project_doc_suggest_dismissed — suggestions someone marked "not needed" (doc_suggest).

Idempotent, both backends (SQLite / Postgres via db_layer). The app ensures it at
boot; apply_doc_intake.py runs it as a migration.
"""
from __future__ import annotations

import json

import db_layer
import doc_types


def _column_exists(conn, table: str, col: str) -> bool:
    if db_layer.is_postgres():
        return bool(conn.execute(
            "SELECT 1 FROM information_schema.columns "
            "WHERE table_schema='public' AND table_name=? AND column_name=?",
            (table, col)).fetchone())
    return any(r[1] == col for r in conn.execute(f"PRAGMA table_info({table})").fetchall())


def ensure_schema(conn) -> None:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS project_doc_intake ("
        f"  {pk},"
        f"  project_code     TEXT NOT NULL,"
        f"  file_path        TEXT NOT NULL,"
        f"  file_name        TEXT,"
        f"  file_size        INTEGER,"
        f"  mime             TEXT,"
        f"  doc_type         TEXT,"
        f"  status           TEXT NOT NULL DEFAULT 'unread',"
        f"  suggestion_json  TEXT,"
        f"  error            TEXT,"
        f"  uploaded_by_uid  INTEGER,"
        f"  created_at       TEXT NOT NULL"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_projdoc_intake_project ON project_doc_intake(project_code)")
    # the same file dropped twice (a double drop, a second tab) waits once
    if not _column_exists(conn, "project_doc_intake", "content_sha256"):
        conn.execute("ALTER TABLE project_doc_intake ADD COLUMN content_sha256 TEXT")
    # project_documents comes from the #229 schema; on a DB without it (bare test
    # fixtures) the columns arrive when that migration runs and this one re-runs.
    has_docs = (bool(conn.execute("SELECT 1 FROM information_schema.tables WHERE table_schema='public' "
                                  "AND table_name='project_documents'").fetchone())
                if db_layer.is_postgres() else
                bool(conn.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='project_documents'").fetchone()))
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS project_doc_suggest_dismissed ("
        f"  {pk},"
        f"  project_code     TEXT NOT NULL,"
        f"  suggestion_key   TEXT NOT NULL,"
        f"  dismissed_by_uid INTEGER,"
        f"  dismissed_at     TEXT NOT NULL,"
        f"  UNIQUE(project_code, suggestion_key)"
        f")")
    for col in (("type_key", "ai_extract", "party", "party_name") if has_docs else ()):
        if not _column_exists(conn, "project_documents", col):
            conn.execute(f"ALTER TABLE project_documents ADD COLUMN {col} TEXT")
    conn.commit()


PARTIES = ("company", "subcontractor", "owner", "other")
PARTY_NAME_MAX = 120


def clean_party(party, name):
    """(party, party_name) normalized. Unknown party -> (None, None); 'company' keeps no
    name (it is always us); a name is only kept for subcontractor / owner / other."""
    p = str(party or "").strip().lower()
    if p not in PARTIES:
        return None, None
    n = " ".join(str(name or "").split())[:PARTY_NAME_MAX] or None
    return p, (None if p == "company" else n)


def same_party(a_party, a_name, b_party, b_name) -> bool:
    """Two records belong to the same party (no party = our company)."""
    ap, bp = a_party or "company", b_party or "company"
    if ap != bp:
        return False
    return ap == "company" or (a_name or "").strip().lower() == (b_name or "").strip().lower()


def intake_public(row) -> dict:
    """Path-safe shape for the review card — NO file_path."""
    try:
        sug = json.loads(row["suggestion_json"]) if row["suggestion_json"] else None
    except (TypeError, ValueError):
        sug = None
    return {
        "id": row["id"], "project_code": row["project_code"], "file_name": row["file_name"],
        "file_size": row["file_size"], "mime": row["mime"], "doc_type": row["doc_type"],
        "status": row["status"], "error": row["error"], "suggestion": sug,
        "created_at": row["created_at"], "file_url": f"/api/documents/intake/{row['id']}/file",
    }


def extract_for_storage(suggestion, set_by: str) -> str | None:
    """What is kept on the filed document from Claude's read (JSON text, or None)."""
    if not suggestion:
        return None
    keep = {k: suggestion.get(k) for k in ("summary", "key_facts", "fields", "confidence", "model", "type_key",
                                           "related")}
    keep["ai_type_key"] = keep.pop("type_key")
    keep["set_by"] = set_by
    return json.dumps(keep, ensure_ascii=False)


def doc_ai_public(d) -> dict | None:
    """The stored read for a filed document's payload (summary + all fields)."""
    raw = d.get("ai_extract") if hasattr(d, "get") else None
    if not raw:
        return None
    try:
        a = json.loads(raw)
    except (TypeError, ValueError):
        return None
    return {"summary": a.get("summary"), "key_facts": a.get("key_facts") or [],
            "fields": a.get("fields") or [], "related": a.get("related") or [], "set_by": a.get("set_by")}


def type_label(key) -> str | None:
    t = doc_types.get(key)
    return t["label"] if t else None
