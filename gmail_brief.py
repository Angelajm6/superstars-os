log = logging.getLogger("ssc.gmail_brief")

OFFICE_ROLES = ("admin", "c_suite")
EASTERN = ZoneInfo("America/New_York")
READY_TIMES = ("06:30", "07:00", "07:30", "08:00")
DAYS = ("weekdays", "daily")
GROUPS = ("decide", "approve", "money", "dead", "wait")
GROUP_NAMES = {"decide": "Decide", "approve": "Approve / sign", "money": "Money", "dead": "Deadlines"}
KIND_GROUP = {"payment": "money", "proposal_reply": "approve", "bid_invitation": "dead"}
OPEN = ("open",)
MAX_ITEMS = 40

BRIEF_SCHEMA = {"type": "object", "additionalProperties": False, "required": ["items"], "properties": {"items": {
    "type": "array", "items": {"type": "object", "additionalProperties": False, "required": ["n", "group", "line", "due"],
                               "properties": {"n": {"type": "integer"}, "group": {"type": "string", "enum": list(GROUP_NAMES)},
                                              "line": {"type": "string"}, "due": {"type": "string"}}}}}}


# ------------------------------------------------------------------ schema
def ensure(conn) -> None:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute("CREATE TABLE IF NOT EXISTS mail_brief_pref (user_id INTEGER PRIMARY KEY, enabled INTEGER NOT NULL DEFAULT 0, "
                 "ready_at TEXT, days TEXT, updated_at TEXT)")
    conn.execute(f"CREATE TABLE IF NOT EXISTS mail_brief ({pk}, user_id INTEGER NOT NULL, owner_user_id INTEGER, "
                 "brief_date TEXT NOT NULL, since_at TEXT, created_at TEXT NOT NULL, fyi INTEGER NOT NULL DEFAULT 0, "
                 "sent_at TEXT, sent_count INTEGER)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_mail_brief_day ON mail_brief(user_id, brief_date)")
    # state: open · tomorrow (held one brief) · removed · answered · carried (moved into a later brief)
    conn.execute(f"CREATE TABLE IF NOT EXISTS mail_brief_item ({pk}, brief_id INTEGER NOT NULL, user_id INTEGER NOT NULL, "
                 "message_id INTEGER, thread_key TEXT, grp TEXT NOT NULL, line_enc TEXT, code TEXT, from_enc TEXT, "
                 "due_enc TEXT, note_enc TEXT, received_at TEXT, first_in TEXT, pos INTEGER NOT NULL DEFAULT 0, "
                 "state TEXT NOT NULL DEFAULT 'open', updated_at TEXT)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_mail_brief_item ON mail_brief_item(brief_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_mail_brief_item_thread ON mail_brief_item(user_id, thread_key)")
    conn.commit()


def _conn():
    return db_layer.connect(pragma_fk=True)


def now_et() -> datetime:
    """Eastern wall time, naive (the brief's clock; stored mail times are the server's local time, Eastern on Render)."""
    return datetime.now(EASTERN).replace(tzinfo=None, microsecond=0)


def _stamp(d: datetime) -> str:
    return d.isoformat(timespec="seconds")


def _one(conn, sql, params=()) -> Optional[dict]:
    r = conn.execute(sql, params).fetchone()
    return dict(r) if r else None


def _rows(conn, sql, params=()) -> list:
    return [dict(r) for r in conn.execute(sql, params).fetchall()]


def _enc(v):
    import inbox
    return inbox._enc(v)


def _dec(v) -> str:
    import inbox
    return inbox._dec(v) or ""


# ------------------------------------------------------------------ settings
def pref(conn, uid: int) -> dict:
    p = _one(conn, "SELECT * FROM mail_brief_pref WHERE user_id = ?", (uid,)) or {"enabled": 0}
    return {"enabled": bool(p.get("enabled")), "ready_at": p.get("ready_at") if p.get("ready_at") in READY_TIMES else "07:00",
            "days": p.get("days") if p.get("days") in DAYS else "weekdays"}


def save_pref(conn, uid: int, **vals) -> None:
    vals["updated_at"] = _stamp(now_et())
    if _one(conn, "SELECT user_id FROM mail_brief_pref WHERE user_id = ?", (uid,)):
        conn.execute("UPDATE mail_brief_pref SET " + ", ".join(f"{k} = ?" for k in vals) + " WHERE user_id = ?",
                     list(vals.values()) + [uid])
    else:
        cols = ["user_id"] + list(vals)
        conn.execute(f"INSERT INTO mail_brief_pref ({', '.join(cols)}) VALUES ({','.join('?' * len(cols))})", [uid] + list(vals.values()))
    conn.commit()


def _owner(conn, uid: int) -> Optional[dict]:
    import gmail_labels
    o = gmail_labels.owner_person(conn, uid)
    if not o:
        return None
    u = _one(conn, "SELECT email FROM users WHERE id = ?", (o["id"],)) or {}
    return dict(o, email=u.get("email") or "")


def _is_brief_day(p: dict, d: datetime) -> bool:
    return p["days"] == "daily" or d.weekday() < 5


def _ready(p: dict, d: datetime) -> datetime:
    h, m = (int(x) for x in p["ready_at"].split(":"))
    return d.replace(hour=h, minute=m, second=0, microsecond=0)


def _previous_ready(p: dict, now: datetime) -> datetime:
    d = now - timedelta(days=1)
    for _ in range(7):
        if _is_brief_day(p, d):
            break
        d -= timedelta(days=1)
    return _ready(p, d)


# ------------------------------------------------------------------ building a brief
def _code(conn, m: dict) -> str:
    if m.get("project_code"):
        return m["project_code"]
    if m.get("proposal_id"):
        r = _one(conn, "SELECT number FROM proposal WHERE id = ?", (m["proposal_id"],))
        if r and r.get("number"):
            return str(r["number"])
    if m.get("estimate_id"):
        r = _one(conn, "SELECT code FROM estimate WHERE id = ?", (m["estimate_id"],))
        if r and r.get("code"):
            return str(r["code"])
    import gmail_labels
    return gmail_labels.KIND_LABELS.get(m.get("kind") or "", "")


def _sender(frm: str) -> str:
    name, addr = parseaddr(frm or "")
    return (name or addr or "")[:80]


def brief_prompt(owner_name: str, cands: list) -> str:
    lines = []
    for i, c in enumerate(cands, 1):
        lines.append(f"{i}. kind: {c['kind'] or 'other'} | from: {c['from']} | received: {c['received_at']} | "
                     f"subject: {c['subject'][:160]} | summary: {c['summary'][:240]} | text: {c['body'][:600]}")
    return (f"You prepare the morning brief for {owner_name}, the owner of Superstars Contracting, a New York City exterior "
            "restoration contractor. Each email below needs the owner's decision, approval, signature or payment OK. For "
            "each, give: group (decide = a choice only the owner can make; approve = something to approve or sign; "
            "money = an invoice, payment or price to OK; dead = it has a deadline in the next days, like a bid due date), "
            "line (one plain sentence, at most 25 words, saying what the owner is asked; names, amounts and dates as "
            "written; no greeting), due (the deadline in a few words like \"Bids due Thu Nov 12, 2:00 PM\", or \"\" when "
            "none is written). Never invent amounts or dates. n is the email's number.\n\n" + "\n".join(lines))


def _write_lines(conn, uid: int, owner_name: str, cands: list) -> dict:
    """n -> {group, line, due}. Claude's small model when it can; the kind and the sorting summary otherwise."""
    out = {i: {"group": KIND_GROUP.get(c["kind"] or "", "decide"), "line": (c["summary"] or c["subject"])[:240], "due": ""}
           for i, c in enumerate(cands, 1)}
    if not cands:
        return out
    import assistant
    import claude_agent
    import inbox
    if assistant.unavailable_reason() or claude_agent._over_budget(conn, uid):
        return out
    try:
        fake = runtime_seams.seam("SSC_BRIEF_FAKE")
        if fake:
            got, usage, model = json.loads(fake), {"input_tokens": 900, "output_tokens": 200}, inbox.triage_model()
        else:
            import anthropic
            resp = anthropic.Anthropic().messages.create(
                model=inbox.triage_model(), max_tokens=4000, messages=[{"role": "user", "content": brief_prompt(owner_name, cands)}],
                output_config={"effort": "low", "format": {"type": "json_schema", "schema": BRIEF_SCHEMA}})
            u = resp.usage
            usage = {"input_tokens": getattr(u, "input_tokens", 0) or 0, "output_tokens": getattr(u, "output_tokens", 0) or 0}
            raw = next((b.text for b in resp.content if getattr(b, "type", "") == "text"), "{}")
            got = json.loads(re.search(r"\{.*\}", raw, re.S).group(0))
            model = getattr(resp, "model", None) or inbox.triage_model()
        now = _stamp(now_et())
        conn.execute("INSERT INTO claude_chat (user_id, surface, title, source, created_at, updated_at) VALUES (?,?,?,?,?,?)",
                     (uid, "office", "Owner brief", "brief", now, now))
        conn.commit()
        chat = _one(conn, "SELECT MAX(id) AS m FROM claude_chat WHERE user_id = ? AND source = 'brief'", (uid,))["m"]
        inbox._record_usage(conn, chat, usage, model)
        for it in got.get("items") or []:
            n = it.get("n")
            if n in out and it.get("group") in GROUP_NAMES and str(it.get("line") or "").strip():
                out[n] = {"group": it["group"], "line": str(it["line"]).strip()[:240], "due": str(it.get("due") or "").strip()[:80]}
    except Exception as e:
        try:
            conn.rollback()
        except Exception:
            pass
        log.info("owner brief user=%s lines fell back to the sorting (%s)", uid, type(e).__name__)
    return out


def _owner_wrote(conn, uid: int, thread_key: str, owner_email: str, after: str) -> bool:
    """The owner wrote in this conversation after the item was made (their reply reached this mailbox)."""
    if not owner_email or not thread_key:
        return False
    import inbox
    for r in _rows(conn, "SELECT id FROM mail_message WHERE user_id = ? AND COALESCE(thread_id, gmail_id) = ? AND received_at > ? "
                         "AND direction = 'in'", (uid, thread_key, after or "")):
        m = inbox.message(conn, r["id"])
        if (parseaddr(m["from"])[1] or "").strip().lower() == owner_email.strip().lower():
            return True
    return False


def _still_for_owner(conn, uid: int, thread_key: str) -> bool:
    return bool(_one(conn, "SELECT id FROM mail_message WHERE user_id = ? AND COALESCE(thread_id, gmail_id) = ? AND for_owner = 1 "
                           "AND trashed_at IS NULL LIMIT 1", (uid, thread_key)))


def build(conn, uid: int, now: Optional[datetime] = None) -> Optional[int]:
    """Today's brief (once a day). Returns its id, or None when there is no owner picked."""
    import gmail_labels
    import inbox
    now = now or now_et()
    owner = _owner(conn, uid)
    if not owner:
        return None
    day = now.date().isoformat()
    have = _one(conn, "SELECT id FROM mail_brief WHERE user_id = ? AND brief_date = ?", (uid, day))
    if have:
        return have["id"]
    p = pref(conn, uid)
    prev = _one(conn, "SELECT * FROM mail_brief WHERE user_id = ? ORDER BY brief_date DESC LIMIT 1", (uid,))
    since = prev["created_at"] if prev else _stamp(_previous_ready(p, now))
    stamp = _stamp(now)
    conn.execute("INSERT INTO mail_brief (user_id, owner_user_id, brief_date, since_at, created_at) VALUES (?,?,?,?,?)",
                 (uid, owner["id"], day, since, stamp))
    conn.commit()
    bid = _one(conn, "SELECT id FROM mail_brief WHERE user_id = ? AND brief_date = ?", (uid, day))["id"]
    items, pos = [], 0
    # what is still open from earlier briefs: back under "Still waiting" (held ones go back to their own group)
    taken = set()
    for it in _rows(conn, "SELECT i.*, b.sent_at FROM mail_brief_item i JOIN mail_brief b ON b.id = i.brief_id WHERE i.user_id = ? "
                          "AND i.brief_id <> ? AND i.state IN ('open', 'tomorrow') ORDER BY i.id", (uid, bid)):
        key = it["thread_key"]
        if key and (_owner_wrote(conn, uid, key, owner["email"], it["first_in"] or it["received_at"])
                    or not _still_for_owner(conn, uid, key)):
            conn.execute("UPDATE mail_brief_item SET state = 'answered', updated_at = ? WHERE id = ?", (stamp, it["id"]))
            continue
        grp = it["grp"] if it["state"] == "tomorrow" or not it["sent_at"] else "wait"
        conn.execute("UPDATE mail_brief_item SET state = 'carried', updated_at = ? WHERE id = ?", (stamp, it["id"]))
        pos += 1
        items.append((bid, uid, it["message_id"], key, grp, it["line_enc"], it["code"], it["from_enc"], it["due_enc"], it["note_enc"],
                      it["received_at"], it["first_in"] or it["received_at"], pos, "open", stamp))
        if key:
            taken.add(key)
    conn.commit()   # what was carried / closed is kept even when Claude's pass below fails
    # what got the "For" label since the last brief: one item per conversation
    cands, seen = [], set()
    for r in _rows(conn, "SELECT id, COALESCE(thread_id, gmail_id) AS tk FROM mail_message WHERE user_id = ? AND direction = 'in' "
                         "AND trashed_at IS NULL AND backfilled_at IS NULL AND for_owner = 1 AND COALESCE(business, 1) <> 0 "
                         "AND received_at >= ? AND received_at <= ? ORDER BY received_at DESC", (uid, since, stamp)):
        if r["tk"] in seen or r["tk"] in taken:
            continue
        seen.add(r["tk"])
        m = inbox.message(conn, r["id"])
        cands.append({"id": m["id"], "tk": r["tk"], "kind": m["kind"], "from": _sender(m["from"]), "received_at": m["received_at"],
                      "subject": m["subject"] or "", "summary": m["summary"] or "", "body": m["body"] or "", "code": _code(conn, m)})
        if len(cands) >= MAX_ITEMS:
            break
    lines = _write_lines(conn, uid, owner["name"], cands)
    for i, c in enumerate(cands, 1):
        w = lines[i]
        pos += 1
        items.append((bid, uid, c["id"], c["tk"], w["group"], _enc(w["line"]), c["code"], _enc(c["from"]),
                      _enc(w["due"]) if w["due"] else None, None, c["received_at"], c["received_at"], pos, "open", stamp))
    for row in items:
        conn.execute("INSERT INTO mail_brief_item (brief_id, user_id, message_id, thread_key, grp, line_enc, code, from_enc, due_enc, "
                     "note_enc, received_at, first_in, pos, state, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)", row)
    fyi = set()
    for r in _rows(conn, "SELECT COALESCE(thread_id, gmail_id) AS tk, direction, trashed_at, kind, business, for_owner, backfilled_at, "
                         "label_manual, triage_needs, needs_action, addressed FROM mail_message WHERE user_id = ? AND direction = 'in' "
                         "AND backfilled_at IS NULL AND received_at >= ? AND received_at <= ?", (uid, since, stamp)):
        if gmail_labels.app_labels(r)["fyi"]:
            fyi.add(r["tk"])
    conn.execute("UPDATE mail_brief SET fyi = ? WHERE id = ?", (len(fyi), bid))
    conn.commit()
    log.info("owner brief built user=%s brief=%s items=%s fyi=%s", uid, bid, len(items), len(fyi))
    return bid


def tick(conn, now: Optional[datetime] = None) -> int:
    """Make the briefs that are due (inbox.claude_round, every few seconds). Returns how many were made."""
    now = now or now_et()
    made = 0
    for r in _rows(conn, "SELECT p.user_id FROM mail_brief_pref p JOIN users u ON u.id = p.user_id "
                         "WHERE p.enabled = 1 AND u.role IN ('admin', 'c_suite') AND u.status = 'active'"):
        p = pref(conn, r["user_id"])
        if not _is_brief_day(p, now) or now < _ready(p, now):
            continue
        if _one(conn, "SELECT id FROM mail_brief WHERE user_id = ? AND brief_date = ?", (r["user_id"], now.date().isoformat())):
            continue
        try:
            if build(conn, r["user_id"], now):
                made += 1
        except Exception as e:
            try:
                conn.rollback()
            except Exception:
                pass
            log.warning("owner brief user=%s failed: %s", r["user_id"], type(e).__name__)
    return made


# ------------------------------------------------------------------ reading it
def _fmt_day(d: datetime) -> str:
    return d.strftime("%A, %B ") + str(d.day)


def _fmt_since(s: str) -> str:
    try:
        d = datetime.fromisoformat(s)
    except (TypeError, ValueError):
        return ""
    t = d.strftime("%I:%M %p").lstrip("0")
    return f"{d.strftime('%A')} {t}"


def _public_item(r: dict) -> dict:
    return {"id": r["id"], "group": r["grp"], "line": _dec(r["line_enc"]), "code": r["code"] or "", "from": _dec(r["from_enc"]),
            "due": _dec(r["due_enc"]), "note": _dec(r["note_enc"]), "received_at": r["received_at"], "first_in": r["first_in"],
            "message_id": r["message_id"], "state": r["state"]}


def email_text(conn, uid: int, b: dict, items: list) -> dict:
    """What the owner gets: plain, short, one line per item (the person can change it before sending)."""
    owner = _owner(conn, uid) or {"first": "", "name": "", "email": ""}
    me = _one(conn, "SELECT full_name, display_name FROM users WHERE id = ?", (uid,)) or {}
    mine = ((me.get("full_name") or me.get("display_name") or "").split() or [""])[0]
    live = [i for i in items if i["state"] == "open"]
    d = datetime.fromisoformat(b["brief_date"])
    n = len(live)
    subject = f"Today: {n} thing{'' if n == 1 else 's'} that need{'s' if n == 1 else ''} you, {d.strftime('%a %b')} {d.day}"
    out = [f"Good morning {owner['first']}," if owner["first"] else "Good morning,", "",
           "Here's what needs you today." if n else "Nothing needs you today."]
    names = dict(GROUP_NAMES, wait="Still waiting on you")
    for g in GROUPS:
        its = [i for i in live if i["group"] == g]
        if not its:
            continue
        out += ["", names[g].upper()]
        for k, i in enumerate(its, 1):
            extra = ", ".join(x for x in (i["code"], i["due"]) if x)
            out.append(f"{k}. {i['line']}" + (f" ({extra})" if extra else ""))
            if i["note"]:
                out.append(f"   Note: {i['note']}")
    if b.get("fyi"):
        out += ["", f"{b['fyi']} other email{'s were' if b['fyi'] != 1 else ' was'} FYI only. Nothing needed from you."]
    out += ["", mine]
    return {"to": owner["email"], "to_name": owner["name"], "subject": subject, "body": "\n".join(out).rstrip() + "\n"}


def view(conn, uid: int) -> dict:
    import gmail_labels
    import inbox
    p, owner, now = pref(conn, uid), _owner(conn, uid), now_et()
    link = inbox._link(conn, uid)
    out = dict(p, owner=owner and {"id": owner["id"], "name": owner["name"], "first": owner["first"]},
               label=gmail_labels.owner_label(conn, uid), ready_times=list(READY_TIMES), connected=bool(link),
               can_send=inbox.can_send(link), today=None, today_label=_fmt_day(now))
    b = _one(conn, "SELECT * FROM mail_brief WHERE user_id = ? AND brief_date = ?", (uid, now.date().isoformat()))
    if not b:
        nxt = now
        for _ in range(8):
            if _is_brief_day(p, nxt) and _ready(p, nxt) > now:
                break
            nxt = (nxt + timedelta(days=1)).replace(hour=0, minute=0)
        out["next_label"] = ("today" if nxt.date() == now.date() else nxt.strftime("%A")) + " at " + \
            _ready(p, nxt).strftime("%I:%M %p").lstrip("0")
        return out
    items = [_public_item(r) for r in _rows(conn, "SELECT * FROM mail_brief_item WHERE brief_id = ? AND state <> 'carried' "
                                                  "ORDER BY pos, id", (b["id"],))]
    out["today"] = {"id": b["id"], "date_label": _fmt_day(datetime.fromisoformat(b["brief_date"])), "since_label": _fmt_since(b["since_at"]),
                    "ready_label": datetime.fromisoformat(b["created_at"]).strftime("%I:%M %p").lstrip("0"),
                    "items": items, "fyi": b["fyi"], "sent_at": b["sent_at"], "sent_count": b["sent_count"],
                    "email": email_text(conn, uid, b, items)}
    return out


# ------------------------------------------------------------------ changing it
def act(conn, uid: int, item_id: int, action: str, note: str = "") -> Optional[dict]:
    import gmail_labels
    it = _one(conn, "SELECT * FROM mail_brief_item WHERE id = ? AND user_id = ?", (item_id, uid))
    if not it or it["state"] == "carried":
        return None
    stamp = _stamp(now_et())
    if action == "note":
        conn.execute("UPDATE mail_brief_item SET note_enc = ?, updated_at = ? WHERE id = ?",
                     (_enc(note.strip()[:300]) if note.strip() else None, stamp, item_id))
    elif action in ("tomorrow", "remove", "answered", "undo"):
        state = {"tomorrow": "tomorrow", "remove": "removed", "answered": "answered", "undo": "open"}[action]
        conn.execute("UPDATE mail_brief_item SET state = ?, updated_at = ? WHERE id = ?", (state, stamp, item_id))
        conn.commit()
        if it["message_id"] and (state in ("removed", "answered") or (state == "open" and it["state"] in ("removed", "answered"))):
            gmail_labels.set_labels(conn, uid, it["message_id"], owner=state == "open")   # "For" off (or back on Undo)
    else:
        return None
    conn.commit()
    log.info("owner brief item user=%s item=%s action=%s", uid, item_id, action)
    return _public_item(_one(conn, "SELECT * FROM mail_brief_item WHERE id = ?", (item_id,)))


def add_item(conn, uid: int, bid: int, text: str) -> Optional[dict]:
    b = _one(conn, "SELECT id FROM mail_brief WHERE id = ? AND user_id = ?", (bid, uid))
    if not b or not text.strip():
        return None
    pos = (_one(conn, "SELECT MAX(pos) AS m FROM mail_brief_item WHERE brief_id = ?", (bid,)) or {}).get("m") or 0
    stamp = _stamp(now_et())
    conn.execute("INSERT INTO mail_brief_item (brief_id, user_id, grp, line_enc, code, received_at, first_in, pos, state, updated_at) "
                 "VALUES (?,?,?,?,?,?,?,?,?,?)", (bid, uid, "decide", _enc(text.strip()[:240]), "", stamp, stamp, pos + 1, "open", stamp))
    conn.commit()
    return _public_item(_one(conn, "SELECT * FROM mail_brief_item WHERE brief_id = ? ORDER BY id DESC LIMIT 1", (bid,)))


def send(conn, uid: int, bid: int, subject: str, body: str) -> dict:
    import inbox
    b = _one(conn, "SELECT * FROM mail_brief WHERE id = ? AND user_id = ?", (bid, uid))
    if not b:
        raise LookupError("not found")
    owner = _owner(conn, uid)
    if not owner or not owner["email"]:
        raise ValueError("Pick who gets the brief first (Settings > Account > Email labels)")
    if not inbox.can_send(inbox._link(conn, uid)):
        raise ValueError("Connect Gmail again so the app may send from your Gmail")
    inbox.compose(conn, uid, owner["email"], "", subject.strip()[:200], body)
    n = conn.execute("SELECT COUNT(*) FROM mail_brief_item WHERE brief_id = ? AND state = 'open'", (bid,)).fetchone()[0]
    conn.execute("UPDATE mail_brief SET sent_at = ?, sent_count = ? WHERE id = ?", (_stamp(now_et()), n, bid))
    conn.commit()
    log.info("owner brief sent user=%s brief=%s items=%s", uid, bid, n)
    return {"sent": True}


# ------------------------------------------------------------------ the bell
def bell_items(conn, uid: int, since: str) -> list:
    import activity_feed
    out = []
    for b in _rows(conn, "SELECT b.id, b.created_at, b.sent_at, (SELECT COUNT(*) FROM mail_brief_item i WHERE i.brief_id = b.id "
                         "AND i.state = 'open') AS n FROM mail_brief b WHERE b.user_id = ? AND b.created_at >= ? ORDER BY b.id DESC LIMIT 5",
                     (uid, since)):
        if b["sent_at"]:
            continue
        o = _owner(conn, uid)
        who = o["first"] if o else "the owner"
        sub = f"{b['n']} thing{'s' if b['n'] != 1 else ''} for {who}" if b["n"] else f"Nothing for {who} today"
        out.append(activity_feed._item(f"brief:{b['id']}", "brief", "doc", f"{who}'s brief is ready", sub, b["created_at"],
                                       "/company#inbox/brief", banner=True, open_label="Open brief"))
    return out


# ------------------------------------------------------------------ routes
def _uid() -> int:
    return (current_user() or {}).get("id")


def _with(fn):
    conn = _conn()
    try:
        return fn(conn)
    finally:
        conn.close()


@requires_role(*OFFICE_ROLES)
def _api_get():
    return _with(lambda conn: jsonify({"data": view(conn, _uid())}))


@requires_role(*OFFICE_ROLES)
def _api_settings():
    uid, d = _uid(), request.get_json(silent=True) or {}

    def run(conn):
        vals = {}
        if "ready_at" in d:
            if d["ready_at"] not in READY_TIMES:
                return jsonify({"error": "Pick a time from the list."}), 400
            vals["ready_at"] = d["ready_at"]
        if "days" in d:
            if d["days"] not in DAYS:
                return jsonify({"error": "Pick weekdays or every day."}), 400
            vals["days"] = d["days"]
        if "enabled" in d:
            on = d.get("enabled") not in (False, "false", 0, None)
            if on and not _owner(conn, uid):
                return jsonify({"error": "Pick who gets the “For” label first."}), 409
            vals["enabled"] = 1 if on else 0
        if vals:
            save_pref(conn, uid, **vals)
        return jsonify({"data": view(conn, uid)})
    return _with(run)


@requires_role(*OFFICE_ROLES)
def _api_build():
    uid = _uid()

    def run(conn):
        if not _owner(conn, uid):
            return jsonify({"error": "Pick who gets the “For” label first."}), 409
        build(conn, uid)
        return jsonify({"data": view(conn, uid)})
    return _with(run)


@requires_role(*OFFICE_ROLES)
def _api_item(item_id):
    uid, d = _uid(), request.get_json(silent=True) or {}

    def run(conn):
        got = act(conn, uid, item_id, str(d.get("action") or ""), str(d.get("note") or ""))
        return (jsonify({"data": got}) if got else (jsonify({"error": "not found"}), 404))
    return _with(run)


@requires_role(*OFFICE_ROLES)
def _api_add(bid):
    uid, d = _uid(), request.get_json(silent=True) or {}
    if not str(d.get("text") or "").strip():
        return jsonify({"error": "Write what the item is about."}), 400

    def run(conn):
        got = add_item(conn, uid, bid, str(d["text"]))
        return (jsonify({"data": got}) if got else (jsonify({"error": "not found"}), 404))
    return _with(run)


@requires_role(*OFFICE_ROLES)
def _api_send(bid):
    uid, d = _uid(), request.get_json(silent=True) or {}
    if not str(d.get("body") or "").strip() or not str(d.get("subject") or "").strip():
        return jsonify({"error": "The subject and the message can't be empty."}), 400

    def run(conn):
        try:
            send(conn, uid, bid, str(d["subject"]), str(d["body"]))
        except LookupError:
            return jsonify({"error": "not found"}), 404
        except ValueError as e:
            return jsonify({"error": str(e)}), 409
        return jsonify({"data": view(conn, uid)})
    return _with(run)


def register(app) -> None:
    conn = _conn()
    try:
        ensure(conn)
    except Exception as e:
        log.warning("owner brief schema ensure skipped: %s", type(e).__name__)
        try:
            conn.rollback()
        except Exception:
            pass
    finally:
        conn.close()
    app.add_url_rule("/api/inbox/brief", "inbox_brief", _api_get, methods=["GET"])
    app.add_url_rule("/api/inbox/brief/settings", "inbox_brief_settings", _api_settings, methods=["PUT"])
    app.add_url_rule("/api/inbox/brief/build", "inbox_brief_build", _api_build, methods=["POST"])
    app.add_url_rule("/api/inbox/brief/items/<int:item_id>", "inbox_brief_item", _api_item, methods=["POST"])
    app.add_url_rule("/api/inbox/brief/<int:bid>/items", "inbox_brief_add", _api_add, methods=["POST"])
    app.add_url_rule("/api/inbox/brief/<int:bid>/send", "inbox_brief_send", _api_send, methods=["POST"])
