"""The owner's daily brief (stage 2 of the prototype accepted 2026-11-09: https://claude.ai/artifact/AD3UWCWVrSTcdKFN1grgyk).

Every morning (7:00 AM Eastern on weekdays by default) the person's Inbox gathers what got the "For <owner>" label since
the last brief into one short list, grouped Decide · Approve / sign · Money · Deadlines · Still waiting on <owner>. The
person reviews it in Inbox > Brief (note, hold for tomorrow, remove, "<owner> answered", add their own item), then sends
it to the owner from their own Gmail. Nothing is ever sent by itself. The owner gets no login view (later, not now).

  * Items: one per conversation. Claude's small model writes the line, the group and any deadline (one call per brief,
    counted toward the Claude limit); without Claude, the kind decides the group and the sorting summary is the line.
  * What is still open next morning comes back under "Still waiting on <owner>"; "Tomorrow" holds an item one brief.
    An item closes itself when the owner writes in the conversation.
  * "Remove" and "<owner> answered" take the "For" label off the conversation (app + Gmail); Undo puts it back.
  * FYI email is only counted. Email that came in through "Sort my last 90 days" is never in a brief.
  * The brief's text (lines, notes, senders) is encrypted at rest; logs carry ids and counts only.

  GET  /api/inbox/brief                     settings + today's brief (or when it will be ready)
  PUT  /api/inbox/brief/settings            {enabled?, ready_at?, days?}
  POST /api/inbox/brief/build               make today's brief now (when there is none yet)
  POST /api/inbox/brief/items/<id>          {action: note|tomorrow|remove|answered|undo, note?}
  POST /api/inbox/brief/<id>/items          {text}: an item of the person's own
  POST /api/inbox/brief/<id>/send           {subject, body}: from the person's Gmail to the owner
"""
from __future__ import annotations

import json
import logging
