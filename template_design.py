"""Company → Templates → Improve design (2026-10-28): redraw a template in the house style.

Step 3 of the accepted prototype (https://claude.ai/artifact/JxTQdUZxuX2JMCcHEa2pDx). Claude reads the
template and writes its CONTENT as blocks (template_layout.py); the house style draws it, so every
redesigned template looks the same. The person compares current and proposed, asks for edits (each edit
is a new draft), and approves one: it becomes the template's next version (the old one stays in History)
and the first approval sets the house style.

  company_template_design   id, template_id, draft_no, status (drafting | ready | failed | approved | discarded),
                            content_json, changes_json, instruction, error, model, new_template_id,
                            created_by, created_at, updated_at
  company_template          + layout_json (the approved content; step 2 fills its fields for a job)
  app_settings              template_house_style = {"layout": LAYOUT_VERSION, "set_at", "set_by"}

A draft runs in a background thread (a long template takes a minute); the page polls the designs list.
A draft still drafting after STUCK_MINUTES shows as failed. Test seam: TEMPLATE_DESIGN_FAKE (planted JSON).
"""
