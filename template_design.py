_LOCK = threading.Lock()


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def _err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


def _wrap(data, **meta):
    resp = jsonify({"data": data, "meta": dict(generated_at=_now(), **meta)})
    resp.headers["Cache-Control"] = "no-store"
    return resp


def _uid():
    u = current_user()
    return u["id"] if u else None


def _clip(s, n=TEXT_MAX) -> str:
    return str(s or "").strip()[:n]


# ---------------------------------------------------------------- schema
def _has_column(conn, table: str, column: str) -> bool:
    if db_layer.is_postgres():
        return bool(conn.execute("SELECT 1 AS x FROM information_schema.columns WHERE table_name = ? AND column_name = ?",
                                 (table, column)).fetchone())
    return any(r["name"] == column for r in conn.execute(f"PRAGMA table_info({table})").fetchall())


def ensure_schema(conn) -> None:
    """Idempotent on both backends; called from company_templates.ensure_schema."""
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS company_template_design ("
        f"  {pk},"
        f"  template_id      INTEGER NOT NULL,"
        f"  draft_no         INTEGER NOT NULL DEFAULT 1,"
        f"  status           TEXT NOT NULL DEFAULT 'drafting',"
        f"  content_json     TEXT,"
        f"  changes_json     TEXT,"
        f"  instruction      TEXT,"
        f"  error            TEXT,"
        f"  model            TEXT,"
        f"  new_template_id  INTEGER,"
        f"  created_by       INTEGER,"
        f"  created_at       TEXT NOT NULL,"
        f"  updated_at       TEXT NOT NULL"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_company_template_design_tpl ON company_template_design(template_id, id)")
    if not _has_column(conn, "company_template", "layout_json"):
        conn.execute("ALTER TABLE company_template ADD COLUMN layout_json TEXT")
    conn.commit()


# ---------------------------------------------------------------- house style
def house_style(conn) -> Optional[dict]:
    r = _one(conn.execute("SELECT value FROM app_settings WHERE key = ?", (HOUSE_KEY,)))
    try:
        v = json.loads(r["value"]) if r and r.get("value") else None
    except ValueError:
        return None
    return v if isinstance(v, dict) else None


def _set_house_style(conn, uid) -> dict:
    name = None
    if uid:
        u = _one(conn.execute("SELECT full_name FROM users WHERE id = ?", (uid,)))
        name = (u or {}).get("full_name")
    v = {"layout": TL.LAYOUT_VERSION, "set_at": _now(), "set_by": name}
    conn.execute("DELETE FROM app_settings WHERE key = ?", (HOUSE_KEY,))
    conn.execute("INSERT INTO app_settings (key, value, updated_at) VALUES (?,?,?)", (HOUSE_KEY, json.dumps(v), _now()))
    return v


def house_public(conn) -> dict:
    import company_brand
    facts = company_brand.letterhead(conn)
    return {"set": house_style(conn), **TL.STYLE_SUMMARY, "has_logo": bool(company_brand.logo(conn)),
            "letterhead_lines": company_brand.letterhead_lines(facts)}


# ---------------------------------------------------------------- Claude's draft
_FIELD = {"type": "object", "additionalProperties": False,
          "properties": {"label": {"type": "string"}, "source": {"type": "string"}, "wide": {"type": "boolean"}},
          "required": ["label", "source", "wide"]}
_BLOCK = {"type": "object", "additionalProperties": False,
          "properties": {"kind": {"type": "string", "enum": list(TL.KINDS)}, "text": {"type": "string"},
                         "fields": {"type": "array", "items": _FIELD},
                         "columns": {"type": "array", "items": {"type": "string"}},
                         "rows": {"type": "integer"},
                         "data": {"type": "array", "items": {"type": "array", "items": {"type": "string"}}},
                         "items": {"type": "array", "items": {"type": "string"}},
                         "signers": {"type": "array", "items": {"type": "string"}}},
          "required": ["kind", "text", "fields", "columns", "rows", "data", "items", "signers"]}
DESIGN_SCHEMA = {"type": "object", "additionalProperties": False,
                 "properties": {"title": {"type": "string"}, "subtitle": {"type": "string"},
                                "blocks": {"type": "array", "items": _BLOCK},
                                "changes": {"type": "array", "items": {"type": "string"}}},
                 "required": ["title", "subtitle", "blocks", "changes"]}


def build_prompt(instruction: Optional[str] = None, previous: Optional[dict] = None) -> str:
    sources = "\n".join(f"  {k}: {v}" for k, v in ct.FIELD_SOURCES)
    base = f"""This file is a TEMPLATE from Superstars Contracting (NYC exterior restoration, rope access,
parking garages, interiors). The company is redrawing all its templates in one house style. You write
only the CONTENT, as blocks; the app draws the letterhead, logo, colors, fonts and footer itself.

Blocks (every block has every key; leave the ones its kind doesn't use empty):
  heading    text = a section heading (keep the template's own numbering, e.g. "2. Fall protection")
  paragraph  text = running text (line breaks kept)
  note       text = a short callout the template stresses (warnings, "keep on site")
  fields     fields = the blanks to fill in, each {{label, source, wide}}. Blank lines and "Name: ____"
             become fields. source = the job fact that fills it, one of
{sources}
             wide = true for long answers (addresses, descriptions)
  table      columns = header labels; data = rows already printed on the template; rows = total rows
             to draw (printed + blank)
  checklist  items = each line with a tick box
  signatures signers = each role that signs (a line + date is drawn for each)

Rules:
- Keep EVERY word of the template, in order. Do not summarise, shorten, reword or add content.
  Fix only obvious typos.
- Leave out the company name, logo, address, phone, license and page numbers: the house style prints them.
- title = the template's name; subtitle = a short qualifier if it has one (e.g. "Rope access"), else "".
- changes = up to five short plain sentences on what the new layout does differently
  (e.g. "Blank lines became a labelled box of fields."). Write them for the office manager."""
    if instruction:
        base += f"""

This is a REVISION. The current draft is below as JSON. Apply the person's request and keep everything
else exactly as it is. The request may change wording only where it asks to.
Person's request: {instruction}
changes = what you changed for this request.

Current draft:
{json.dumps(previous or {}, ensure_ascii=False)}"""
    return base + "\n\nReturn ONLY the structured JSON."


def call_model(data: bytes, filename: str, instruction=None, previous=None) -> dict:
    """ONE streamed API call (a long template can need a long answer). RuntimeError on any failure."""
    if not os.environ.get("ANTHROPIC_API_KEY"):
        raise RuntimeError("unavailable")
    import anthropic

    import ai_models
    import document_scanner
    model = os.environ.get("TEMPLATE_DESIGN_MODEL") or document_scanner.MODEL
    content = [ct._spec(data, filename), {"type": "text", "text": build_prompt(instruction, previous)}]
    try:
        with anthropic.Anthropic().messages.stream(
                model=model, max_tokens=32000, **ai_models.thinking_off(model),
                output_config={"effort": "low", "format": {"type": "json_schema", "schema": DESIGN_SCHEMA}},
                messages=[{"role": "user", "content": content}]) as stream:
            msg = stream.get_final_message()
    except Exception as e:  # anthropic.APIError + transport errors; never log the file
        raise RuntimeError(f"design draft failed: {type(e).__name__}")
    if msg.stop_reason == "refusal":
        raise RuntimeError("design draft refused")
    if msg.stop_reason == "max_tokens":
        raise RuntimeError("too long")
    text = next((b.text for b in msg.content if getattr(b, "type", "") == "text"), "")
    try:
        raw = json.loads(text)
    except ValueError:
        raise RuntimeError("design draft was not JSON")
    raw["_model"] = model
    return raw


def process_design(raw) -> tuple:
    """Pure: (content, changes). Unknown kinds and empty blocks are dropped; every list is capped."""
    raw = raw if isinstance(raw, dict) else {}
    blocks = []
    for b in (raw.get("blocks") or [])[:BLOCKS_MAX]:
        if not isinstance(b, dict) or b.get("kind") not in TL.KINDS:
            continue
        k, out = b["kind"], {"kind": b["kind"]}
        if k in ("heading", "paragraph", "note"):
            out["text"] = _clip(b.get("text"))
            if not out["text"]:
                continue
        elif k == "fields":
            fs = []
            for f in (b.get("fields") or [])[:LIST_MAX]:
                if isinstance(f, dict) and _clip(f.get("label"), 80):
                    src = str(f.get("source") or "").strip()
                    fs.append({"label": _clip(f.get("label"), 80),
                               "source": src if src in ct.FIELD_SOURCE_KEYS else "other", "wide": bool(f.get("wide"))})
            if not fs:
                continue
            out["fields"] = fs
        elif k == "table":
            cols = [_clip(c, 60) for c in (b.get("columns") or [])[:COLS_MAX]]
            if not any(cols):
                continue
            data = [[_clip(c, 200) for c in (r or [])[:len(cols)]] for r in (b.get("data") or [])[:ROWS_MAX] if isinstance(r, list)]
            try:
                rows = int(b.get("rows") or 0)
            except (TypeError, ValueError):
                rows = 0
            out.update(columns=cols, data=data, rows=max(len(data), min(ROWS_MAX, rows), 1 if not data else 0))
        else:   # checklist / signatures
            key = "items" if k == "checklist" else "signers"
            vals = [_clip(x, 300) for x in (b.get(key) or [])[:LIST_MAX] if _clip(x, 300)]
            if not vals:
                continue
            out[key] = vals
        blocks.append(out)
    content = {"title": _clip(raw.get("title"), ct.TITLE_MAX), "subtitle": _clip(raw.get("subtitle"), 120), "blocks": blocks}
    changes = [_clip(c, 200) for c in (raw.get("changes") or []) if _clip(c, 200)][:CHANGES_MAX]
    return content, changes


def content_fields(content: dict) -> list:
    """The blanks of a redesigned template, for company_template.fields_json (step 2 fills them)."""
    out, seen = [], set()
    for b in content.get("blocks") or []:
        for f in b.get("fields") or []:
            if f["label"].lower() not in seen:
                seen.add(f["label"].lower())
                out.append({"label": f["label"], "source": f["source"]})
    return out


# ---------------------------------------------------------------- drafts
def _stuck(updated_at) -> bool:
    try:
        return datetime.fromisoformat(str(updated_at)) < datetime.now() - timedelta(minutes=STUCK_MINUTES)
    except (TypeError, ValueError):
        return False


def _design_public(r: dict) -> dict:
    stuck = r["status"] == "drafting" and _stuck(r.get("updated_at"))
    status = "failed" if stuck else r["status"]
    return {"id": r["id"], "template_id": r["template_id"], "draft_no": r["draft_no"], "status": status,
            "changes": ct._loads(r.get("changes_json"), []), "instruction": r.get("instruction"),
            "error": "Claude took too long. Try again." if stuck else r.get("error"),
            "new_template_id": r.get("new_template_id"), "created_at": r.get("created_at")}


def list_designs(conn, template_id: int) -> list:
    rows = conn.execute("SELECT * FROM company_template_design WHERE template_id = ? AND status != 'discarded' "
                        "ORDER BY id DESC", (template_id,)).fetchall()
    return [_design_public(dict(r)) for r in rows]


def _template_row(conn, template_id: int) -> Optional[dict]:
    return _one(conn.execute("SELECT * FROM company_template WHERE id = ? AND archived_at IS NULL", (template_id,)))


def start(conn, template_id: int, uid, *, instruction: Optional[str] = None, from_id: Optional[int] = None,
          background: bool = True) -> tuple:
    """(design | None, error, http code). A first draft, or an edit of draft `from_id`."""
    t = _template_row(conn, template_id)
    if not t or t["state"] != "filed" or t["superseded"]:
        return None, "template not found", 404
    if not os.environ.get("ANTHROPIC_API_KEY") and not runtime_seams.seam("TEMPLATE_DESIGN_FAKE"):
        return None, "Claude can't redraw templates right now (AI is off).", 503
    instruction = " ".join(str(instruction or "").split())[:INSTRUCTION_MAX] or None
    previous = None
    if from_id is not None or instruction:
        if not instruction:
            return None, "say what to change", 400
        src = _one(conn.execute("SELECT * FROM company_template_design WHERE id = ? AND template_id = ?",
                                (from_id, template_id))) if from_id is not None else None
        if not src or src["status"] not in ("ready", "approved") or not src.get("content_json"):
            return None, "pick a finished draft to change", 400
        previous = ct._loads(src["content_json"], {})
    with _LOCK:
        busy = _one(conn.execute("SELECT id, updated_at FROM company_template_design WHERE template_id = ? AND status = 'drafting' "
                                 "ORDER BY id DESC LIMIT 1", (template_id,)))
        if busy and not _stuck(busy["updated_at"]):
            return None, "Claude is still drawing the last version", 409
        n = _one(conn.execute("SELECT COALESCE(MAX(draft_no), 0) AS n FROM company_template_design WHERE template_id = ?",
                              (template_id,)))["n"] + 1
        now = _now()
        cur = conn.execute("INSERT INTO company_template_design (template_id, draft_no, status, instruction, created_by, "
                           "created_at, updated_at) VALUES (?,?,?,?,?,?,?)",
                           (template_id, n, "drafting", instruction, uid, now, now))
        did = cur.lastrowid
        conn.commit()
    args = (did, t["file_path"], t["file_name"], instruction, previous)
    if background:
        threading.Thread(target=_draft_job, args=args, daemon=True, name=f"template-design-{did}").start()
    else:
        _draft_job(*args)
    return get_design(conn, did), None, 202


def _draft_job(did, file_path, file_name, instruction, previous) -> None:
    status, content, changes, error, model = "failed", None, [], None, None
    try:
        fake = runtime_seams.seam("TEMPLATE_DESIGN_FAKE")
        if fake:
            with open(fake, encoding="utf-8") as fh:
                raw = json.load(fh)
        else:
            data = ssc_paths.resolve_data_path(file_path).read_bytes()
            if len(data) > ct.READ_MAX_BYTES:
                raise RuntimeError("too large")
            raw = call_model(data, file_name, instruction, previous)
        content, changes = process_design(raw)
        if not content["blocks"]:
            raise RuntimeError("empty draft")
        status, model = "ready", raw.get("_model") or ("fake" if fake else None)
    except Exception as e:
        reason = str(e)
        log.error("template design draft %s failed: %s", did, type(e).__name__)
        error = ("This template is too long for one redraw. Split it and try again." if reason in ("too long", "too large")
                 else "Claude couldn't redraw this one. Try again.")
    conn = db_layer.connect()
    try:
        conn.execute("UPDATE company_template_design SET status = ?, content_json = ?, changes_json = ?, error = ?, model = ?, "
                     "updated_at = ? WHERE id = ? AND status = 'drafting'",
                     (status, json.dumps(content, ensure_ascii=False) if content else None,
                      json.dumps(changes, ensure_ascii=False), error, model, _now(), did))
        conn.commit()
    finally:
        conn.close()


def get_design(conn, did: int) -> Optional[dict]:
    r = _one(conn.execute("SELECT * FROM company_template_design WHERE id = ?", (did,)))
    return _design_public(r) if r else None


def _render_args(conn, t: dict) -> dict:
    import company_brand
    return {"folder_name": ct.FOLDER_NAMES.get(t["folder"], ""), "revision": datetime.now().strftime("%Y-%m"),
            "logo_uri": company_brand.logo_data_uri(conn), "letterhead": company_brand.letterhead(conn)}


def preview(conn, did: int) -> Optional[dict]:
    r = _one(conn.execute("SELECT d.*, t.folder FROM company_template_design d JOIN company_template t ON t.id = d.template_id "
                          "WHERE d.id = ?", (did,)))
    if not r or not r.get("content_json"):
        return None
    css, body = TL.render(ct._loads(r["content_json"], {}), mode="page", **_render_args(conn, r))
    return {"css": css, "html": body}


def pdf_bytes(html_doc: str) -> bytes:
    """The house-style PDF (headless Chromium on Render, pdf_export). Tests replace this."""
    import pdf_export
    with tempfile.TemporaryDirectory() as td:
        hp, pp = Path(td) / "template.html", Path(td) / "template.pdf"
        hp.write_text(html_doc, encoding="utf-8")
        try:
            res = pdf_export.render_html_to_pdf(hp, pp, timeout_sec=90)
        except Exception as e:   # no browser on this host (PDFExportError) and the like
            log.error("template PDF render failed: %s", type(e).__name__)
            res = {}
        if not res.get("ok"):
            raise ValueError("The PDF couldn't be made right now. Try again in a minute.")
        return pp.read_bytes()


def approve(conn, did: int, uid) -> tuple:
    """(new template | None, error, code). The draft becomes the template's next version."""
    d = _one(conn.execute("SELECT * FROM company_template_design WHERE id = ?", (did,)))
    if not d:
        return None, "draft not found", 404
    if d["status"] != "ready":
        return None, "only a finished draft can be approved", 400
    t = _template_row(conn, d["template_id"])
    if not t or t["superseded"]:
        return None, "this template already has a newer version", 409
    content = ct._loads(d["content_json"], {})
    doc = TL.render(content, mode="pdf", **_render_args(conn, t))
    pdf = pdf_bytes(doc)   # ValueError -> the route says so
    ct._FILE_BASE.mkdir(parents=True, exist_ok=True)
    fpath = ct._FILE_BASE / (uuid.uuid4().hex + ".pdf")
    fpath.write_bytes(pdf)
    title = content.get("title") or t["title"]
    version = int(t.get("version") or 1) + 1
    now = _now()
    try:
        cur = conn.execute(
            "INSERT INTO company_template (title, folder, type_key, offer_json, summary, fields_json, design_verdict, "
            "design_notes, state, read_status, model, file_name, file_path, file_size, mime, content_sha256, version, "
            "supersedes_id, created_by, created_at, updated_at, filed_at, layout_json) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (title, t["folder"], t.get("type_key"), t.get("offer_json"), t.get("summary"),
             json.dumps(content_fields(content), ensure_ascii=False), "ok", "[]", "filed", "ready", d.get("model"),
             f"{title} v{version}.pdf"[:200], ssc_paths.store_rel(fpath), len(pdf), "application/pdf",
             hashlib.sha256(pdf).hexdigest(), version, t["id"], uid, now, now, now, json.dumps(content, ensure_ascii=False)))
        new_id = cur.lastrowid
        conn.execute("UPDATE company_template SET superseded = 1, updated_at = ? WHERE id = ?", (now, t["id"]))
        conn.execute("UPDATE company_template_design SET status = 'approved', new_template_id = ?, updated_at = ? WHERE id = ?",
                     (new_id, now, did))
        conn.execute("UPDATE company_template_design SET template_id = ? WHERE template_id = ?", (new_id, t["id"]))
        first = house_style(conn) is None
        if first:
            _set_house_style(conn, uid)
        conn.commit()
    except Exception:
        conn.rollback()
        fpath.unlink(missing_ok=True)
        raise
    return {"template": ct.get(conn, new_id), "house_style_set_now": first}, None, 200


def discard(conn, did: int) -> bool:
    cur = conn.execute("UPDATE company_template_design SET status = 'discarded', updated_at = ? WHERE id = ? "
                       "AND status IN ('ready', 'failed', 'drafting')", (_now(), did))
    conn.commit()
    return bool(cur.rowcount)


def history(conn, template_id: int) -> list:
    """The template and every version before it, newest first."""
    out, seen, tid = [], set(), template_id
    while tid and tid not in seen and len(out) < 50:
        seen.add(tid)
        r = _one(conn.execute(f"SELECT {ct._PUBLIC_COLS} FROM company_template WHERE id = ?", (tid,)))
        if not r:
            break
        out.append(ct.public(r))
        tid = r.get("supersedes_id")
    return out


# ---------------------------------------------------------------- routes
def register_routes(app, gate) -> None:
    def _with_conn(fn):
        conn = db_layer.connect()
        try:
            return fn(conn)
        finally:
            conn.close()

    @app.route("/api/company/portal/templates/<int:template_id>/designs", methods=["GET"])
    @gate
    def template_designs(template_id):
        def go(conn):
            t = ct.get(conn, template_id)
            if not t:
                return None
            return list_designs(conn, template_id), t, house_public(conn)
        got = _with_conn(go)
        if not got:
            return _err("template not found", 404)
        return _wrap(got[0], template=got[1], house_style=got[2])

    @app.route("/api/company/portal/templates/<int:template_id>/designs", methods=["POST"])
    @gate
    def template_design_start(template_id):
        """Claude redraws the template (the file goes to the Anthropic API, as on upload). With
        {instruction, from_id} it revises that draft instead. Returns at once; poll the list."""
        body = request.get_json(silent=True) or {}
        from_id = body.get("from_id")
        try:
            from_id = int(from_id) if from_id not in (None, "") else None
        except (TypeError, ValueError):
            return _err("pick a finished draft to change")
        d, err, code = _with_conn(lambda c: start(c, template_id, _uid(), instruction=body.get("instruction"), from_id=from_id))
        if err:
            return _err(err, code)
        return _wrap(d), code

    @app.route("/api/company/portal/templates/designs/<int:did>/preview", methods=["GET"])
    @gate
    def template_design_preview(did):
        p = _with_conn(lambda c: preview(c, did))
        if not p:
            return _err("draft not ready", 404)
        return _wrap(p)

    @app.route("/api/company/portal/templates/designs/<int:did>/approve", methods=["POST"])
    @gate
    def template_design_approve(did):
        try:
            out, err, code = _with_conn(lambda c: approve(c, did, _uid()))
        except ValueError as e:
            return _err(str(e), 503)
        if err:
            return _err(err, code)
        return _wrap(out)

    @app.route("/api/company/portal/templates/designs/<int:did>", methods=["DELETE"])
    @gate
    def template_design_discard(did):
        if not _with_conn(lambda c: discard(c, did)):
            return _err("draft not found", 404)
        return _wrap({"id": did, "discarded": True})

    @app.route("/api/company/portal/templates/<int:template_id>/history", methods=["GET"])
    @gate
    def template_history(template_id):
        rows = _with_conn(lambda c: history(c, template_id))
        if not rows:
            return _err("template not found", 404)
        return _wrap(rows)

    @app.route("/api/company/portal/templates/<int:template_id>/word", methods=["GET"])
    @gate
    def template_word(template_id):
        """A redesigned template as Word, for anyone who edits it outside the app."""
        import claude_docs
        r = _with_conn(lambda c: _one(c.execute("SELECT title, layout_json FROM company_template WHERE id = ?", (template_id,))))
        if not r or not r.get("layout_json"):
            return _err("only a redesigned template has a Word copy", 404)
        content = ct._loads(r["layout_json"], {})
        d = {"title": content.get("title") or r["title"], "html": TL.word_html(content)}
        resp = Response(claude_docs.docx_bytes(d),
                        mimetype="application/vnd.openxmlformats-officedocument.wordprocessingml.document")
        resp.headers["Content-Disposition"] = "attachment; filename*=UTF-8''" + quote(claude_docs.file_name(d, ".docx"))
        resp.headers["Cache-Control"] = "no-store"
        return resp
