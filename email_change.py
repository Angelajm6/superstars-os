"""Change a sign-in email, confirmed from the new address (accepted 2026-10-12).

Flow
----
1. ``POST   /api/account/email-change``                 {new_email, current_password} — your own
2. ``POST   /api/admin/users/<id>/email-change``        {new_email} — an admin, for someone else
3. the new address gets ``<base>/confirm-email?token=…`` (24 hours, single use)
4. ``GET    /confirm-email``                             the page with a Confirm button (public:
                                                         the token IS the credential, like /reset-password)
5. ``POST   /api/auth/email-change/confirm``             {token} — the email changes here
``GET /api/account/email-change`` shows a pending change; ``DELETE`` cancels it.

Security properties
-------------------
* Nothing changes until someone clicks the link in the NEW mailbox, so a typo or a stranger's
  address can never take over or lock out an account. An admin request works the same way.
* Your own request re-checks the current password (accounts that have one), counted against
  the same wrong-password limit as Settings > Password.
* Only a SHA-256 hash of the token is stored. One live request per account (a new one cancels
  the old); at most ``MAX_PER_HOUR`` requests per account per hour.
* The new email must not belong to another account (checked at request AND at confirm time).
* On confirm: the Google sign-in binding (google_sub) is cleared so the new address can bind its
  own Google account, Google Calendar / Gmail connections are disconnected (they must match the
  sign-in email), and the old address gets a notice. Password, tasks, role and history stay.
* Logs carry user ids only — never an email address or a token (CLAUDE.md PII rule).

Delivery uses the password-reset transports (fake-dir test seam, SendGrid, SMTP) and its
public base URL; with no transport the request returns 503 and nothing is stored.
"""
from __future__ import annotations

import hashlib
import html as html_lib
import logging
import re
import secrets
import smtplib
import ssl
from datetime import datetime, timedelta
from email.message import EmailMessage
from pathlib import Path
from typing import Optional
from urllib.parse import quote

from flask import jsonify, request, send_file

import auth
import password_reset
from auth import current_user, requires_role

log = logging.getLogger("ssc.email_change")

TTL = timedelta(hours=24)
MAX_PER_HOUR = 5
PAGE = auth.SCRIPT_DIR / "confirm_email.html"
EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
FROM_NAME = "Superstars Contracting"
INVALID = "This link is invalid, was already used, or has expired. Ask for a new one from Settings → Account."

SUBJECT_CONFIRM = "Confirm your new sign-in email"
SUBJECT_NOTICE = "Your sign-in email was changed"


# ------------------------------------------------------------------ schema
def ensure_schema(conn) -> None:
    """Idempotent. No FK on user_id (same reason as password_reset_token: a fresh database may
    create its application tables after this module boots)."""
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if auth.db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS email_change_request ("
        f"  {pk},"
        f"  user_id      INTEGER NOT NULL,"
        f"  new_email    TEXT    NOT NULL,"
        f"  token_hash   TEXT    NOT NULL UNIQUE,"
        f"  requested_by INTEGER NOT NULL,"
        f"  requested_at TEXT    NOT NULL,"
        f"  expires_at   TEXT    NOT NULL,"
        f"  used_at      TEXT,"
        f"  cancelled_at TEXT"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_email_change_user ON email_change_request(user_id, requested_at)")
    conn.commit()


# ------------------------------------------------------------------ helpers
def _hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def _clean_email(raw) -> str:
    return str(raw or "").strip().lower()


def _email_problem(conn, uid: int, current: str, new: str) -> Optional[str]:
    if not new or len(new) > 254 or not EMAIL_RE.match(new):
        return "Enter a valid email address."
    if new == (current or "").strip().lower():
        return "That is already the sign-in email."
    taken = conn.execute("SELECT id FROM users WHERE LOWER(email) = ? AND id <> ?", (new, uid)).fetchone()
    if taken:
        return "Another account already uses that email."
    return None


def _user(conn, uid: int) -> Optional[dict]:
    try:
        r = conn.execute("SELECT id, email, full_name, display_name, password_hash, force_sso, is_active, google_sub "
                         "FROM users WHERE id = ?", (uid,)).fetchone()
    except Exception:   # a database without the SSO columns yet
        conn.rollback()
        r = conn.execute("SELECT id, email, full_name, display_name, password_hash, is_active "
                         "FROM users WHERE id = ?", (uid,)).fetchone()
    return dict(r) if r else None


def _pending(conn, uid: int) -> Optional[dict]:
    r = conn.execute("SELECT new_email, expires_at, requested_by FROM email_change_request "
                     "WHERE user_id = ? AND used_at IS NULL AND cancelled_at IS NULL AND expires_at > ? "
                     "ORDER BY id DESC LIMIT 1", (uid, auth._now_iso())).fetchone()
    return {"new_email": r["new_email"], "expires_at": r["expires_at"], "by_admin": r["requested_by"] != uid} if r else None


def _recent_count(conn, uid: int) -> int:
    since = (datetime.now() - timedelta(hours=1)).isoformat(timespec="seconds")
    r = conn.execute("SELECT COUNT(1) FROM email_change_request WHERE user_id = ? AND requested_at >= ?",
                     (uid, since)).fetchone()
    return r[0] if r else 0


def _first_name(u: dict) -> str:
    name = (u.get("display_name") or u.get("full_name") or "").strip()
    return name.split()[0] if name else "there"


def _page_html(title: str, lines: list, button: Optional[tuple] = None) -> str:
    esc = html_lib.escape
    btn = (f'<p style="margin:22px 0"><a href="{esc(button[1], quote=True)}" style="display:inline-block;background:#4364DC;'
           f'color:#ffffff;text-decoration:none;font-weight:600;font-size:14px;padding:11px 20px;border-radius:10px">'
           f'{esc(button[0])}</a></p>') if button else ""
    body = "".join(f'<p style="margin:0 0 12px">{esc(t)}</p>' for t in lines)
    return ('<!doctype html><html><body style="margin:0;background:#F6F7F9;font-family:Inter,Segoe UI,Helvetica,Arial,sans-serif;'
            'color:#1B1F27"><div style="max-width:520px;margin:0 auto;padding:28px 18px"><div style="background:#ffffff;'
            'border:1px solid #E6E8EE;border-radius:14px;padding:24px 26px;font-size:14.5px;line-height:1.55">'
            '<div style="font-size:11px;letter-spacing:.12em;text-transform:uppercase;color:#868C98;margin-bottom:10px">'
            f'Superstars Contracting</div><h1 style="font-size:19px;font-weight:600;margin:0 0 14px">{esc(title)}</h1>'
            f'{body}{btn}</div></div></body></html>')


def _send(to_email: str, subject: str, text: str, html: str, cfg: dict) -> bool:
    """Same transports as password_reset._deliver. Never raises."""
    transport = cfg["transport"]
    try:
        if transport == "fake":
            out = Path(cfg["dir"])
            out.mkdir(parents=True, exist_ok=True)
            stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
            (out / f"email-change-{stamp}.eml").write_text(f"To: {to_email}\nSubject: {subject}\n\n{text}", encoding="utf-8")
            return True
        if transport == "sendgrid":
            import notifications
            sent, err = notifications._send_live(to_email, subject, text, html, from_name=FROM_NAME, track_clicks=False)
            if not sent:
                log.warning("email change mail not sent via sendgrid")
            return bool(sent)
        if transport == "smtp":
            msg = EmailMessage()
            msg["Subject"], msg["From"], msg["To"] = subject, f"{FROM_NAME} <{cfg['SSC_RESET_EMAIL_FROM']}>", to_email
            msg.set_content(text)
            msg.add_alternative(html, subtype="html")
            port = int(password_reset._env("SSC_RESET_SMTP_PORT") or "587")
            with smtplib.SMTP(cfg["SSC_RESET_SMTP_HOST"], port, timeout=12) as s:
                s.starttls(context=ssl.create_default_context())
                s.login(cfg["SSC_RESET_SMTP_USERNAME"], cfg["SSC_RESET_SMTP_PASSWORD"])
                s.send_message(msg)
            return True
    except Exception as e:  # noqa: BLE001
        log.warning("email change mail not sent via %s: %s", transport, type(e).__name__)
    return False


def _send_confirm(u: dict, new_email: str, token: str, cfg: dict, by_admin: bool) -> bool:
    url = cfg["base_url"] + "/confirm-email?token=" + quote(token, safe="")
    who = "An administrator asked" if by_admin else "You asked"
    lines = [f"Hi {_first_name(u)},",
             f"{who} to change the Superstars sign-in email from {u['email']} to this address. "
             "Click below to confirm. The link works once and expires in 24 hours.",
             "If you did not expect this, ignore this email and nothing changes."]
    text = "\n\n".join(lines[:2]) + f"\n\nConfirm: {url}\n\n" + lines[2] + "\n"
    return _send(new_email, SUBJECT_CONFIRM, text, _page_html(SUBJECT_CONFIRM, lines, ("Confirm new email", url)), cfg)


def _send_notice(old_email: str, new_email: str, name: str) -> None:
    cfg = password_reset.delivery_config()
    if not cfg or not old_email:
        return
    lines = [f"Hi {name},", f"The Superstars sign-in email for this account is now {new_email}. "
             "Your password, tasks and history did not change.",
             "If you did not make this change, contact your administrator right away."]
    _send(old_email, SUBJECT_NOTICE, "\n\n".join(lines) + "\n", _page_html(SUBJECT_NOTICE, lines), cfg)


def _start(conn, target: dict, new_email: str, requested_by: int):
    """Store a request and send the link. Returns a Flask response tuple."""
    if _recent_count(conn, target["id"]) >= MAX_PER_HOUR:
        return jsonify({"error": "Too many email change requests. Try again in an hour."}), 429
    cfg = password_reset.delivery_config()
    if cfg is None:
        return jsonify({"error": "This server cannot send email right now, so the email cannot be changed. "
                                 "Ask your administrator to check the email setup."}), 503
    token = secrets.token_urlsafe(32)
    now = auth._now_iso()
    expires = (datetime.now() + TTL).isoformat(timespec="seconds")
    conn.execute("UPDATE email_change_request SET cancelled_at = ? WHERE user_id = ? AND used_at IS NULL AND cancelled_at IS NULL",
                 (now, target["id"]))
    conn.execute("INSERT INTO email_change_request (user_id, new_email, token_hash, requested_by, requested_at, expires_at) "
                 "VALUES (?, ?, ?, ?, ?, ?)", (target["id"], new_email, _hash(token), requested_by, now, expires))
    conn.commit()
    if not _send_confirm(target, new_email, token, cfg, requested_by != target["id"]):
        conn.execute("UPDATE email_change_request SET cancelled_at = ? WHERE token_hash = ?", (auth._now_iso(), _hash(token)))
        conn.commit()
        return jsonify({"error": "The confirmation email could not be sent. Try again in a few minutes."}), 502
    log.info("email change requested user=%s by=%s", target["id"], requested_by)
    return jsonify({"data": {"pending": _pending(conn, target["id"])}}), 202


def forget_google_links(conn, uid: int) -> None:
    """Google Calendar / Gmail connections must match the sign-in email: drop them (best-effort
    revoke at Google first). Never raises."""
    try:
        import gcal_sync
        import gmail_suggest
        import secret_box
    except Exception:
        return
    for table, extra in (("google_calendar_link", ("google_calendar_event",)),
                         ("gmail_link", ("gmail_suggestion", "gmail_seen"))):
        try:
            row = conn.execute(f"SELECT refresh_token_enc FROM {table} WHERE user_id = ?", (uid,)).fetchone()
            if row and row["refresh_token_enc"] and not gcal_sync.unavailable_reason():
                try:
                    gcal_sync._http("POST", gcal_sync.REVOKE_URL, data={"token": secret_box.decrypt_text(row["refresh_token_enc"])})
                except Exception as e:
                    log.info("email change: google revoke skipped user=%s (%s)", uid, type(e).__name__)
            for t in extra + (table,):
                conn.execute(f"DELETE FROM {t} WHERE user_id = ?", (uid,))
            conn.commit()
        except Exception as e:
            log.info("email change: %s cleanup skipped user=%s (%s)", table, uid, type(e).__name__)
            try:
                conn.rollback()
            except Exception:
                pass
    for mod in (gcal_sync, gmail_suggest):
        try:
            mod._TOKENS.pop(uid, None)
        except Exception:
            pass


# ------------------------------------------------------------------ routes
@requires_role("admin", "c_suite", "pm", "super", "estimator")
def _api_request_own():
    import account
    u = current_user()
    body = request.get_json(silent=True) or {}
    new_email = _clean_email(body.get("new_email"))
    conn = auth._db()
    try:
        me = _user(conn, u["id"])
        problem = _email_problem(conn, me["id"], me["email"], new_email)
        if problem:
            return jsonify({"error": problem}), 400
        if account._has_password(me):
            if account._recent_pw_fails(me["id"]) >= account.PW_FAIL_LIMIT:
                return jsonify({"error": "Too many wrong passwords. Try again in 15 minutes."}), 429
            if not auth.verify_password(body.get("current_password") or "", me["password_hash"]):
                account._note_pw_fail(me["id"])
                return jsonify({"error": "Your current password is not right."}), 400
        return _start(conn, me, new_email, me["id"])
    finally:
        conn.close()


@requires_role("admin")
def _api_request_admin(user_id: int):
    u = current_user()
    body = request.get_json(silent=True) or {}
    new_email = _clean_email(body.get("new_email"))
    conn = auth._db()
    try:
        target = _user(conn, user_id)
        if not target:
            return jsonify({"error": "No such user."}), 404
        problem = _email_problem(conn, target["id"], target["email"], new_email)
        if problem:
            return jsonify({"error": problem}), 400
        return _start(conn, target, new_email, u["id"])
    finally:
        conn.close()


@requires_role("admin", "c_suite", "pm", "super", "estimator")
def _api_pending():
    u = current_user()
    conn = auth._db()
    try:
        return jsonify({"data": {"pending": _pending(conn, u["id"])}})
    finally:
        conn.close()


@requires_role("admin", "c_suite", "pm", "super", "estimator")
def _api_cancel():
    u = current_user()
    conn = auth._db()
    try:
        conn.execute("UPDATE email_change_request SET cancelled_at = ? WHERE user_id = ? AND used_at IS NULL AND cancelled_at IS NULL",
                     (auth._now_iso(), u["id"]))
        conn.commit()
        log.info("email change cancelled user=%s", u["id"])
        return jsonify({"data": {"pending": None}})
    finally:
        conn.close()


def _api_confirm():
    token = str((request.get_json(silent=True) or {}).get("token") or "")
    if not token:
        return jsonify({"error": INVALID, "code": "invalid_token"}), 400
    now = auth._now_iso()
    conn = auth._db()
    try:
        row = conn.execute("SELECT id, user_id, new_email FROM email_change_request WHERE token_hash = ? "
                           "AND used_at IS NULL AND cancelled_at IS NULL AND expires_at > ?", (_hash(token), now)).fetchone()
        target = row and _user(conn, row["user_id"])
        if not row or not target or not target.get("is_active"):
            return jsonify({"error": INVALID, "code": "invalid_token"}), 400
        new_email = row["new_email"]
        if conn.execute("SELECT id FROM users WHERE LOWER(email) = ? AND id <> ?", (new_email, target["id"])).fetchone():
            return jsonify({"error": "Another account already uses that email, so it cannot be changed.", "code": "taken"}), 409
        burned = conn.execute("UPDATE email_change_request SET used_at = ? WHERE id = ? AND used_at IS NULL", (now, row["id"]))
        if getattr(burned, "rowcount", 1) == 0:     # single use under concurrency
            conn.rollback()
            return jsonify({"error": INVALID, "code": "invalid_token"}), 400
        if "google_sub" in target:   # the new address binds its own Google account on first Google sign-in
            conn.execute("UPDATE users SET email = ?, google_sub = NULL WHERE id = ?", (new_email, target["id"]))
        else:
            conn.execute("UPDATE users SET email = ? WHERE id = ?", (new_email, target["id"]))
        conn.execute("UPDATE email_change_request SET cancelled_at = ? WHERE user_id = ? AND used_at IS NULL AND cancelled_at IS NULL",
                     (now, target["id"]))
        conn.commit()
        forget_google_links(conn, target["id"])
    finally:
        conn.close()
    _send_notice(target["email"], new_email, _first_name(target))
    log.info("email changed user=%s", target["id"])
    return jsonify({"data": {"ok": True, "email": new_email}})


def _page():
    resp = send_file(str(PAGE))
    resp.headers["Cache-Control"] = "no-store"
    resp.headers["Referrer-Policy"] = "no-referrer"     # the token is in the URL
    return resp


def register(app) -> None:
    conn = auth._db()
    try:
        ensure_schema(conn)
    except Exception as e:
        log.warning("email change schema ensure skipped: %s", type(e).__name__)
        try:
            conn.rollback()
        except Exception:
            pass
    finally:
        conn.close()
    app.add_url_rule("/confirm-email", "email_change_page", _page, methods=["GET"])
    app.add_url_rule("/api/account/email-change", "email_change_request_own", _api_request_own, methods=["POST"])
    app.add_url_rule("/api/account/email-change", "email_change_pending", _api_pending, methods=["GET"])
    app.add_url_rule("/api/account/email-change", "email_change_cancel", _api_cancel, methods=["DELETE"])
    app.add_url_rule("/api/admin/users/<int:user_id>/email-change", "email_change_request_admin",
                     _api_request_admin, methods=["POST"])
    app.add_url_rule("/api/auth/email-change/confirm", "email_change_confirm", _api_confirm, methods=["POST"])
