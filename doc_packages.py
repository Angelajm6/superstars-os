@requires_role(*ROLES_READ)
def _api_package(project_code):
    conn = _conn()
    try:
        d = package(conn, project_code)
        if not d:
            return _err("project not found", 404)
        resp = jsonify({"data": d})
        resp.headers["Cache-Control"] = "no-store"
        return resp
    finally:
        conn.close()


@requires_role(*ROLES_SEND)
def _api_send(project_code):
    body = request.get_json(silent=True) or {}
    conn = _conn()
    try:
        try:
            return jsonify({"data": send(conn, project_code, to_email=body.get("to_email"), to_name=body.get("to_name"),
                                         message=body.get("message"), document_ids=body.get("document_ids"),
                                         share_in_portal=bool(body.get("share_in_portal", True)), actor=_uid())}), 201
        except LookupError as e:
            return _err(str(e), 404)
        except ValueError as e:
            return _err(str(e))
        except RuntimeError as e:
            return _err(str(e), 502)
    finally:
        conn.close()


def register(app) -> None:
    conn = _conn()
    try:
        ensure_schema(conn)
        db_layer._PKMAP_CACHE.clear()
    except Exception as e:   # a fresh preprod DB may migrate later; never block boot
        log.warning("#327 document package schema ensure skipped: %s", e)
    finally:
        conn.close()
    app.add_url_rule("/api/projects/<project_code>/documents/package", "docpkg_get", _api_package, methods=["GET"])
    app.add_url_rule("/api/projects/<project_code>/documents/package/send", "docpkg_send", _api_send, methods=["POST"])
    app.add_url_rule("/d/<token>", "docpkg_public_page", _public_page, methods=["GET"])
    app.add_url_rule("/d/<token>/file/<int:doc_id>", "docpkg_public_file", _public_file, methods=["GET"])
