def _by_token(conn, token: str) -> Optional[dict]:
    if not token or len(token) < 20 or len(token) > 128:
        return None
    return _one(conn.execute("SELECT * FROM document_package WHERE token_hash = ?", (_hash(token),)))


def _pkg_docs(conn, pkg: dict) -> list:
    """The package's documents that are still deliverable: present, not superseded,
    not red-flagged (a flag pulls a document from every sent package at once)."""
    rows = _rows(conn.execute(
        "SELECT i.document_id, i.requirement_key, i.title AS item_title, d.title, d.file_name, d.doc_type, d.file_size, "
        "       d.effective_date, d.expiry_date, d.category, d.superseded "
        "FROM document_package_item i JOIN project_documents d ON d.id = i.document_id "
        "WHERE i.package_id = ? ORDER BY i.id", (pkg["id"],)))
    out = []
    for r in rows:
        if r.get("superseded") or visibility.is_flagged(conn, "document", r["document_id"]):
            continue
        out.append(r)
    return out


