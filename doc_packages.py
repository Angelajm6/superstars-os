# ---------------------------------------------------------------- helpers
def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _conn():
    return db_layer.connect()


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def _base_url() -> str:
    return (os.environ.get("APP_BASE_URL") or "http://127.0.0.1:5050").rstrip("/")


def _fmt_date(iso) -> str:
    if not iso:
        return "—"
    try:
        return date.fromisoformat(str(iso)[:10]).strftime("%B %-d, %Y")
    except ValueError:
        return str(iso)


def _uid():
    u = current_user()
    return u["id"] if u else None


def _err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


# ---------------------------------------------------------------- schema
def ensure_schema(conn) -> None:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS document_package ("
        f"  {pk},"
        f"  project_code     TEXT NOT NULL,"
        f"  client_org_id    INTEGER,"
        f"  token_hash       TEXT,"
        f"  token_expires_at TEXT,"
        f"  sent_to          TEXT,"
        f"  sent_name        TEXT,"
        f"  message          TEXT,"
        f"  sent_by          INTEGER,"
        f"  sent_at          TEXT NOT NULL,"
        f"  viewed_at        TEXT,"
        f"  view_count       INTEGER NOT NULL DEFAULT 0,"
        f"  doc_count        INTEGER NOT NULL DEFAULT 0"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_docpkg_project ON document_package(project_code, sent_at)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_docpkg_token ON document_package(token_hash)")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS document_package_item ("
        f"  {pk},"
        f"  package_id       INTEGER NOT NULL,"
        f"  document_id      INTEGER NOT NULL,"
        f"  requirement_key  TEXT,"
        f"  title            TEXT"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_docpkg_item ON document_package_item(package_id)")
    conn.commit()


# ---------------------------------------------------------------- the package
def _doc_status(d: dict, today_iso: str, d30_iso: str) -> str:
    exp = d.get("expiry_date")
    if exp and exp < today_iso:
        return "expired"
    if exp and exp <= d30_iso:
        return "expiring"
    return "on_file"


def _doc_public(d: dict, today_iso: str, d30_iso: str) -> dict:
    return {"id": d["id"], "category": d["category"], "requirement_key": d.get("requirement_key"), "title": d["title"],
            "doc_type": d.get("doc_type"), "file_name": d.get("file_name"), "file_size": d.get("file_size"),
            "effective_date": d.get("effective_date"), "expiry_date": d.get("expiry_date"),
            "uploaded_at": d.get("uploaded_at"), "status": _doc_status(d, today_iso, d30_iso),
            "file_url": f"/api/documents/{d['id']}/file"}


def package(conn, project_code: str, *, today: Optional[date] = None) -> Optional[dict]:
    today = today or date.today()
    t = today.isoformat()
    d30 = (today + timedelta(days=30)).isoformat()
    p = _one(conn.execute("SELECT project_code, name, address, status, client_org_id FROM projects WHERE project_code = ?",
                          (project_code,)))
    if not p:
        return None
    labels = {(r["category"], r["requirement_key"]): r["label"] for r in _rows(conn.execute(
        "SELECT category, requirement_key, label FROM document_requirements"))}
    docs = _rows(conn.execute("SELECT * FROM project_documents WHERE project_code = ? AND COALESCE(superseded, 0) = 0 "
                              "ORDER BY uploaded_at DESC, id DESC", (project_code,)))
    states = visibility.document_states(conn, project_code)
    by_key: dict = {}
    for d in docs:
        k = (d["category"], d.get("requirement_key"))
        if d.get("requirement_key") and k not in by_key:
            by_key[k] = d
    items, summary = [], {"required": 0, "on_file": 0, "missing": 0, "attention": 0}
    for cat, key in PACKAGE_KEYS:
        d = by_key.get((cat, key))
        summary["required"] += 1
        label = labels.get((cat, key), key)
        if d:
            pub = _doc_public(d, t, d30)
            st = states.get(d["id"], {})
            pub["shared_client"], pub["flagged"] = bool(st.get("shared_client")), bool(st.get("flagged"))
            summary["attention" if pub["status"] in ("expiring", "expired") else "on_file"] += 1
            items.append({"category": cat, "requirement_key": key, "label": label, "status": pub["status"], "doc": pub})
        else:
            summary["missing"] += 1
            items.append({"category": cat, "requirement_key": key, "label": label, "status": "missing", "doc": None})
    keyed = {d["id"] for d in by_key.values()}
    extras = []
    for d in docs:
        if d["category"] in EXTRA_CATEGORIES and d["id"] not in keyed:
            pub = _doc_public(d, t, d30)
            st = states.get(d["id"], {})
            pub["shared_client"], pub["flagged"] = bool(st.get("shared_client")), bool(st.get("flagged"))
            extras.append(pub)
    summary["pct"] = round(100 * summary["on_file"] / summary["required"]) if summary["required"] else 0
    last = _one(conn.execute("SELECT id, sent_to, sent_name, sent_at, viewed_at, view_count, doc_count, token_expires_at "
                             "FROM document_package WHERE project_code = ? ORDER BY sent_at DESC, id DESC LIMIT 1", (project_code,)))
    sends = _one(conn.execute("SELECT COUNT(1) AS n FROM document_package WHERE project_code = ?", (project_code,)))
    if last:
        last["link_active"] = (last.get("token_expires_at") or "") >= _now()
        last.pop("token_expires_at", None)
    client = crm.get_org(conn, p["client_org_id"]) if p.get("client_org_id") else None
    contacts = _rows(conn.execute("SELECT id, full_name, email FROM crm_contact WHERE org_id = ? AND email IS NOT NULL "
                                  "AND email <> '' ORDER BY full_name", (p["client_org_id"],))) if p.get("client_org_id") else []
    return {"project": p, "client": ({"id": client["id"], "name": client["name"]} if client else None), "contacts": contacts,
            "items": items, "extras": extras, "summary": summary, "last_sent": last,
            "sends": int((sends or {}).get("n") or 0)}


