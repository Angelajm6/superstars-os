"""#327 — Permits & insurance package: what secures the job, and sending it to the client.

C-suite priority item 2: "a section within each job so we can have the permits and
insurance documents that we get from our broker to the client to secure the job."
Project Documents (#229 / #271) already stores the paper with a required-docs
checklist and per-document client sharing. This module adds the two missing pieces:

  * the PACKAGE — the subset that secures a job (every PERMITS requirement + the
    COI and the bond from CONTRACTS), with its own readiness on the Documents view;
  * SEND TO CLIENT — one email with a private link (`/d/<token>`, 90 days) where the
    client sees the package and downloads each file; the office sees sent / opened.
    Optionally the same documents are shared into the client portal (the #270
    visibility engine), so the portal's Documents section shows them too.

Tables (idempotent, both backends, no FKs by the #304 rule):
  document_package       id, project_code, client_org_id, token_hash, token_expires_at,
                         sent_to, sent_name, message, sent_by, sent_at, viewed_at,
                         view_count, doc_count
  document_package_item  id, package_id, document_id, requirement_key, title

Files are served ONLY through `/d/<token>/file/<doc id>` (membership + not
red-flagged + not expired) and the existing gated route; `file_path` never enters
a payload. A red-flagged document disappears from every sent package instantly.
"""
