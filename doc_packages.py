def send(conn, project_code: str, *, to_email=None, to_name=None, message=None, document_ids=None,
         share_in_portal: bool = True, actor=None) -> dict:
    pk = package(conn, project_code)
    if not pk:
        raise LookupError("project not found")
    available = {}
    for it in pk["items"]:
        if it["doc"] and not it["doc"]["flagged"]:
            available[it["doc"]["id"]] = (it["requirement_key"], it["label"], it["doc"])
    for d in pk["extras"]:
        if not d["flagged"]:
            available[d["id"]] = (None, d["title"], d)
    if document_ids is None:
        chosen = list(available.keys())
    else:
        try:
            chosen = [int(i) for i in document_ids]
        except (TypeError, ValueError):
            raise ValueError("document_ids must be a list of ids")
        bad = [i for i in chosen if i not in available]
        if bad:
            raise ValueError("a chosen document is not part of this job's package (or is red-flagged)")
    if not chosen:
        raise ValueError("nothing to send yet — upload the permits and the COI first")
    contacts = {c["email"].lower(): c for c in pk["contacts"]}
    to_email = (to_email or (pk["contacts"][0]["email"] if pk["contacts"] else "") or "").strip().lower()
    if "@" not in to_email or "." not in to_email.split("@")[-1]:
        raise ValueError("a valid recipient email is required")
    to_name = (to_name or (contacts.get(to_email) or {}).get("full_name") or "").strip()[:120] or None
    message = (message or "").strip()[:2000] or None
    token = secrets.token_urlsafe(32)
    now = _now()
    expires = (datetime.now() + timedelta(days=LINK_DAYS)).isoformat(timespec="seconds")
    # every send is its own package row with its own link; older links keep working until they expire
    conn.execute("INSERT INTO document_package (project_code, client_org_id, token_hash, token_expires_at, sent_to, sent_name, "
                 "message, sent_by, sent_at, doc_count) VALUES (?,?,?,?,?,?,?,?,?,?)",
                 (project_code, pk["project"].get("client_org_id"), _hash(token), expires, to_email, to_name, message, actor,
                  now, len(chosen)))
    pkg_id = _one(conn.execute("SELECT MAX(id) AS m FROM document_package"))["m"]
    for did in chosen:
        key, label, doc = available[did]
        conn.execute("INSERT INTO document_package_item (package_id, document_id, requirement_key, title) VALUES (?,?,?,?)",
                     (pkg_id, did, key, label if key else doc["title"]))
    shared = 0
    if share_in_portal:
        for did in chosen:
            if visibility.share(conn, "document", did, "client", actor).get("ok"):
                shared += 1
    conn.commit()
    project_label = pk["project"].get("name") or pk["project"].get("address") or project_code
    url = f"{_base_url()}/d/{token}"
    greeting = f"Hello {to_name.split(' ')[0]}," if to_name else "Hello,"
    msg = message or (f"Please find the permits and insurance documents for {project_label}. "
                      f"Open the link to view and download each one.")
    lines = [available[did][1] for did in chosen]
    subject = EMAIL_SUBJECT.format(project=project_label)
    text = (f"{greeting}\n\n{msg}\n\nIncluded:\n" + "\n".join(f"  - {ln}" for ln in lines)
            + f"\n\nOpen the documents: {url}\n\n— {COMPANY_NAME}")
    html = _EMAIL_HTML.format(subject=_html.escape(subject), project=_html.escape(project_label),
                              greeting=_html.escape(greeting), message=_html.escape(msg),
                              items="".join(f"<li>{_html.escape(ln)}</li>" for ln in lines),
                              url=_html.escape(url, quote=True), expires=_html.escape(_fmt_date(expires)))
    ok, err = _deliver(to_email, subject, text, html)
    if not ok:
        conn.execute("DELETE FROM document_package_item WHERE package_id = ?", (pkg_id,))
        conn.execute("DELETE FROM document_package WHERE id = ?", (pkg_id,))
        conn.commit()
        raise RuntimeError(f"email not sent: {err}")
    if pk["project"].get("client_org_id"):
        try:
            crm.add_activity(conn, entity_type="organization", entity_id=pk["project"]["client_org_id"], activity_type="system",
                             author_user_id=actor, function_tag="ops",
                             summary=f"Permits & insurance package for {project_code} emailed to {to_name or to_email} "
                                     f"({len(chosen)} document{'s' if len(chosen) != 1 else ''})")
        except Exception as e:
            log.info("#327 activity not logged: %s", e)
    return {"package_id": pkg_id, "sent_to": to_email, "sent_name": to_name, "sent_at": now, "doc_count": len(chosen),
            "shared_in_portal": shared, "expires_at": expires}


