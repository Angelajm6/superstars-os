def _public_page(token):
    conn = _conn()
    try:
        pkg = _by_token(conn, token)
        if not pkg:
            return _gone("This link is not valid.")
        if (pkg.get("token_expires_at") or "") < _now():
            return _gone("This link has expired. Reply to the email you received and we will send a fresh one.", 410)
        conn.execute("UPDATE document_package SET viewed_at = COALESCE(viewed_at, ?), view_count = view_count + 1 WHERE id = ?",
                     (_now(), pkg["id"]))
        conn.commit()
        docs = _pkg_docs(conn, pkg)
        resp = make_response(_page(conn, pkg, token, docs), 200)
        resp.headers["Cache-Control"] = "no-store"
        resp.headers["X-Robots-Tag"] = "noindex, nofollow"
        return resp
    finally:
        conn.close()


def _public_file(token, doc_id):
    conn = _conn()
    try:
        pkg = _by_token(conn, token)
        if not pkg or (pkg.get("token_expires_at") or "") < _now():
            return _gone("This link is not valid.")
        if not any(d["document_id"] == doc_id for d in _pkg_docs(conn, pkg)):
            return _gone("That document is not available on this link.")
        row = _one(conn.execute("SELECT file_path, mime, file_name FROM project_documents WHERE id = ?", (doc_id,)))
        if not row or not row.get("file_path"):
            return _gone("That document is not available on this link.")
        p = ssc_paths.resolve_data_path(row["file_path"])
        base = ssc_paths.under_root("data_room", "project_docs").resolve()
        if not (p.resolve().is_relative_to(base) and p.exists()):
            return _gone("That document is not available right now.", 503)
        resp = make_response(send_file(str(p), mimetype=row["mime"] or "application/octet-stream", as_attachment=False,
                                       download_name=row["file_name"] or f"document-{doc_id}"))
        resp.headers["Cache-Control"] = "no-store"
        resp.headers["X-Robots-Tag"] = "noindex, nofollow"
        return resp
    finally:
        conn.close()


