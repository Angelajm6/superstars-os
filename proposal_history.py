"""Claude's changes to a draft proposal, kept so any of them can be undone (accepted prototype 2026-11-11:
https://claude.ai/artifact/SJpPbUkDHenqQ9BfHECvnT).

  proposal_version(id, proposal_id, user_id, at, source, summary, before)

Each row is one change and `before` is the whole proposal (proposal_engine.snapshot) as it was just ahead of it.
source  claude     a change asked for in the Studio's Claude panel
        claude_ai  a change made through Claude in claude.ai (the connector's edit_proposal)
        back       Undo / Go back, which is itself a step so it can be undone

Going back to row N puts back N.before; every change after N goes with it. The person's own typing is not kept
here (it autosaves as before). Only the company layout (ssc) has versions.
"""
from __future__ import annotations

import json
import logging
from datetime import datetime
from typing import Optional

log = logging.getLogger("ssc.proposal_history")

KEEP = 40          # rows kept per proposal; the oldest go first
LIST_MAX = 25
SUMMARY_MAX = 160
SOURCES = ("claude", "claude_ai", "back")
_READY = False


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def ensure(conn) -> None:
    """Idempotent."""
    import db_layer
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(f"CREATE TABLE IF NOT EXISTS proposal_version ({pk}, proposal_id INTEGER NOT NULL, user_id INTEGER, "
                 "at TEXT NOT NULL, source TEXT NOT NULL, summary TEXT, before TEXT NOT NULL)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_proposal_version_p ON proposal_version(proposal_id, id)")
    conn.commit()


def summary_of(reply: str, changed: Optional[list] = None, labels: Optional[dict] = None) -> str:
    """The first sentence of Claude's reply ("Removed the sidewalk shed line."), else the parts that changed."""
    s = " ".join(str(reply or "").split())
    if s:
        cut = [i for i in (s.find(". "), s.find("? "), s.find("! ")) if i > 0]
        s = s[:min(cut) + 1] if cut else s
    if not s and changed:
        s = "Changed the " + ", ".join((labels or {}).get(k, k) for k in changed)
    s = s or "Changed the proposal"
    return s if len(s) <= SUMMARY_MAX else s[:SUMMARY_MAX - 1].rstrip() + "…"


def record(conn, pid: int, uid, before: dict, summary: str, source: str = "claude") -> int:
    """Keep the proposal as it was before a change. Commits. Returns the new row's id."""
    if source not in SOURCES:
        raise ValueError("unknown source")
    global _READY
    if not _READY:   # a change can come before the Studio's boot ensure ran (the Claude drawer, the connector, a test app)
        ensure(conn)
        _READY = True
    cur = conn.execute("INSERT INTO proposal_version (proposal_id, user_id, at, source, summary, before) "
                       "VALUES (?,?,?,?,?,?) RETURNING id",
                       (pid, uid, _now(), source, str(summary or "")[:SUMMARY_MAX], json.dumps(before, default=str)))
    vid = cur.fetchone()[0]
    old = conn.execute("SELECT id FROM proposal_version WHERE proposal_id = ? ORDER BY id DESC LIMIT 1 OFFSET ?",
                       (pid, KEEP - 1)).fetchone()
    if old:
        conn.execute("DELETE FROM proposal_version WHERE proposal_id = ? AND id < ?", (pid, old[0]))
    conn.commit()
    return int(vid)


def _who(conn, uid) -> str:
    if not uid:
        return ""
    r = conn.execute("SELECT full_name, email FROM users WHERE id = ?", (uid,)).fetchone()
    if not r:
        return ""
    r = dict(r)
    return (str(r.get("full_name") or "").split() or [str(r.get("email") or "").split("@")[0]])[0]


def listing(conn, pid: int) -> list:
    """Newest first: [{id, at, source, summary, who, later}] — later = how many changes going back to it also undoes."""
    rows = [dict(r) for r in conn.execute(
        "SELECT id, user_id, at, source, summary FROM proposal_version WHERE proposal_id = ? ORDER BY id DESC LIMIT ?",
        (pid, LIST_MAX)).fetchall()]
    names = {}
    out = []
    for i, r in enumerate(rows):
        u = r["user_id"]
        if u not in names:
            names[u] = _who(conn, u)
        out.append({"id": r["id"], "at": r["at"], "source": r["source"], "summary": r["summary"] or "",
                    "who": names[u], "later": i})
    return out


def restore(conn, pid: int, vid: int, uid) -> dict:
    """Put back the proposal as it was before change `vid`, keeping the present one as a 'back' step.
    {summary, undid} — undid = how many changes went."""
    import proposal_engine
    import proposals
    r = proposals.get(conn, pid)
    if not r:
        raise LookupError("proposal not found")
    if r["status"] != "draft":
        raise ValueError("This proposal was already sent. Make a new version to change it.")
    row = conn.execute("SELECT id, summary, before FROM proposal_version WHERE id = ? AND proposal_id = ?",
                       (vid, pid)).fetchone()
    if not row:
        raise ValueError("That change isn't in this proposal's history any more.")
    row = dict(row)
    undid = conn.execute("SELECT COUNT(*) FROM proposal_version WHERE proposal_id = ? AND id >= ?",
                         (pid, vid)).fetchone()[0]
    now = proposal_engine.snapshot(conn, pid)
    what = row["summary"] or "a change"
    summary = ("Undid: " if undid == 1 else "Went back to before: ") + what
    proposal_engine.undo(conn, pid, json.loads(row["before"]), uid)
    record(conn, pid, uid, now, summary, "back")
    return {"summary": summary, "undid": int(undid)}


def latest(conn, pid: int) -> Optional[int]:
    r = conn.execute("SELECT id FROM proposal_version WHERE proposal_id = ? ORDER BY id DESC LIMIT 1", (pid,)).fetchone()
    return int(r[0]) if r else None
