"""#336 — the building in 3D, stage 1: real massing from public city data + the elevation grids.

What the client sees on /drawing-markup today is one flat grid per elevation. This module
gives the page the BUILDING: its true footprint and height from NYC Open Data (Building
Footprints, dataset 5zhs-2jue — no key, no account), the neighbours around it for scale,
and which elevation belongs to which wall, so the browser can extrude the real shape and
drape the existing drop × level grids onto its faces. Every cell stays clickable and
opens the same panel the 2D markup uses.

How a job finds its building
  1. the linked `building.bin` when the office entered one;
  2. else the address is geocoded with NYC Planning's GeoSearch (free) — it answers with
     the point AND the BIN;
  3. else the job's site point (Crew & site) → the footprint that contains it.
The result is cached per job in `building_geometry` (30 days; "Refresh" re-fetches).
Outside the city, or when the provider is down, the page still works: it falls back to a
box sized from the traced elevations, so Long Island and New Jersey jobs are not blank.

Coordinates leave here as LOCAL METRES around the building's centroid (x east, y north),
which is what the renderer wants; heights are metres too (the source is feet).

Access = the elevation module's rule (`elevation._require_project`): admin / c_suite see
every job, pm / super / estimator / architect their assigned ones, a client the one job
its portal is bound to. Read-only; no PII.
"""
from __future__ import annotations

import json
import logging
import math
import os
from pathlib import Path
from datetime import date, datetime, timedelta
from typing import Optional

from flask import jsonify, request

import db_layer
import elevation as _elev
from auth import current_user

log = logging.getLogger("ssc.building3d")

FOOTPRINTS = "https://data.cityofnewyork.us/resource/5zhs-2jue.json"
GEOSEARCH = "https://geosearch.planninglabs.nyc/v2/search"
CACHE_DAYS = 30
RETRY_AFTER_ERROR_HOURS = 6
NEIGHBOUR_RADIUS_M = 90
NEIGHBOUR_LIMIT = 60
FT = 0.3048
UA = "SuperstarsOS/1.0 (+facade restoration dashboard)"


# ---------------------------------------------------------------- helpers
def _conn():
    return db_layer.connect(pragma_fk=True)


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _num(v) -> Optional[float]:
    try:
        return float(v) if v not in (None, "") else None
    except (TypeError, ValueError):
        return None


def _err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


def _default_fetch(url: str, params: dict) -> object:
    """GET → parsed JSON (list or dict). Kept tiny so tests can inject a fake."""
    import requests
    r = requests.get(url, params=params, timeout=8, headers={"User-Agent": UA, "Accept": "application/json"})
    r.raise_for_status()
    return r.json()


# ---------------------------------------------------------------- schema
def ensure_schema(conn) -> None:
    pg = db_layer.is_postgres()
    pk = "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if pg else "id INTEGER PRIMARY KEY AUTOINCREMENT"
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS building_geometry ("
        f"  {pk},"
        f"  project_code      TEXT NOT NULL,"
        f"  bin               TEXT,"
        f"  lat               REAL,"
        f"  lng               REAL,"
        f"  geocode_label     TEXT,"
        f"  footprint_json    TEXT,"
        f"  height_ft         REAL,"
        f"  ground_ft         REAL,"
        f"  construction_year INTEGER,"
        f"  neighbours_json   TEXT,"
        f"  source            TEXT,"
        f"  error             TEXT,"
        f"  fetched_at        TEXT NOT NULL"
        f")")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_building_geometry_project ON building_geometry(project_code)")
    conn.commit()


# ---------------------------------------------------------------- providers
def geocode(text: str, fetch=None) -> Optional[dict]:
    """NYC Planning GeoSearch: address text → {lat, lng, bin, label}. None when nothing matched."""
    fetch = fetch or _default_fetch
    if not (text or "").strip():
        return None
    data = fetch(GEOSEARCH, {"text": text.strip(), "size": 1})
    feats = (data or {}).get("features") or []
    if not feats:
        return None
    f = feats[0]
    lng, lat = (f.get("geometry") or {}).get("coordinates") or (None, None)
    props = f.get("properties") or {}
    b = (((props.get("addendum") or {}).get("pad") or {}).get("bin"))
    return {"lat": _num(lat), "lng": _num(lng), "bin": (str(b) if b else None), "label": props.get("label")}


def _footprint_rows(where: str, fetch, limit: int = 1) -> list:
    fetch = fetch or _default_fetch
    data = fetch(FOOTPRINTS, {"$where": where, "$limit": limit,
                              "$select": "bin,height_roof,ground_elevation,construction_year,the_geom"})
    return list(data or [])


def _rings(geom: dict) -> list:
    """Outer ring(s) as [[lng, lat], ...] lists — the first ring of every polygon."""
    if not geom:
        return []
    t, c = geom.get("type"), geom.get("coordinates") or []
    if t == "Polygon":
        return [c[0]] if c else []
    if t == "MultiPolygon":
        return [poly[0] for poly in c if poly]
    return []


def footprint_by_bin(bin_: str, fetch=None) -> Optional[dict]:
    rows = _footprint_rows(f"bin='{str(bin_).strip()}'", fetch)
    return _pack(rows[0]) if rows else None


def footprint_at(lat: float, lng: float, fetch=None) -> Optional[dict]:
    rows = _footprint_rows(f"intersects(the_geom,'POINT({lng} {lat})')", fetch)
    return _pack(rows[0]) if rows else None


def neighbours(lat: float, lng: float, *, exclude_bin=None, radius_m: int = NEIGHBOUR_RADIUS_M, fetch=None) -> list:
    rows = _footprint_rows(f"within_circle(the_geom,{lat},{lng},{radius_m})", fetch, limit=NEIGHBOUR_LIMIT)
    out = []
    for r in rows:
        if exclude_bin and str(r.get("bin")) == str(exclude_bin):
            continue
        p = _pack(r)
        if p and p["rings"]:
            out.append({"bin": p["bin"], "height_ft": p["height_ft"], "rings": p["rings"]})
    return out


def _pack(r: dict) -> Optional[dict]:
    rings = _rings(r.get("the_geom") or {})
    if not rings:
        return None
    return {"bin": str(r.get("bin") or ""), "height_ft": _num(r.get("height_roof")),
            "ground_ft": _num(r.get("ground_elevation")),
            "construction_year": int(r["construction_year"]) if str(r.get("construction_year") or "").isdigit() else None,
            "rings": rings}


# ---------------------------------------------------------------- resolve + cache
def _project(conn, code: str) -> Optional[dict]:
    p = _one(conn.execute("SELECT p.project_code, p.name, p.address, p.city_zip, p.building_id, p.site_lat, p.site_lng, "
                          "b.bin AS b_bin, b.lat AS b_lat, b.lng AS b_lng, b.address_line, b.borough, b.city, b.zip, b.stories "
                          "FROM projects p LEFT JOIN building b ON b.id = p.building_id WHERE p.project_code = ?", (code,)))
    return p


def _address_text(p: dict) -> str:
    line = (p.get("address_line") or p.get("address") or "").strip()
    tail = (p.get("city_zip") or "").strip() or " ".join(x for x in ((p.get("city") or p.get("borough") or ""), (p.get("zip") or "")) if x)
    return f"{line}, {tail}".strip(", ") if line else ""


def cached(conn, code: str) -> Optional[dict]:
    return _one(conn.execute("SELECT * FROM building_geometry WHERE project_code = ?", (code,)))


def resolve(conn, code: str, *, refresh: bool = False, fetch=None, now: Optional[datetime] = None) -> dict:
    """The cached geometry row for a job, fetched (or re-fetched) when missing / stale / asked."""
    now = now or datetime.now()
    row = cached(conn, code)
    if row and not refresh:
        try:
            age = now - datetime.fromisoformat(row["fetched_at"])
        except ValueError:
            age = timedelta(days=999)
        if row.get("footprint_json") and age < timedelta(days=CACHE_DAYS):
            return row
        if not row.get("footprint_json") and age < timedelta(hours=RETRY_AFTER_ERROR_HOURS):
            return row
    p = _project(conn, code)
    if not p:
        raise LookupError("project not found")
    fetch = fetch or _default_fetch
    result = {"bin": None, "lat": None, "lng": None, "geocode_label": None, "footprint": None, "neighbours": [], "error": None}
    try:
        bin_ = (str(p.get("b_bin")).strip() if p.get("b_bin") else None)
        lat, lng = _num(p.get("b_lat")), _num(p.get("b_lng"))
        if not bin_:
            g = geocode(_address_text(p), fetch)
            if g:
                bin_ = g.get("bin") or bin_
                lat, lng = g.get("lat") or lat, g.get("lng") or lng
                result["geocode_label"] = g.get("label")
        if lat is None or lng is None:
            lat, lng = _num(p.get("site_lat")), _num(p.get("site_lng"))
        fp = footprint_by_bin(bin_, fetch) if bin_ else None
        if not fp and lat is not None and lng is not None:
            fp = footprint_at(lat, lng, fetch)
        if fp:
            ring0 = fp["rings"][0]
            if len(ring0) > 1 and ring0[0] == ring0[-1]:
                ring0 = ring0[:-1]              # the closing point would weight one corner twice
            xs = [pt[0] for pt in ring0]
            ys = [pt[1] for pt in ring0]
            lng, lat = sum(xs) / len(xs), sum(ys) / len(ys)
            result.update({"bin": fp["bin"] or bin_, "lat": lat, "lng": lng, "footprint": fp})
            try:
                result["neighbours"] = neighbours(lat, lng, exclude_bin=fp["bin"], fetch=fetch)
            except Exception as ex:
                log.info("#336 neighbours skipped for %s: %s", code, ex)
        else:
            result.update({"bin": bin_, "lat": lat, "lng": lng, "error": "no footprint found for this address"})
    except Exception as ex:
        result["error"] = f"{type(ex).__name__}: {str(ex)[:200]}"
        log.info("#336 geometry fetch failed for %s: %s", code, result["error"])
    fp = result["footprint"]
    vals = (code, result["bin"], result["lat"], result["lng"], result["geocode_label"],
            json.dumps(fp["rings"]) if fp else None, fp["height_ft"] if fp else None, fp["ground_ft"] if fp else None,
            fp["construction_year"] if fp else None, json.dumps(result["neighbours"]) if fp else None,
            "nyc_open_data" if fp else None, result["error"], now.isoformat(timespec="seconds"))
    if row:
        conn.execute("UPDATE building_geometry SET project_code=?, bin=?, lat=?, lng=?, geocode_label=?, footprint_json=?, height_ft=?, "
                     "ground_ft=?, construction_year=?, neighbours_json=?, source=?, error=?, fetched_at=? WHERE id=?", vals + (row["id"],))
    else:
        conn.execute("INSERT INTO building_geometry (project_code, bin, lat, lng, geocode_label, footprint_json, height_ft, ground_ft, "
                     "construction_year, neighbours_json, source, error, fetched_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)", vals)
    conn.commit()
    return cached(conn, code)


# ---------------------------------------------------------------- geometry maths
def local_xy(lng: float, lat: float, lng0: float, lat0: float) -> tuple:
    """Equirectangular metres around (lng0, lat0): x east, y north. Plenty for a city block."""
    k = math.cos(math.radians(lat0))
    return (round((lng - lng0) * 111320.0 * k, 3), round((lat - lat0) * 110540.0, 3))


def _signed_area(ring: list) -> float:
    a = 0.0
    for i in range(len(ring)):
        x0, y0 = ring[i]
        x1, y1 = ring[(i + 1) % len(ring)]
        a += x0 * y1 - x1 * y0
    return a / 2.0


def _ccw(ring: list) -> list:
    return ring if _signed_area(ring) >= 0 else list(reversed(ring))


def compass(bearing: float) -> str:
    b = bearing % 360
    if b < 45 or b >= 315:
        return "N"
    if b < 135:
        return "E"
    if b < 225:
        return "S"
    return "W"


def faces(ring_xy: list) -> dict:
    """Edges of a CCW ring with outward normals; the longest edge per compass direction
    is that wall. Bearings are degrees clockwise from north."""
    ring = _ccw([tuple(p) for p in ring_xy])
    if len(ring) > 1 and ring[0] == ring[-1]:
        ring = ring[:-1]
    edges = []
    for i in range(len(ring)):
        x0, y0 = ring[i]
        x1, y1 = ring[(i + 1) % len(ring)]
        dx, dy = x1 - x0, y1 - y0
        length = math.hypot(dx, dy)
        if length < 0.5:
            continue
        # CCW ring: outward normal is (dy, -dx)
        nx, ny = dy / length, -dx / length
        bearing = (math.degrees(math.atan2(nx, ny)) + 360) % 360
        edges.append({"x0": x0, "y0": y0, "x1": x1, "y1": y1, "length_m": round(length, 2),
                      "bearing": round(bearing, 1), "compass": compass(bearing), "normal": [round(nx, 4), round(ny, 4)]})
    walls = {}
    for e in edges:
        c = e["compass"]
        if c not in walls or e["length_m"] > walls[c]["length_m"]:
            walls[c] = e
    return {"edges": edges, "walls": walls}


def _face_code(face: Optional[str], label: Optional[str]) -> Optional[str]:
    """Map an elevation's face ('N', 'North', 'NE', 'Front (north)') onto N/E/S/W."""
    for v in (face, label):
        s = (v or "").strip().upper()
        if not s:
            continue
        for key in ("N", "S", "E", "W"):
            if s == key or s.startswith(key) or f"({key.lower()}" in (v or "").lower() or key.lower() + "orth" in s.lower() \
                    or key.lower() + "outh" in s.lower() or key.lower() + "ast" in s.lower() or key.lower() + "est" in s.lower():
                return key
    return None


# ---------------------------------------------------------------- the model
def model(conn, code: str, *, fetch=None, refresh: bool = False) -> Optional[dict]:
    p = _project(conn, code)
    if not p:
        return None
    internal = _elev.is_internal()
    elev_rows = _rows(conn.execute(
        "SELECT id, face, face_label, name, status, geometry_json FROM elevation WHERE project_code = ? ORDER BY id", (code,)))
    elevs = []
    for r in elev_rows:
        status = r.get("status") or "confirmed"
        if status != "confirmed" and not internal:
            continue
        try:
            g = json.loads(r.get("geometry_json") or "{}")
        except ValueError:
            g = {}
        fac = (g or {}).get("facade") or {}
        elevs.append({"id": r["id"], "face": r.get("face"), "face_label": r.get("face_label") or r.get("face"),
                      "name": r.get("name"), "status": status, "traced": bool(fac),
                      "compass": _face_code(r.get("face"), r.get("face_label") or r.get("name")),
                      "width_ft": _num(fac.get("width_ft")), "height_ft": _num(fac.get("height_ft"))})
    mapping = {}
    for e in elevs:
        if e["traced"] and e["status"] == "confirmed" and e["compass"] and e["compass"] not in mapping:
            mapping[e["compass"]] = e["id"]
    try:
        row = resolve(conn, code, refresh=refresh, fetch=fetch)
    except LookupError:
        return None
    except Exception as ex:
        log.info("#336 resolve failed for %s: %s", code, ex)
        row = None
    geometry = {"available": False, "source": None, "error": (row or {}).get("error") if row else "geometry unavailable"}
    if row and row.get("footprint_json"):
        rings = json.loads(row["footprint_json"])
        lng0, lat0 = float(row["lng"]), float(row["lat"])
        local_rings = [[list(local_xy(pt[0], pt[1], lng0, lat0)) for pt in ring] for ring in rings]
        f = faces(local_rings[0]) if local_rings else {"edges": [], "walls": {}}
        nb = []
        for n in json.loads(row.get("neighbours_json") or "[]"):
            nb.append({"bin": n.get("bin"), "height_m": round((_num(n.get("height_ft")) or 10.0) * FT, 2),
                       "rings": [[list(local_xy(pt[0], pt[1], lng0, lat0)) for pt in ring] for ring in n.get("rings") or []]})
        h_ft = _num(row.get("height_ft")) or 30.0
        geometry = {"available": True, "source": row.get("source"), "bin": row.get("bin"), "lat": lat0, "lng": lng0,
                    "geocode_label": row.get("geocode_label"), "height_m": round(h_ft * FT, 2), "height_ft": h_ft,
                    "ground_ft": _num(row.get("ground_ft")), "construction_year": row.get("construction_year"),
                    "rings": local_rings, "edges": f["edges"], "walls": f["walls"], "neighbours": nb,
                    "fetched_at": row.get("fetched_at"), "error": None}
    # fallback box from the traced elevations (any city, any failure)
    widths = {e["compass"]: e["width_ft"] for e in elevs if e["traced"] and e["compass"] and e["width_ft"]}
    w_ns = max([v for k, v in widths.items() if k in ("N", "S")] or [0.0])
    w_ew = max([v for k, v in widths.items() if k in ("E", "W")] or [0.0])
    h = max([e["height_ft"] for e in elevs if e["height_ft"]] or [0.0])
    if not w_ns and not w_ew:
        w_ns, w_ew = 80.0, 60.0
    fallback = {"width_m": round((w_ns or w_ew * 1.4) * FT, 2), "depth_m": round((w_ew or w_ns * 0.7) * FT, 2),
                "height_m": round((h or 40.0) * FT, 2)}
    stories = p.get("stories")
    if not stories and geometry.get("available"):
        stories = max(1, int(round(geometry["height_ft"] / 11.0)))
    return {"project": {"project_code": p["project_code"], "name": p.get("name"), "address": p.get("address_line") or p.get("address"),
                        "borough": p.get("borough"), "stories": stories},
            "geometry": geometry, "fallback": fallback, "elevations": elevs, "mapping": mapping,
            "photoreal": photoreal(geometry),   # #353
            "audience": _elev.audience(), "can_refresh": internal}


# ---------------------------------------------------------------- #353 photoreal
# Google Photorealistic 3D Tiles, drawn by the vendored NASA-AMMOS 3d-tiles-renderer.
# SSC_GOOGLE_TILES_KEY is a BROWSER key (HTTP-referrer + Map Tiles API restricted, daily
# quota capped) — public by nature, so it may reach any viewer who can open the model.
# Google's policy requires its Maps logo on screen, so photoreal only switches on when the
# official logo file is vendored too. Without either, the massing view is used as today.
GOOGLE_LOGO_REL = "static/vendor/google/google_maps_logo.svg"
GEOID_NYC_M = -32.7   # NAVD88 -> WGS84 ellipsoid offset around New York City (approx.)


def photoreal(geometry: dict) -> dict:
    key = (os.environ.get("SSC_GOOGLE_TILES_KEY") or "").strip()
    logo = Path(__file__).resolve().parent / GOOGLE_LOGO_REL
    out = {"available": False, "reason": None}
    if not key:
        out["reason"] = "no_key"
    elif not logo.is_file():
        out["reason"] = "no_logo"
    elif not (geometry or {}).get("available") or geometry.get("lat") is None:
        out["reason"] = "no_location"
    else:
        ground_ft = geometry.get("ground_ft")
        out.update({"available": True, "key": key, "lat": geometry["lat"], "lng": geometry["lng"],
                    "logo_url": "/files/" + GOOGLE_LOGO_REL,
                    # starting guess for the ground on Google's ellipsoid; the browser refines
                    # it by casting a ray onto the loaded tiles
                    "ground_ellipsoid_m": round((ground_ft or 0.0) * FT + GEOID_NYC_M, 2)})
    return out


# ---------------------------------------------------------------- routes
def _api_model(project_code):
    conn = _conn()
    try:
        blocked = _elev._require_project(conn, project_code)
        if blocked:
            return blocked
        refresh = _elev.is_internal() and request.args.get("refresh") == "1"
        m = model(conn, project_code, refresh=refresh)
        return jsonify({"data": m}) if m else _err("project not found", 404)
    finally:
        conn.close()


def _api_refresh(project_code):
    if not _elev.is_internal():
        return _err("forbidden", 403)
    conn = _conn()
    try:
        blocked = _elev._require_project(conn, project_code)
        if blocked:
            return blocked
        m = model(conn, project_code, refresh=True)
        return jsonify({"data": m}) if m else _err("project not found", 404)
    finally:
        conn.close()


def register(app) -> None:
    conn = _conn()
    try:
        ensure_schema(conn)
        db_layer._PKMAP_CACHE.clear()
    except Exception as e:
        log.warning("#336 building_geometry schema ensure skipped: %s", e)
    finally:
        conn.close()
    # under /api/elevation/ on purpose: that prefix is what the client-portal and architect
    # containment allowlists already admit for the drawing markup (client_portal, elevation)
    app.add_url_rule("/api/elevation/model3d/<project_code>", "building3d_model", _api_model, methods=["GET"])
    app.add_url_rule("/api/elevation/model3d/<project_code>/refresh", "building3d_refresh", _api_refresh, methods=["POST"])
