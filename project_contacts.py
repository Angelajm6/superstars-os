"""#357 — the people on a job: ownership group, property managers, consultants, site supervisors.

The C-suite asked for the contacts of everyone around a project. The CRM (#266) already
holds organizations and people; nothing tied a person to a PROJECT in a role. This module
adds that link, and becomes the one source for the names printed on documents (the DCR's
Superintendent / Project Manager / Client were always "—": they read dead columns).

  project_contact  id, project_code, role, contact_id -> crm_contact (people outside the
                   company) | employee_id -> employees (OUR supervisors, site_supervisor
                   only), discipline (consultants), title_on_job, is_primary, notes,
                   sort_order, created_at, created_by, updated_at, removed_at, removed_by

  roles: owner · property_manager · consultant (architect | structural_engineer |
         mep_engineer | expeditor | other) · site_supervisor (ours = an employee, theirs =
         the owner's / GC's person)
  one PRIMARY per (project, role, side); removing is soft (history kept)

Access: reading = admin / c_suite / pm / super (section `project_contacts`, plus the #263
project scoping on /api/projects/<code>/…); writing = admin / c_suite. Email and phone go to
those internal roles only, never into logs or the lookup; an employee's phone is never shown
(worker PII). Clients and architects never reach these routes.
"""
from __future__ import annotations

import logging
from datetime import datetime
from typing import Optional

from flask import jsonify, request

import crm
import db_layer
from auth import current_user, requires_company, requires_section

log = logging.getLogger("ssc.project_contacts")

# Oct 7 C-suite notes: the groups read Owner / Engineer / Architect / General contractor
# (labels only; the stored role keys are unchanged).
ROLES = {"owner": "Owner", "property_manager": "Property manager",
         "consultant": "Engineer / Architect", "site_supervisor": "General contractor"}
DISCIPLINES = {"architect": "Architect", "structural_engineer": "Structural engineer",
               "mep_engineer": "MEP engineer", "expeditor": "Expeditor", "other": "Other consultant"}
_RT_FOR = {"owner": "owner", "property_manager": "property_manager", "site_supervisor": "other"}
_RT_FOR_DISCIPLINE = {"architect": "architect", "structural_engineer": "engineer", "mep_engineer": "engineer",
                      "expeditor": "expeditor", "other": "consultant"}


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def ensure(conn) -> None:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(f"CREATE TABLE IF NOT EXISTS project_contact ({pk}, project_code TEXT NOT NULL, role TEXT NOT NULL, "
                 f"contact_id INTEGER, employee_id TEXT, discipline TEXT, title_on_job TEXT, "
                 f"is_primary INTEGER NOT NULL DEFAULT 0, notes TEXT, sort_order INTEGER DEFAULT 0, "
                 f"created_at TEXT, created_by INTEGER, updated_at TEXT, removed_at TEXT, removed_by INTEGER)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_project_contact_role ON project_contact(project_code, role)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_project_contact_contact ON project_contact(contact_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_project_contact_employee ON project_contact(employee_id)")
    conn.commit()


# ---------------------------------------------------------------- reads
def _project(conn, code) -> Optional[dict]:
    return _one(conn.execute("SELECT project_code, client_org_id FROM projects WHERE project_code = ?", (code,)))


def _pms(conn, code) -> list:
    try:
        return _rows(conn.execute(
            "SELECT u.id, COALESCE(u.display_name, u.full_name, u.email) AS name, u.email FROM pm_project_assignment a "
            "JOIN users u ON u.id = a.user_id WHERE a.project_code = ? AND u.role = 'pm' AND COALESCE(u.is_active, 1) = 1 "
            "ORDER BY a.id", (code,)))
    except Exception:
        conn.rollback()
        return []


def _link_rows(conn, code) -> list:
    return _rows(conn.execute(
        "SELECT pc.id, pc.role, pc.contact_id, pc.employee_id, pc.discipline, pc.title_on_job, pc.is_primary, pc.notes, "
        "       c.full_name AS c_name, c.title AS c_title, c.email AS c_email, c.phone AS c_phone, "
        "       o.id AS org_id, o.name AS org_name, "
        "       e.name AS e_name, e.worker_id AS e_worker_id, e.trade AS e_trade "
        "FROM project_contact pc "
        "LEFT JOIN crm_contact c ON c.id = pc.contact_id "
        "LEFT JOIN crm_organization o ON o.id = c.org_id "
        "LEFT JOIN employees e ON e.employee_id = pc.employee_id "
        "WHERE pc.project_code = ? AND pc.removed_at IS NULL "
        "ORDER BY pc.role, pc.is_primary DESC, pc.sort_order, pc.id", (code,)))


def _public(r: dict, with_pii: bool) -> dict:
    ours = bool(r.get("employee_id"))
    out = {"id": r["id"], "role": r["role"], "side": "ours" if ours else "theirs", "is_primary": bool(r["is_primary"]),
           "discipline": r.get("discipline"), "discipline_label": DISCIPLINES.get(r.get("discipline") or "", None),
           "title": r.get("title_on_job") or (None if ours else r.get("c_title")), "notes": r.get("notes")}
    if ours:
        out.update({"name": (f"{r['e_worker_id']} — {r['e_name']}" if r.get("e_worker_id") else r.get("e_name")) or r["employee_id"],
                    "employee_id": r["employee_id"], "org": "Superstars Contracting", "trade": r.get("e_trade")})
    else:
        out.update({"name": r.get("c_name") or "—", "contact_id": r.get("contact_id"), "org": r.get("org_name"),
                    "org_id": r.get("org_id")})
        if with_pii:
            out.update({"email": r.get("c_email"), "phone": r.get("c_phone")})
    return out


def list_for_project(conn, code, *, with_pii: bool) -> Optional[dict]:
    if not _project(conn, code):
        return None
    rows = [_public(r, with_pii) for r in _link_rows(conn, code)]
    groups = {k: [x for x in rows if x["role"] == k and not (k == "site_supervisor" and x["side"] == "ours")] for k in ROLES}
    try:
        crew = int(conn.execute("SELECT COUNT(1) FROM project_assignments WHERE project_code = ? AND "
                                "COALESCE(status, 'active') = 'active'", (code,)).fetchone()[0])
    except Exception:
        conn.rollback()
        crew = 0
    pms = [{"name": p["name"], **({"email": p.get("email")} if with_pii else {})} for p in _pms(conn, code)]
    return {"team": {"pms": pms, "supervisors": [x for x in rows if x["role"] == "site_supervisor" and x["side"] == "ours"],
                     "crew_count": crew},
            "groups": groups, "roles": ROLES, "disciplines": DISCIPLINES}


def project_people(conn, code) -> dict:
    """The names documents print: superintendent (our primary site supervisor, else the
    legacy column), project manager (first assigned PM), owner / client (the client org,
    else the legacy column). Never raises — a header must always render."""
    out = {"superintendent": None, "project_manager": None, "owner_client": None}
    try:
        legacy = _one(conn.execute("SELECT * FROM projects WHERE project_code = ?", (code,))) or {}
        r = _one(conn.execute(
            "SELECT e.name FROM project_contact pc JOIN employees e ON e.employee_id = pc.employee_id "
            "WHERE pc.project_code = ? AND pc.role = 'site_supervisor' AND pc.removed_at IS NULL "
            "ORDER BY pc.is_primary DESC, pc.id LIMIT 1", (code,)))
        out["superintendent"] = (r or {}).get("name") or legacy.get("superintendent")
        pms = _pms(conn, code)
        out["project_manager"] = pms[0]["name"] if pms else None
        if legacy.get("client_org_id"):
            o = _one(conn.execute("SELECT name FROM crm_organization WHERE id = ?", (legacy["client_org_id"],)))
            out["owner_client"] = (o or {}).get("name")
        out["owner_client"] = out["owner_client"] or legacy.get("client")
    except Exception as e:
        log.info("#357 project_people fell back: %s", e)
        try:
            conn.rollback()
        except Exception:
            pass
    return out


# ---------------------------------------------------------------- writes
def _clean(v, n=200) -> Optional[str]:
    s = (str(v).strip() if v is not None else "")[:n]
    return s or None


def _set_primary(conn, code, role, side_ours: bool, keep_id: int) -> None:
    side = "pc.employee_id IS NOT NULL" if side_ours else "pc.employee_id IS NULL"
    conn.execute(f"UPDATE project_contact SET is_primary = 0 WHERE id IN (SELECT pc.id FROM project_contact pc "
                 f"WHERE pc.project_code = ? AND pc.role = ? AND {side} AND pc.removed_at IS NULL AND pc.id <> ?)",
                 (code, role, keep_id))
    conn.execute("UPDATE project_contact SET is_primary = 1 WHERE id = ?", (keep_id,))


def add(conn, code, p: dict, *, actor=None) -> dict:
    proj = _project(conn, code)
    if not proj:
        raise LookupError("project not found")
    role = (p.get("role") or "").strip()
    if role not in ROLES:
        raise ValueError("pick the role: owner, property manager, engineer / architect or general contractor")
    disc = (p.get("discipline") or "").strip() or None
    if role == "consultant":
        if disc not in DISCIPLINES:
            raise ValueError("pick the consultant's discipline")
    else:
        disc = None
    emp, cid, newc = _clean(p.get("employee_id"), 20), p.get("contact_id"), p.get("new_contact")
    if sum(1 for x in (emp, cid, newc) if x) != 1:
        raise ValueError("pick one person: an existing contact, a new person, or one of our employees")
    if emp:
        if role != "site_supervisor":
            raise ValueError("our own people can only be added as site supervisors")
        if not conn.execute("SELECT 1 FROM employees WHERE employee_id = ? AND archived_at IS NULL", (emp,)).fetchone():
            raise ValueError("that worker is not on the active roster")
    if cid:
        try:
            cid = int(cid)
        except (TypeError, ValueError):
            raise ValueError("unknown contact")
        if not crm.get_contact(conn, cid):
            raise ValueError("unknown contact")
    if newc:
        if not isinstance(newc, dict) or not _clean(newc.get("full_name")):
            raise ValueError("enter the person's name")
        org_id = p.get("org_id")
        raw_org = p.get("new_org")
        new_org = _clean(raw_org.get("name") if isinstance(raw_org, dict) else raw_org)
        if org_id and not crm.get_org(conn, org_id):
            raise ValueError("unknown organization")
    # duplicate active link?
    dup = None
    if cid:
        dup = conn.execute("SELECT 1 FROM project_contact WHERE project_code = ? AND role = ? AND removed_at IS NULL "
                           "AND contact_id = ?", (code, role, cid)).fetchone()
    elif emp:
        dup = conn.execute("SELECT 1 FROM project_contact WHERE project_code = ? AND role = ? AND removed_at IS NULL "
                           "AND employee_id = ?", (code, role, emp)).fetchone()
    if dup:
        raise PermissionError("that person is already on this job in that role")
    # everything validated — now create the org / person (the CRM helpers commit)
    rt = _RT_FOR_DISCIPLINE.get(disc) if role == "consultant" else _RT_FOR[role]
    if newc:
        if new_org:
            org_id = crm.create_org(conn, name=new_org, relationship_type=rt, created_by=actor)
        cid = crm.create_contact(conn, full_name=newc.get("full_name"), org_id=int(org_id) if org_id else None,
                                 email=newc.get("email"), phone=newc.get("phone"), title=newc.get("title"),
                                 relationship_type=rt, created_by=actor)
    now = _now()
    conn.execute("INSERT INTO project_contact (project_code, role, contact_id, employee_id, discipline, title_on_job, "
                 "is_primary, notes, created_at, created_by, updated_at) VALUES (?,?,?,?,?,?,0,?,?,?,?)",
                 (code, role, cid if not emp else None, emp, disc, _clean(p.get("title_on_job"), 80),
                  _clean(p.get("notes"), 500), now, actor, now))
    new_id = _one(conn.execute("SELECT MAX(id) AS m FROM project_contact WHERE project_code = ?", (code,)))["m"]
    side_ours = bool(emp)
    has_primary = conn.execute(
        f"SELECT 1 FROM project_contact WHERE project_code = ? AND role = ? AND removed_at IS NULL AND is_primary = 1 AND "
        f"employee_id IS {'NOT ' if side_ours else ''}NULL", (code, role)).fetchone()
    if p.get("is_primary") or not has_primary:
        _set_primary(conn, code, role, side_ours, new_id)
    conn.commit()
    return {"id": new_id}


def update(conn, code, link_id: int, p: dict) -> None:
    r = _one(conn.execute("SELECT * FROM project_contact WHERE id = ? AND project_code = ? AND removed_at IS NULL",
                          (link_id, code)))
    if not r:
        raise LookupError("contact not found on this job")
    sets, vals = [], []
    if "title_on_job" in p:
        sets.append("title_on_job = ?"); vals.append(_clean(p.get("title_on_job"), 80))
    if "notes" in p:
        sets.append("notes = ?"); vals.append(_clean(p.get("notes"), 500))
    if "discipline" in p and r["role"] == "consultant":
        if p.get("discipline") not in DISCIPLINES:
            raise ValueError("pick the consultant's discipline")
        sets.append("discipline = ?"); vals.append(p.get("discipline"))
    if sets:
        conn.execute(f"UPDATE project_contact SET {', '.join(sets)}, updated_at = ? WHERE id = ?", vals + [_now(), link_id])
    if p.get("is_primary"):
        _set_primary(conn, code, r["role"], bool(r["employee_id"]), link_id)
    person = p.get("person")   # edit the CRM person's phone / email / title in place
    if isinstance(person, dict) and r.get("contact_id"):
        fields = {k: _clean(person.get(k)) for k in ("full_name", "title", "email", "phone") if k in person}
        if "full_name" in fields and not fields["full_name"]:
            raise ValueError("the name can't be empty")
        if fields:
            crm.update_contact(conn, r["contact_id"], **fields)
    conn.commit()


def remove(conn, code, link_id: int, *, actor=None) -> None:
    r = _one(conn.execute("SELECT * FROM project_contact WHERE id = ? AND project_code = ? AND removed_at IS NULL",
                          (link_id, code)))
    if not r:
        raise LookupError("contact not found on this job")
    conn.execute("UPDATE project_contact SET removed_at = ?, removed_by = ?, is_primary = 0 WHERE id = ?",
                 (_now(), actor, link_id))
    if r["is_primary"]:   # the next one in line becomes primary
        side = "employee_id IS NOT NULL" if r["employee_id"] else "employee_id IS NULL"
        nxt = _one(conn.execute(f"SELECT id FROM project_contact WHERE project_code = ? AND role = ? AND {side} AND "
                                f"removed_at IS NULL ORDER BY id LIMIT 1", (code, r["role"])))
        if nxt:
            conn.execute("UPDATE project_contact SET is_primary = 1 WHERE id = ?", (nxt["id"],))
    conn.commit()


def lookup(conn, q: str, kind: str) -> list:
    """Picker search — names, titles and orgs only; never email or phone."""
    s = f"%{(q or '').strip().lower()}%"
    if kind == "org":
        return [{"id": r["id"], "name": r["name"], "type": r.get("relationship_type")} for r in _rows(conn.execute(
            "SELECT id, name, relationship_type FROM crm_organization WHERE LOWER(name) LIKE ? AND "
            "COALESCE(status, 'active') = 'active' ORDER BY name LIMIT 20", (s,)))]
    if kind == "employee":
        return [{"employee_id": r["employee_id"], "name": f"{r.get('worker_id') or ''} — {r.get('name') or ''}".strip(" —"),
                 "trade": r.get("trade")} for r in _rows(conn.execute(
            "SELECT employee_id, worker_id, name, trade FROM v_active_workers WHERE LOWER(COALESCE(name,'')) LIKE ? OR "
            "LOWER(COALESCE(worker_id,'')) LIKE ? ORDER BY worker_id LIMIT 20", (s, s)))]
    return [{"id": r["id"], "name": r["full_name"], "title": r.get("title"), "org": r.get("org_name")} for r in _rows(conn.execute(
        "SELECT c.id, c.full_name, c.title, o.name AS org_name FROM crm_contact c LEFT JOIN crm_organization o ON o.id = c.org_id "
        "WHERE (LOWER(c.full_name) LIKE ? OR LOWER(COALESCE(o.name,'')) LIKE ?) AND COALESCE(c.status, 'active') = 'active' "
        "ORDER BY c.full_name LIMIT 20", (s, s)))]


# ---------------------------------------------------------------- routes
def _uid():
    return (current_user() or {}).get("id")


def _run(fn, code=200):
    conn = db_layer.connect()
    try:
        return jsonify({"data": fn(conn)}), code
    except LookupError as e:
        conn.rollback(); return jsonify({"error": str(e)}), 404
    except PermissionError as e:
        conn.rollback(); return jsonify({"error": str(e)}), 409
    except ValueError as e:
        conn.rollback(); return jsonify({"error": str(e)}), 400
    finally:
        conn.close()


@requires_section("project_contacts")
def _api_list(project_code):
    def f(c):
        d = list_for_project(c, project_code, with_pii=True)
        if d is None:
            raise LookupError("project not found")
        return d
    return _run(f)


@requires_company
def _api_add(project_code):
    p = request.get_json(silent=True) or {}
    return _run(lambda c: (add(c, project_code, p, actor=_uid()), list_for_project(c, project_code, with_pii=True))[1], 201)


@requires_company
def _api_update(project_code, link_id):
    p = request.get_json(silent=True) or {}
    return _run(lambda c: (update(c, project_code, link_id, p), list_for_project(c, project_code, with_pii=True))[1])


@requires_company
def _api_remove(project_code, link_id):
    return _run(lambda c: (remove(c, project_code, link_id, actor=_uid()), list_for_project(c, project_code, with_pii=True))[1])


@requires_company
def _api_lookup(project_code):
    kind = request.args.get("kind") or "contact"
    return _run(lambda c: lookup(c, request.args.get("q") or "", kind if kind in ("contact", "org", "employee") else "contact"))


def register(app) -> None:
    conn = db_layer.connect()
    try:
        ensure(conn)
        db_layer._PKMAP_CACHE.clear()
    except Exception as e:
        log.warning("#357 project_contact ensure skipped: %s", e)
    finally:
        conn.close()
    base = "/api/projects/<project_code>/contacts"
    app.add_url_rule(base, "project_contacts_list", _api_list, methods=["GET"])
    app.add_url_rule(base, "project_contacts_add", _api_add, methods=["POST"])
    app.add_url_rule(f"{base}/lookup", "project_contacts_lookup", _api_lookup, methods=["GET"])
    app.add_url_rule(f"{base}/<int:link_id>", "project_contacts_update", _api_update, methods=["PATCH"])
    app.add_url_rule(f"{base}/<int:link_id>", "project_contacts_remove", _api_remove, methods=["DELETE"])
