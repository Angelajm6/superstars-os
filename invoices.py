_SELECT = ("SELECT i.*, o.name AS client_name, p.name AS project_name, "
           "       b.address_line AS building_address, e.code AS estimate_code, pr.number AS proposal_number "
           "FROM invoice i "
           "LEFT JOIN crm_organization o ON o.id = i.client_org_id "
           "LEFT JOIN projects p ON p.project_code = i.project_code "
           "LEFT JOIN building b ON b.id = i.building_id "
           "LEFT JOIN estimate e ON e.id = i.estimate_id "
           "LEFT JOIN proposal pr ON pr.id = i.proposal_id ")


def _decorate(r: dict, today: Optional[date] = None) -> dict:
    today = today or _today()
    t = today.isoformat()
    r["balance"] = round(_num(r.get("amount")) - _num(r.get("amount_paid")), 2)
    r["overdue"] = bool(r.get("status") == "issued" and r.get("due_at") and r["due_at"] < t)
    r["days_overdue"] = ((today - date.fromisoformat(r["due_at"])).days if r["overdue"] else 0)
    r["days_to_due"] = ((date.fromisoformat(r["due_at"]) - today).days
                        if r.get("status") == "issued" and r.get("due_at") else None)
    return r


def get(conn, invoice_id: int, *, today: Optional[date] = None) -> Optional[dict]:
    r = _one(conn.execute(_SELECT + "WHERE i.id = ?", (invoice_id,)))
    if not r:
        return None
    r = _decorate(r, today)
    r["payments"] = _rows(conn.execute(
        "SELECT id, amount, paid_on, method, reference, notes, created_by, created_at "
        "FROM invoice_payment WHERE invoice_id = ? ORDER BY paid_on, id", (invoice_id,)))
    return r


def list_invoices(conn, *, status=None, kind=None, client_org_id=None, project_code=None, proposal_id=None,
                  overdue_only=False, search=None, limit=500, today: Optional[date] = None) -> list:
    today = today or _today()
    where, params = ["1=1"], []
    if status == "open":
        where.append("i.status = 'issued'")
    elif status:
        where.append("i.status = ?"); params.append(status)
    if kind:
        where.append("i.kind = ?"); params.append(kind)
    if client_org_id:
        where.append("i.client_org_id = ?"); params.append(int(client_org_id))
    if project_code:
        where.append("i.project_code = ?"); params.append(project_code)
    if proposal_id:
        where.append("i.proposal_id = ?"); params.append(int(proposal_id))
    if overdue_only:
        where.append("i.status = 'issued' AND i.due_at IS NOT NULL AND i.due_at < ?"); params.append(today.isoformat())
    if search:
        s = f"%{search.strip().lower()}%"
        where.append("(LOWER(i.number) LIKE ? OR LOWER(COALESCE(i.description,'')) LIKE ? OR LOWER(COALESCE(o.name,'')) LIKE ? "
                     "OR LOWER(COALESCE(i.project_code,'')) LIKE ? OR LOWER(COALESCE(b.address_line,'')) LIKE ?)")
        params += [s, s, s, s, s]
    params.append(int(limit))
    rows = _rows(conn.execute(
        _SELECT + "WHERE " + " AND ".join(where) +
        " ORDER BY CASE i.status WHEN 'issued' THEN 0 WHEN 'draft' THEN 1 WHEN 'paid' THEN 2 ELSE 3 END, "
        "         i.due_at, i.id DESC LIMIT ?", params))
    return [_decorate(r, today) for r in rows]


def receivables_summary(conn, *, today: Optional[date] = None, horizon_days: int = 30) -> dict:
    """The numbers the Overview and Finance KPIs show. Open = issued and not paid."""
    today = today or _today()
    t = today.isoformat()
    h = (today + timedelta(days=horizon_days)).isoformat()
    y = t[:4] + "-01-01"
    o = _one(conn.execute(
        "SELECT COUNT(1) AS n, COALESCE(SUM(amount - amount_paid),0) AS v, "
        "  SUM(CASE WHEN due_at IS NOT NULL AND due_at < ? THEN 1 ELSE 0 END) AS od_n, "
        "  COALESCE(SUM(CASE WHEN due_at IS NOT NULL AND due_at < ? THEN amount - amount_paid ELSE 0 END),0) AS od_v, "
        "  SUM(CASE WHEN due_at IS NOT NULL AND due_at >= ? AND due_at <= ? THEN 1 ELSE 0 END) AS soon_n, "
        "  COALESCE(SUM(CASE WHEN due_at IS NOT NULL AND due_at >= ? AND due_at <= ? THEN amount - amount_paid ELSE 0 END),0) AS soon_v, "
        "  SUM(CASE WHEN kind = 'deposit' THEN 1 ELSE 0 END) AS dep_n, "
        "  COALESCE(SUM(CASE WHEN kind = 'deposit' THEN amount - amount_paid ELSE 0 END),0) AS dep_v "
        "FROM invoice WHERE status = 'issued'", (t, t, t, h, t, h))) or {}
    d = _one(conn.execute(
        "SELECT COUNT(1) AS n, COALESCE(SUM(amount),0) AS v FROM invoice WHERE status = 'draft'")) or {}
    p = _one(conn.execute(
        "SELECT COUNT(1) AS n, COALESCE(SUM(amount),0) AS v FROM invoice_payment WHERE paid_on >= ?", (y,))) or {}
    return {
        "open_count": int(o.get("n") or 0), "open_value": round(_num(o.get("v")), 2),
        "overdue_count": int(o.get("od_n") or 0), "overdue_value": round(_num(o.get("od_v")), 2),
        "due_soon_count": int(o.get("soon_n") or 0), "due_soon_value": round(_num(o.get("soon_v")), 2),
        "horizon_days": horizon_days,
        "awaiting_deposit_count": int(o.get("dep_n") or 0), "awaiting_deposit_value": round(_num(o.get("dep_v")), 2),
        "draft_count": int(d.get("n") or 0), "draft_value": round(_num(d.get("v")), 2),
        "collected_ytd_count": int(p.get("n") or 0), "collected_ytd_value": round(_num(p.get("v")), 2),
    }


