def next_number(conn, today: Optional[date] = None) -> str:
    """INV-YYYY-#### — per-year sequence, numeric max (CLAUDE.md ID rule)."""
    year = (today or _today()).strftime("%Y")
    prefix = f"INV-{year}-"
    rows = conn.execute("SELECT number FROM invoice WHERE number LIKE ?", (prefix + "%",)).fetchall()
    mx = 0
    for r in rows:
        tail = str(r[0] if not hasattr(r, "keys") else r["number"])[len(prefix):]
        if tail.isdigit():
            mx = max(mx, int(tail))
    return f"{prefix}{mx + 1:04d}"


