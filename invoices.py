def _validate(fields: dict, *, partial: bool = False) -> dict:
    out = {}
    if "kind" in fields or not partial:
        k = (fields.get("kind") or "other").strip().lower()
        if k not in KINDS:
            raise ValueError("kind must be one of " + ", ".join(KINDS))
        out["kind"] = k
    if "client_org_id" in fields or not partial:
        try:
            out["client_org_id"] = int(fields.get("client_org_id"))
        except (TypeError, ValueError):
            raise ValueError("client_org_id is required")
    if "amount" in fields or not partial:
        try:
            a = round(float(fields.get("amount")), 2)
        except (TypeError, ValueError):
            raise ValueError("amount is required")
        if a <= 0:
            raise ValueError("amount must be greater than zero")
        out["amount"] = a
    if "retainage" in fields:
        try:
            r = round(float(fields.get("retainage") or 0), 2)
        except (TypeError, ValueError):
            raise ValueError("retainage must be a number")
        if r < 0:
            raise ValueError("retainage cannot be negative")
        out["retainage"] = r
    for k in ("project_code", "description", "notes", "source_doc"):
        if k in fields:
            v = fields.get(k)
            out[k] = (str(v).strip()[:2000] or None) if v not in (None, "") else None
    for k in ("building_id", "estimate_id", "proposal_id"):
        if k in fields:
            v = fields.get(k)
            if v in (None, ""):
                out[k] = None
            else:
                try:
                    out[k] = int(v)
                except (TypeError, ValueError):
                    raise ValueError(f"{k} must be an integer")
    if "due_at" in fields:
        out["due_at"] = _iso_date(fields.get("due_at"))
    return out


def create(conn, fields: dict, *, created_by=None) -> dict:
    f = _validate(fields)
    if not crm.get_org(conn, f["client_org_id"]):
        raise LookupError("client organization not found")
    now = _now()
    number = next_number(conn)
    conn.execute(
        "INSERT INTO invoice (number, kind, status, client_org_id, project_code, building_id, estimate_id, "
        "proposal_id, source_doc, description, amount, retainage, amount_paid, due_at, notes, created_by, "
        "created_at, updated_at) VALUES (?,?,'draft',?,?,?,?,?,?,?,?,?,0,?,?,?,?,?)",
        (number, f["kind"], f["client_org_id"], f.get("project_code"), f.get("building_id"), f.get("estimate_id"),
         f.get("proposal_id"), f.get("source_doc"), f.get("description"), f["amount"], f.get("retainage", 0),
         f.get("due_at"), f.get("notes"), created_by, now, now))
    conn.commit()
    r = get(conn, _one(conn.execute("SELECT id FROM invoice WHERE number = ?", (number,)))["id"])
    _activity(conn, r["client_org_id"], f"Invoice {number} drafted — {r['kind'].replace('_', ' ')} {_money(r['amount'])}",
              actor=created_by)
    return r


def create_from_proposal(conn, proposal: dict, *, created_by=None) -> Optional[dict]:
    """The #307 trigger: a signed proposal with deposit terms drafts its deposit invoice
    once (idempotent per proposal). Returns None when there is nothing to bill."""
    amt = _num(proposal.get("deposit_amount"))
    if amt <= 0:
        return None
    existing = _one(conn.execute(
        "SELECT id FROM invoice WHERE proposal_id = ? AND kind = 'deposit' AND status <> 'void'", (proposal["id"],)))
    if existing:
        return get(conn, existing["id"])
    label = (proposal.get("building_address_line") or proposal.get("building_address")
             or proposal.get("client_name") or proposal.get("number"))
    pct = proposal.get("deposit_pct")
    pct_txt = f"{'%g' % float(pct)}% " if pct not in (None, "") else ""
    return create(conn, {
        "kind": "deposit", "client_org_id": proposal["client_org_id"],
        "project_code": proposal.get("converted_project_code") or proposal.get("project_code"),
        "building_id": proposal.get("building_id"), "estimate_id": proposal.get("estimate_id"),
        "proposal_id": proposal["id"], "source_doc": f"proposal:{proposal['id']}",
        "description": f"Deposit {pct_txt}on proposal {_proposal_label(proposal)} — {label}",
        "amount": amt,
    }, created_by=created_by)


def update(conn, invoice_id: int, fields: dict, *, actor=None) -> dict:
    r = get(conn, invoice_id)
    if not r:
        raise LookupError("invoice not found")
    if r["status"] == "draft":
        f = _validate({k: v for k, v in fields.items() if k in EDITABLE}, partial=True)
    elif r["status"] == "issued":
        allowed = {k: v for k, v in fields.items() if k in ("due_at", "notes", "description", "qb_invoice_id", "qb_status")}
        f = _validate({k: v for k, v in allowed.items() if k in ("due_at", "notes", "description")}, partial=True)
        for k in ("qb_invoice_id", "qb_status"):
            if k in allowed:
                f[k] = (str(allowed[k]).strip()[:200] or None) if allowed[k] not in (None, "") else None
    else:
        raise ValueError(f"a {r['status']} invoice cannot be edited")
    if not f:
        return r
    sets = ", ".join(f"{k} = ?" for k in f)
    conn.execute(f"UPDATE invoice SET {sets}, updated_at = ? WHERE id = ?", (*f.values(), _now(), invoice_id))
    conn.commit()
    return get(conn, invoice_id)


def issue(conn, invoice_id: int, *, issued_on=None, due_on=None, actor=None) -> dict:
    r = get(conn, invoice_id)
    if not r:
        raise LookupError("invoice not found")
    if r["status"] != "draft":
        raise ValueError(f"only a draft can be issued (this one is {r['status']})")
    if _num(r["amount"]) <= 0:
        raise ValueError("set an amount before issuing")
    issued = _iso_date(issued_on) or _today().isoformat()
    due = _iso_date(due_on) or r.get("due_at")
    if not due:
        days = DEPOSIT_NET_DAYS if r["kind"] == "deposit" else NET_DAYS_DEFAULT
        due = (date.fromisoformat(issued) + timedelta(days=days)).isoformat()
    if due < issued:
        raise ValueError("the due date cannot be before the issue date")
    conn.execute("UPDATE invoice SET status = 'issued', issued_at = ?, due_at = ?, updated_at = ? WHERE id = ?",
                 (issued, due, _now(), invoice_id))
    conn.commit()
    r = get(conn, invoice_id)
    _activity(conn, r["client_org_id"], f"Invoice {r['number']} issued — {_money(r['amount'])}, due {due}", actor=actor)
    _quickbooks("issued", invoice_id)
    return r


def record_payment(conn, invoice_id: int, *, amount, paid_on=None, method=None, reference=None, notes=None,
                   actor=None, qb_payment_id=None) -> dict:
    """qb_payment_id: the payment came FROM QuickBooks (#316) — stored with source 'quickbooks'
    and not sent back; any other payment is mirrored to QuickBooks when it is connected."""
    r = get(conn, invoice_id)
    if not r:
        raise LookupError("invoice not found")
    if r["status"] != "issued":
        raise ValueError(f"payments can only be recorded on an issued invoice (this one is {r['status']})")
    try:
        amt = round(float(amount), 2)
    except (TypeError, ValueError):
        raise ValueError("amount is required")
    if amt <= 0:
        raise ValueError("amount must be greater than zero")
    if amt > r["balance"] + 0.005:
        raise ValueError(f"that is more than the {_money(r['balance'])} still open on this invoice")
    paid = _iso_date(paid_on) or _today().isoformat()
    method = (method or "").strip().lower() or None
    if method and method not in METHODS:
        raise ValueError("method must be one of " + ", ".join(METHODS))
    now = _now()
    conn.execute("INSERT INTO invoice_payment (invoice_id, amount, paid_on, method, reference, notes, created_by, "
                 "created_at) VALUES (?,?,?,?,?,?,?,?)",
                 (invoice_id, amt, paid, method, (reference or "").strip()[:200] or None,
                  (notes or "").strip()[:2000] or None, actor, now))
    if qb_payment_id:
        conn.execute("UPDATE invoice_payment SET qb_payment_id = ?, source = 'quickbooks' WHERE id = "
                     "(SELECT MAX(id) FROM invoice_payment WHERE invoice_id = ?)", (str(qb_payment_id), invoice_id))
    total = _num(_one(conn.execute("SELECT COALESCE(SUM(amount),0) AS v FROM invoice_payment WHERE invoice_id = ?",
                                   (invoice_id,)))["v"])
    fully = total >= _num(r["amount"]) - 0.005
    conn.execute("UPDATE invoice SET amount_paid = ?, status = ?, paid_at = ?, updated_at = ? WHERE id = ?",
                 (round(total, 2), "paid" if fully else "issued", paid if fully else None, now, invoice_id))
    conn.commit()
    r = get(conn, invoice_id)
    _activity(conn, r["client_org_id"],
              f"Payment {_money(amt)} on invoice {r['number']}" + (" — paid in full" if fully else f" — {_money(r['balance'])} open"),
              actor=actor)
    if fully and r["kind"] == "deposit":
        _mark_ira_deposit(conn, r, paid)
    if not qb_payment_id:
        _quickbooks("paid_here", invoice_id)
    return r


def _mark_ira_deposit(conn, r: dict, paid_on: str) -> None:
    """A paid deposit invoice satisfies the IRA job's deposit flag (#274) when the
    project is known. Best effort: the table may not exist on a fresh DB."""
    code = r.get("project_code")
    if not code:
        return
    try:
        conn.execute("UPDATE ira_job SET deposit_received = 1, deposit_date = COALESCE(deposit_date, ?), "
                     "updated_at = ? WHERE project_code = ? AND COALESCE(deposit_received,0) = 0",
                     (paid_on, _now(), code))
        conn.commit()
    except Exception as e:
        log.info("#315 ira_job deposit flag skipped: %s", e)


def void(conn, invoice_id: int, *, reason=None, actor=None) -> dict:
    r = get(conn, invoice_id)
    if not r:
        raise LookupError("invoice not found")
    if r["status"] not in ("draft", "issued"):
        raise ValueError(f"a {r['status']} invoice cannot be voided")
    if _num(r["amount_paid"]) > 0:
        raise ValueError("an invoice with payments cannot be voided — record the remaining balance or leave it open")
    reason = (reason or "").strip()[:1000] or None
    notes = (r.get("notes") or "")
    if reason:
        notes = (notes + "\n" if notes else "") + f"Voided: {reason}"
    conn.execute("UPDATE invoice SET status = 'void', voided_at = ?, notes = ?, updated_at = ? WHERE id = ?",
                 (_now(), notes or None, _now(), invoice_id))
    conn.commit()
    r = get(conn, invoice_id)
    _activity(conn, r["client_org_id"], f"Invoice {r['number']} voided" + (f": {reason}" if reason else ""), actor=actor)
    _quickbooks("voided", invoice_id)
    return r


def _quickbooks(event: str, invoice_id: int) -> None:
    """#316 — mirror the change in QuickBooks when it is connected. Never blocks the app write."""
    try:
        import qbo
        qbo.after(event, invoice_id)
    except Exception as e:
        log.warning("#316 quickbooks %s for invoice %s skipped: %s", event, invoice_id, type(e).__name__)


def delete_draft(conn, invoice_id: int) -> None:
    r = get(conn, invoice_id)
    if not r:
        raise LookupError("invoice not found")
    if r["status"] != "draft":
        raise ValueError("only a draft can be deleted — void it instead")
    conn.execute("DELETE FROM invoice_payment WHERE invoice_id = ?", (invoice_id,))
    conn.execute("DELETE FROM invoice WHERE id = ?", (invoice_id,))
    conn.commit()


