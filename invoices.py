def _api_list():
    a = request.args
    status = (a.get("status") or "").strip().lower() or None
    if status and status not in STATUSES + ("open",):
        return _err("status must be one of open, " + ", ".join(STATUSES))
    kind = (a.get("kind") or "").strip().lower() or None
    if kind and kind not in KINDS:
        return _err("kind must be one of " + ", ".join(KINDS))
    try:
        org = int(a.get("client_org_id")) if a.get("client_org_id") else None
        pid = int(a.get("proposal_id")) if a.get("proposal_id") else None
        limit = int(a.get("limit") or 500)
    except ValueError:
        return _err("ids and limit must be integers")
    conn = _conn()
    try:
        rows = list_invoices(conn, status=status, kind=kind, client_org_id=org,
                             project_code=(a.get("project") or "").strip() or None, proposal_id=pid,
                             overdue_only=a.get("overdue") == "1", search=(a.get("search") or "").strip() or None,
                             limit=limit)
        return _wrap(rows, summary=receivables_summary(conn))
    finally:
        conn.close()


