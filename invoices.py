# ---------------------------------------------------------------- helpers
def _conn():
    return db_layer.connect()


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _today() -> date:
    return date.today()


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def _num(v) -> float:
    try:
        return float(v or 0)
    except (TypeError, ValueError):
        return 0.0


def _money(v) -> str:
    try:
        return "${:,.2f}".format(float(v))
    except (TypeError, ValueError):
        return "$0.00"


def _iso_date(v) -> Optional[str]:
    """Accept YYYY-MM-DD (or None); anything else raises ValueError."""
    if v in (None, ""):
        return None
    s = str(v).strip()[:10]
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
        raise ValueError("dates must be YYYY-MM-DD")
    date.fromisoformat(s)
    return s


def _err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


def _wrap(data, **meta):
    m = {"generated_at": _now()}
    if isinstance(data, list):
        m["count"] = len(data)
        data = [_scrub(d) for d in data]
    elif isinstance(data, dict):
        data = _scrub(data)
    m.update(meta)
    return jsonify({"data": data, "meta": m})


def _scrub(d: dict) -> dict:
    """#326 — the document columns are server-only; the API carries flags instead."""
    if not isinstance(d, dict) or "number" not in d:
        return d
    import invoice_docs
    return invoice_docs.public(d)


def _uid():
    u = current_user()
    return u["id"] if u else None


