"""#315 — Invoices & receivables.

ROADMAP Phase B: "what needs to get paid / any due invoice" becomes a real query
instead of a QuickBooks screenshot. One row per invoice the company issues to a
client, with the payments recorded against it.

  invoice           id, number (INV-YYYY-####), kind (deposit | progress | final |
                    change_order | other), status (draft | issued | paid | void),
                    client_org_id, project_code, building_id, estimate_id,
                    proposal_id, source_doc, description, amount, retainage,
                    amount_paid, issued_at, due_at, paid_at, voided_at,
                    qb_invoice_id, qb_status, notes, created_by, created_at,
                    updated_at
  invoice_payment   id, invoice_id, amount, paid_on, method, reference, notes,
                    created_by, created_at

Lifecycle: draft → issued → paid; draft or issued → void. Payments only land on an
issued invoice; the invoice flips to paid when the payments cover the amount.
`overdue` is derived (issued, past due_at), never stored.

The proposal trigger (#307 `_on_signed`) now drafts the deposit invoice here so
the "Issue deposit invoice" task points at a real row; #316 (QuickBooks phase 1)
pushes issued invoices to QuickBooks Online and fills `qb_invoice_id`/`qb_status`.

Money-out (payables) is #319; this module is money-in only. Comp data is not
involved — invoices are client-facing amounts.

Access: every endpoint sits behind `requires_section('company_portal')`
(admin / c_suite). The client portal does not read these rows yet.
"""
