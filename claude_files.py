"""Files attached to a Claude conversation (accepted 2026-10-15): drawings, bid forms, contracts, photos.

A person attaches up to 5 files to a message (PDF, photos, Word, Excel, CSV, text; 20 MB each).
They are stored ENCRYPTED on the data disk and only the person who attached them can open them.
Claude receives them with the message: PDFs and pictures as they are (uploaded once to the
Anthropic Files API, with an expiry, so a long conversation does not resend them), Word / Excel /
CSV / text as their text. A file reaches a record (a bid's documents) only through an approval
card. Logs carry ids, kinds and sizes only, never names or contents.
"""
from __future__ import annotations

import base64
import io
import json
import logging
import re
import secrets
import zipfile
from datetime import datetime, timedelta
from typing import Optional

from flask import jsonify, request, send_file

import assistant
import db_layer
import secret_box
import ssc_paths
from auth import current_user, requires_role

log = logging.getLogger("ssc.claude_files")

ROLES = ("admin", "c_suite", "pm", "super")   # who has Claude (claude_agent.TEAM_ROLES)
MAX_BYTES = 20 * 1024 * 1024
MAX_PER_MESSAGE = 5
MAX_TEXT_CHARS = 200_000          # Word / Excel / CSV / text: about 50k tokens
PDF_PAGE_LIMIT = 100              # longer PDFs go to Claude as their text
IMG_MAX_EDGE = 2000
API_TTL = 30 * 24 * 3600          # the Anthropic copy expires by itself; re-sent if needed
ORPHAN_AGE = timedelta(days=1)    # attached but never sent: removed
EXT = {".pdf": "pdf", ".png": "image", ".jpg": "image", ".jpeg": "image", ".heic": "image", ".heif": "image",
       ".webp": "image", ".gif": "image", ".docx": "word", ".xlsx": "excel", ".xlsm": "excel", ".xls": "excel",
       ".csv": "text", ".txt": "text", ".eml": "text", ".md": "text"}
MIME = {".pdf": "application/pdf", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
        ".heic": "image/heic", ".heif": "image/heif", ".webp": "image/webp", ".gif": "image/gif",
        ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        ".xlsm": "application/vnd.ms-excel.sheet.macroEnabled.12", ".xls": "application/vnd.ms-excel", ".csv": "text/csv", ".txt": "text/plain",
        ".eml": "message/rfc822", ".md": "text/markdown"}
ACCEPT = ", ".join(sorted(EXT))


def ensure(conn) -> None:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS claude_file ({pk}, user_id INTEGER NOT NULL, chat_id INTEGER, message_id INTEGER, "
        f"name TEXT NOT NULL, ext TEXT NOT NULL, mime TEXT, size INTEGER NOT NULL, kind TEXT NOT NULL, pages INTEGER, "
        f"as_text INTEGER NOT NULL DEFAULT 0, path TEXT NOT NULL, text_enc TEXT, api_file_id TEXT, api_expires_at TEXT, "
        f"created_at TEXT NOT NULL)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_claude_file_chat ON claude_file(chat_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_claude_file_user ON claude_file(user_id)")
    conn.commit()


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _one(conn, sql, params=()) -> Optional[dict]:
    r = conn.execute(sql, params).fetchone()
    return dict(r) if r else None


def _rows(conn, sql, params=()) -> list:
    return [dict(r) for r in conn.execute(sql, params).fetchall()]


def _size(n: int) -> str:
    return f"{n / 1048576:.1f} MB" if n >= 1048576 else f"{max(1, round(n / 1024))} KB"


def public(r: dict) -> dict:
    """What the chat shows on a file chip."""
    what = {"pdf": "PDF", "image": "Photo", "word": "Word", "excel": "Excel", "text": "Text"}[r["kind"]]
    pages = f"{r['pages']} page{'s' if r['pages'] != 1 else ''} · " if r.get("pages") else ""
    return {"id": r["id"], "name": r["name"], "kind": r["kind"], "size": r["size"],
            "label": f"{pages}{_size(r['size'])}" + (" · read as text" if r.get("as_text") else ""),
            "type": what, "url": f"/api/claude/files/{r['id']}"}


# ------------------------------------------------------------------ reading what is inside
def _docx_text(data: bytes) -> str:
    import xml.etree.ElementTree as ET
    w = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        root = ET.fromstring(z.read("word/document.xml"))
    out = []
    for p in root.iter(w + "p"):
        parts = []
        for el in p.iter():
            if el.tag == w + "t" and el.text:
                parts.append(el.text)
            elif el.tag in (w + "tab",):
                parts.append("\t")
            elif el.tag in (w + "br", w + "cr"):
                parts.append("\n")
        out.append("".join(parts))
    return "\n".join(out)


def _xlsx_text(data: bytes) -> str:
    import openpyxl
    wb = openpyxl.load_workbook(io.BytesIO(data), read_only=True, data_only=True)
    out = []
    try:
        for ws in wb.worksheets:
            out.append(f"## Sheet: {ws.title}")
            for i, row in enumerate(ws.iter_rows(values_only=True)):
                if i >= 5000:
                    out.append("… (more rows not shown)")
                    break
                cells = ["" if v is None else str(v) for v in row[:60]]
                while cells and cells[-1] == "":
                    cells.pop()
                if cells:
                    out.append("\t".join(cells))
            if sum(len(x) for x in out) > MAX_TEXT_CHARS:
                break
    finally:
        wb.close()
    return "\n".join(out)


def _pdf_info(data: bytes) -> tuple:
    """(pages, text when it is too long to send as a PDF)."""
    import pypdf
    try:
        reader = pypdf.PdfReader(io.BytesIO(data))
        if reader.is_encrypted:
            raise ValueError("This PDF is password protected. Save a copy without the password and attach that.")
        n = len(reader.pages)
    except ValueError:
        raise
    except Exception:
        raise ValueError("This PDF could not be opened. Try saving it again as a PDF.")
    if n <= PDF_PAGE_LIMIT:
        return n, None
    text = []
    for i, page in enumerate(reader.pages):
        try:
            text.append(f"--- page {i + 1} ---\n" + (page.extract_text() or ""))
        except Exception:
            text.append(f"--- page {i + 1} --- (no text)")
        if sum(len(t) for t in text) > MAX_TEXT_CHARS:
            break
    return n, "\n".join(text)


def _image_for_model(data: bytes) -> tuple:
    """(bytes, mime): a JPEG at most IMG_MAX_EDGE on the long side (HEIC from iPhones included)."""
    from PIL import Image, ImageOps
    try:
        import pillow_heif
        pillow_heif.register_heif_opener()
    except Exception:
        pass
    im = ImageOps.exif_transpose(Image.open(io.BytesIO(data)))
    if im.mode not in ("RGB", "L"):
        bg = Image.new("RGB", im.size, (255, 255, 255))
        im = im.convert("RGBA")
        bg.paste(im, mask=im.split()[-1])
        im = bg
    im.thumbnail((IMG_MAX_EDGE, IMG_MAX_EDGE))
    out = io.BytesIO()
    im.convert("RGB").save(out, "JPEG", quality=85)
    return out.getvalue(), "image/jpeg"


# ------------------------------------------------------------------ storing
def _path(uid: int) -> tuple:
    rel_dir = ssc_paths.under_root("data_room", "claude_files", str(int(uid)))
    rel_dir.mkdir(parents=True, exist_ok=True)
    p = rel_dir / (secrets.token_hex(16) + ".bin")
    return p, ssc_paths.store_rel(p)


def store(conn, uid: int, filename: str, data: bytes) -> dict:
    """Check, read and keep one attached file (encrypted). Raises ValueError with a message for the person."""
    name = re.sub(r"[\x00-\x1f/\\]", "", (filename or "").strip())[-150:] or "file"
    ext = ("." + name.rsplit(".", 1)[-1].lower()) if "." in name else ""
    kind = EXT.get(ext)
    if not kind:
        raise ValueError("Claude reads PDF, photos, Word, Excel, CSV and text files. Save it as one of those and attach it again.")
    if not data:
        raise ValueError("That file is empty.")
    if len(data) > MAX_BYTES:
        raise ValueError(f"{name} is {_size(len(data))}. Files can be up to 20 MB; split it or attach the pages you need.")
    pages, text, as_text = None, None, 0
    try:
        if kind == "pdf":
            pages, text = _pdf_info(data)
            as_text = 1 if text is not None else 0
        elif kind == "image":
            _image_for_model(data)   # proves it opens
        elif kind == "word":
            text = _docx_text(data)
        elif kind == "excel" and ext == ".xls":
            import sheet_read   # Excel 97-2003 (xlrd)
            text = sheet_read.text(data, ext, max_chars=MAX_TEXT_CHARS)
        elif kind == "excel":
            text = _xlsx_text(data)
        else:
            text = data.decode("utf-8", errors="replace")
    except ValueError:
        raise
    except Exception as e:
        log.info("claude file (%s, %s bytes) could not be read: %s", kind, len(data), type(e).__name__)
        raise ValueError(f"{name} could not be opened. Check the file and attach it again.")
    if text is not None:
        text = text[:MAX_TEXT_CHARS]
        if kind != "pdf" and not text.strip():
            raise ValueError(f"{name} has no text Claude can read.")
    full, rel = _path(uid)
    full.write_bytes(secret_box.encrypt_bytes(data))
    conn.execute("INSERT INTO claude_file (user_id, name, ext, mime, size, kind, pages, as_text, path, text_enc, created_at) "
                 "VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                 (uid, name, ext, MIME.get(ext), len(data), kind, pages, as_text, rel,
                  secret_box.encrypt_text(text) if text is not None else None, _now()))
    conn.commit()
    r = _one(conn, "SELECT * FROM claude_file WHERE user_id = ? AND path = ?", (uid, rel))
    log.info("claude file %s stored for user %s (%s, %s bytes)", r["id"], uid, kind, len(data))
    return r


def read_bytes(r: dict) -> bytes:
    return secret_box.decrypt_bytes(ssc_paths.resolve_data_path(r["path"]).read_bytes())


def text_of(r: dict) -> str:
    return secret_box.decrypt_text(r["text_enc"]) if r.get("text_enc") else ""


def remove(conn, r: dict) -> None:
    try:
        ssc_paths.resolve_data_path(r["path"]).unlink(missing_ok=True)
    except OSError:
        pass
    conn.execute("DELETE FROM claude_file WHERE id = ?", (r["id"],))
    conn.commit()


def prune_orphans(conn, uid: int) -> int:
    """Files attached but never sent, older than a day."""
    cut = (datetime.now() - ORPHAN_AGE).isoformat(timespec="seconds")
    rows = _rows(conn, "SELECT * FROM claude_file WHERE user_id = ? AND message_id IS NULL AND created_at < ?", (uid, cut))
    for r in rows:
        remove(conn, r)
    return len(rows)


def owned(conn, uid: int, ids) -> list:
    """The person's own files, in the order given; raises LookupError for any other id."""
    out = []
    for i in ids:
        r = _one(conn, "SELECT * FROM claude_file WHERE id = ? AND user_id = ?", (int(i), uid))
        if not r:
            raise LookupError("one of those files is not yours or no longer exists")
        out.append(r)
    return out


def for_chat(conn, chat_id: int) -> list:
    return [public(r) for r in _rows(conn, "SELECT * FROM claude_file WHERE chat_id = ? AND message_id IS NOT NULL "
                                           "ORDER BY id", (chat_id,))]


def by_ids(conn, ids) -> dict:
    ids = [int(i) for i in ids if str(i).isdigit()]
    if not ids:
        return {}
    return {r["id"]: r for r in _rows(conn, f"SELECT * FROM claude_file WHERE id IN ({','.join('?' * len(ids))})", ids)}


# ------------------------------------------------------------------ what Claude receives
def _upload(name: str, data: bytes, mime: str) -> str:
    """One copy at Anthropic (Files API), gone by itself after API_TTL. Tests replace this."""
    import anthropic
    meta = anthropic.Anthropic().files.upload(file=(name, data, mime), expires_in_seconds=API_TTL)
    return meta.id


def _source(conn, r: dict, data: bytes, mime: str) -> dict:
    fresh = r.get("api_file_id") and r.get("api_expires_at") and \
        datetime.fromisoformat(r["api_expires_at"]) > datetime.now() + timedelta(hours=1)
    if fresh:
        return {"type": "file", "file_id": r["api_file_id"]}
    if not assistant._fake():
        try:
            fid = _upload(r["name"], data, mime)
            exp = (datetime.now() + timedelta(seconds=API_TTL)).isoformat(timespec="seconds")
            conn.execute("UPDATE claude_file SET api_file_id = ?, api_expires_at = ? WHERE id = ?", (fid, exp, r["id"]))
            conn.commit()
            r["api_file_id"], r["api_expires_at"] = fid, exp
            return {"type": "file", "file_id": fid}
        except Exception as e:   # sent with the message instead
            log.warning("claude file %s upload failed: %s", r["id"], type(e).__name__)
    return {"type": "base64", "media_type": mime, "data": base64.b64encode(data).decode("ascii")}


def blocks(conn, r: dict) -> list:
    """The content blocks for one file, as the model reads it."""
    try:
        if r["kind"] in ("word", "excel", "text") or r.get("as_text"):
            return [{"type": "document", "title": r["name"],
                     "source": {"type": "text", "media_type": "text/plain", "data": text_of(r) or "(no text)"}}]
        data = read_bytes(r)
        if r["kind"] == "pdf":
            return [{"type": "document", "title": r["name"], "source": _source(conn, r, data, "application/pdf")}]
        img, mime = _image_for_model(data)
        return [{"type": "image", "source": _source(conn, r, img, mime)}]
    except Exception as e:
        log.warning("claude file %s could not be prepared: %s", r["id"], type(e).__name__)
        return [{"type": "text", "text": f"[The attached file {r['name']} could not be read. Ask the person to attach it again.]"}]


# ------------------------------------------------------------------ routes
def _me() -> dict:
    u = current_user() or {}
    return {"id": u.get("id"), "role": u.get("role")}


def _conn():
    conn = db_layer.connect(pragma_fk=True)
    ensure(conn)
    return conn


@requires_role(*ROLES)
def _api_upload():
    me = _me()
    f = request.files.get("file")
    if not f:
        return jsonify({"error": "Choose a file to attach"}), 400
    data = f.read(MAX_BYTES + 1)
    conn = _conn()
    try:
        prune_orphans(conn, me["id"])
        try:
            r = store(conn, me["id"], f.filename or "file", data)
        except ValueError as e:
            return jsonify({"error": str(e)}), 400
        return jsonify({"data": public(r)}), 201
    finally:
        conn.close()


@requires_role(*ROLES)
def _api_get(file_id):
    me = _me()
    conn = _conn()
    try:
        r = _one(conn, "SELECT * FROM claude_file WHERE id = ? AND user_id = ?", (file_id, me["id"]))
        if not r:
            return jsonify({"error": "not found"}), 404
        data = read_bytes(r)
    finally:
        conn.close()
    inline = r["kind"] in ("pdf", "image") and r["ext"] not in (".heic", ".heif") and request.args.get("download") != "1"
    resp = send_file(io.BytesIO(data), mimetype=r["mime"] or "application/octet-stream", as_attachment=not inline,
                     download_name=r["name"])
    resp.headers["Cache-Control"] = "private, no-store"
    resp.headers["X-Content-Type-Options"] = "nosniff"
    resp.headers["Content-Security-Policy"] = "default-src 'none'; img-src 'self' data:; style-src 'unsafe-inline'; sandbox"
    return resp


@requires_role(*ROLES)
def _api_delete(file_id):
    """Take a file off before sending (sent files stay with their conversation)."""
    me = _me()
    conn = _conn()
    try:
        r = _one(conn, "SELECT * FROM claude_file WHERE id = ? AND user_id = ?", (file_id, me["id"]))
        if not r:
            return jsonify({"error": "not found"}), 404
        if r["message_id"]:
            return jsonify({"error": "That file was already sent; it stays with the conversation."}), 409
        remove(conn, r)
        return jsonify({"data": {"removed": file_id}})
    finally:
        conn.close()


def register(app) -> None:
    app.add_url_rule("/api/claude/files", "claude_file_upload", _api_upload, methods=["POST"])
    app.add_url_rule("/api/claude/files/<int:file_id>", "claude_file_get", _api_get, methods=["GET"])
    app.add_url_rule("/api/claude/files/<int:file_id>", "claude_file_delete", _api_delete, methods=["DELETE"])
