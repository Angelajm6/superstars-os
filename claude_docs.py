def _uid():
    return (current_user() or {}).get("id")


@requires_role(*ROLES)
def _api_get(did):
    conn = _conn()
    try:
        d = get(conn, _uid(), did)
        if not d:
            return jsonify({"error": "not found"}), 404
        return jsonify({"data": {"id": d["id"], "title": d["title"], "html": page(d, edit=True), "updated_at": d["updated_at"]}})
    finally:
        conn.close()


@requires_role(*ROLES)
def _api_patch(did):
    body = request.get_json(silent=True) or {}
    conn = _conn()
    try:
        r = update(conn, _uid(), did, html=body.get("html"), title=body.get("title"))
        d = get(conn, _uid(), did)
        return jsonify({"data": dict(r, updated_at=d["updated_at"])})
    except LookupError:
        return jsonify({"error": "not found"}), 404
    except ValueError as e:
        return jsonify({"error": str(e)}), 400
    finally:
        conn.close()


@requires_role(*ROLES)
def _api_pdf(did):
    conn = _conn()
    try:
        d = get(conn, _uid(), did)
    finally:
        conn.close()
    if not d:
        return jsonify({"error": "not found"}), 404
    try:
        data = pdf_bytes(d)
    except ValueError as e:
        return jsonify({"error": str(e)}), 503
    resp = send_file(io.BytesIO(data), mimetype="application/pdf", as_attachment=True, download_name=file_name(d, ".pdf"))
    resp.headers["Cache-Control"] = "no-store"
    return resp


@requires_role(*ROLES)
def _api_docx(did):
    conn = _conn()
    try:
        d = get(conn, _uid(), did)
    finally:
        conn.close()
    if not d:
        return jsonify({"error": "not found"}), 404
    resp = send_file(io.BytesIO(docx_bytes(d)), as_attachment=True, download_name=file_name(d, ".docx"),
                     mimetype="application/vnd.openxmlformats-officedocument.wordprocessingml.document")
    resp.headers["Cache-Control"] = "no-store"
    return resp


@requires_role(*SAVE_ROLES)
def _api_save(did):
    body = request.get_json(silent=True) or {}
    conn = _conn()
    try:
        return jsonify({"data": save_to_job(conn, _uid(), did, str(body.get("project_code") or ""), str(body.get("category") or ""))})
    except LookupError:
        return jsonify({"error": "not found"}), 404
    except ValueError as e:
        return jsonify({"error": str(e)}), 400
    finally:
        conn.close()


@requires_role(*SAVE_ROLES)
def _api_jobs():
    conn = _conn()
    try:
        return jsonify({"data": _rows(conn, "SELECT project_code, name FROM projects WHERE COALESCE(status, 'active') = 'active' "
                                            "ORDER BY project_code")})
    finally:
        conn.close()


