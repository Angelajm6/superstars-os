# ------------------------------------------------------------------ storage
def _conn():
    return db_layer.connect()


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _one(conn, sql, params=()) -> Optional[dict]:
    r = conn.execute(sql, params).fetchone()
    return dict(r) if r else None


def _rows(conn, sql, params=()) -> list:
    return [dict(r) for r in conn.execute(sql, params).fetchall()]


def ensure(conn) -> None:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(f"CREATE TABLE IF NOT EXISTS claude_doc ({pk}, user_id INTEGER NOT NULL, chat_id INTEGER, title TEXT NOT NULL, "
                 "html TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_claude_doc_chat ON claude_doc(chat_id)")
    conn.execute("CREATE TABLE IF NOT EXISTS claude_doc_ref (doc_id INTEGER NOT NULL, chat_id INTEGER, message_id INTEGER, "
                 "kind TEXT NOT NULL, created_at TEXT NOT NULL)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_claude_doc_ref_chat ON claude_doc_ref(chat_id)")
    conn.commit()


def clean(html: str) -> str:
    """Claude's (or the person's) HTML: no scripts, handlers or outside URLs; just the document's inside."""
    import proposal_template
    h = proposal_template.sanitize(html or "")
    b = re.search(r"(?is)<body[^>]*>(.*)</body>", h)
    if b:
        h = b.group(1)
    h = re.sub(r"(?is)<(html|head|body|title|meta)[^>]*>|</(html|head|body|title)>", "", h)
    h = re.sub(r"(?is)<style[^>]*>.*?</style>", "", h)   # one look for every document (DOC_CSS)
    h = re.sub(r'\s+contenteditable="[^"]*"', "", h)
    h = re.sub(r'\s+class="ssc-flash"', "", h)
    if len(h) > MAX_HTML:
        raise ValueError("That document is too long. Split it into two documents.")
    return h.strip()


def create(conn, uid, chat_id, message_id, title: str, html: str) -> dict:
    title = (title or "").strip()[:160] or "Document"
    body = clean(html)
    if not re.sub(r"(?s)<[^>]+>", "", body).strip():
        raise ValueError("the document is empty")
    now = _now()
    conn.execute("INSERT INTO claude_doc (user_id, chat_id, title, html, created_at, updated_at) VALUES (?,?,?,?,?,?)",
                 (uid, chat_id, title, body, now, now))
    conn.commit()
    did = _one(conn, "SELECT MAX(id) AS m FROM claude_doc WHERE user_id = ?", (uid,))["m"]
    conn.execute("INSERT INTO claude_doc_ref (doc_id, chat_id, message_id, kind, created_at) VALUES (?,?,?,?,?)",
                 (did, chat_id, message_id, "created", now))
    conn.commit()
    return {"doc_id": did, "title": title}


def get(conn, uid, did: int) -> Optional[dict]:
    return _one(conn, "SELECT * FROM claude_doc WHERE id = ? AND user_id = ?", (did, uid))


def update(conn, uid, did: int, *, html: Optional[str] = None, title: Optional[str] = None,
           chat_id=None, message_id=None) -> dict:
    d = get(conn, uid, did)
    if not d:
        raise LookupError("no document with that id in this person's chats")
    sets, vals = [], []
    if html is not None:
        body = clean(html)
        sets.append("html = ?"); vals.append(body)
    if title is not None and title.strip():
        sets.append("title = ?"); vals.append(title.strip()[:160])
    if not sets:
        return {"doc_id": did, "title": d["title"]}
    sets.append("updated_at = ?"); vals.append(_now())
    conn.execute(f"UPDATE claude_doc SET {', '.join(sets)} WHERE id = ?", vals + [did])
    if message_id is not None:
        conn.execute("INSERT INTO claude_doc_ref (doc_id, chat_id, message_id, kind, created_at) VALUES (?,?,?,?,?)",
                     (did, chat_id, message_id, "updated", _now()))
    conn.commit()
    d = get(conn, uid, did)
    return {"doc_id": did, "title": d["title"]}


def refs_for_chat(conn, chat_id) -> dict:
    """message_id -> [{id, title, kind, updated_at}] for the chat view."""
    out: dict = {}
    for r in _rows(conn, "SELECT r.message_id, r.kind, d.id, d.title, d.updated_at FROM claude_doc_ref r "
                         "JOIN claude_doc d ON d.id = r.doc_id WHERE r.chat_id = ? ORDER BY r.created_at", (chat_id,)):
        out.setdefault(r["message_id"], []).append({"id": r["id"], "title": r["title"], "kind": r["kind"], "updated_at": r["updated_at"]})
    return out


def page(d: dict, edit: bool = False) -> str:
    """The letterhead (Settings > Company brand) sits above the article, outside the editable .doc, so edits never save it."""
    import company_brand
    e = _html.escape
    attr = ' contenteditable="true" spellcheck="true"' if edit else ""
    return (f"<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>{e(d['title'])}</title>"
            f"<style>{DOC_CSS}{company_brand.LETTERHEAD_CSS}{EDIT_CSS if edit else ''}</style></head><body>"
            f"{company_brand.letterhead_html()}<article class=\"doc\"{attr}>{d['html']}</article></body></html>")


def pdf_bytes(d: dict) -> bytes:
    import pdf_export
    with tempfile.TemporaryDirectory() as td:
        hp, pp = Path(td) / "doc.html", Path(td) / "doc.pdf"
        hp.write_text(page(d), encoding="utf-8")
        res = pdf_export.render_html_to_pdf(hp, pp, timeout_sec=30)
        if not res.get("ok"):
            raise ValueError("The PDF couldn't be made right now. Try again in a minute, or download it as Word.")
        return pp.read_bytes()


