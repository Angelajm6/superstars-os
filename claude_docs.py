class _Blocks(HTMLParser):
    """HTML -> a list of blocks: ('h', level, runs) ('p', runs) ('li', runs, ordered) ('table', rows[cells[runs]])."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks, self.runs, self.bold, self.ital = [], [], 0, 0
        self.kind, self.level, self.list_stack = "p", 0, []
        self.table, self.row, self.cell = None, None, None

    def _flush(self):
        text = "".join(t for t, _b, _i in self.runs).strip()
        if self.cell is not None:
            return
        if text:
            if self.kind == "h":
                self.blocks.append(("h", self.level, self.runs))
            elif self.kind == "li":
                self.blocks.append(("li", self.runs, bool(self.list_stack and self.list_stack[-1] == "ol")))
            else:
                self.blocks.append(("p", self.runs))
        self.runs, self.kind = [], "p"

    def handle_starttag(self, tag, attrs):
        if tag in ("h1", "h2", "h3", "h4"):
            self._flush(); self.kind, self.level = "h", int(tag[1])
        elif tag in ("p", "div", "section", "article", "blockquote"):
            self._flush()
        elif tag in ("ul", "ol"):
            self._flush(); self.list_stack.append(tag)
        elif tag == "li":
            self._flush(); self.kind = "li"
        elif tag == "br":
            self._add("\n")
        elif tag in ("b", "strong", "th"):
            self.bold += 1
            if tag == "th":
                self.cell = []
        elif tag in ("i", "em"):
            self.ital += 1
        elif tag == "table":
            self._flush(); self.table = []
        elif tag == "tr":
            self.row = []
        elif tag == "td":
            self.cell = []

    def handle_endtag(self, tag):
        if tag in ("h1", "h2", "h3", "h4", "p", "div", "li", "section", "article", "blockquote"):
            self._flush()
        elif tag in ("ul", "ol"):
            self._flush()
            if self.list_stack:
                self.list_stack.pop()
        elif tag in ("b", "strong", "th"):
            self.bold = max(0, self.bold - 1)
            if tag == "th" and self.row is not None and self.cell is not None:
                self.row.append(self.cell); self.cell = None
        elif tag in ("i", "em"):
            self.ital = max(0, self.ital - 1)
        elif tag == "td" and self.row is not None and self.cell is not None:
            self.row.append(self.cell); self.cell = None
        elif tag == "tr" and self.table is not None and self.row is not None:
            if self.row:
                self.table.append(self.row)
            self.row = None
        elif tag == "table" and self.table is not None:
            if self.table:
                self.blocks.append(("table", self.table))
            self.table = None

    def _add(self, t):
        run = (t, self.bold > 0, self.ital > 0)
        (self.cell if self.cell is not None else self.runs).append(run)

    def handle_data(self, data):
        if self.table is not None and self.cell is None:
            return   # whitespace between cells
        t = re.sub(r"\s+", " ", data)
        if t:
            self._add(t)

    def close(self):
        super().close()
        self._flush()


def _x(t: str) -> str:
    return _html.escape(t, quote=False)


def _runs_xml(runs) -> str:
    out = []
    for t, b, i in runs:
        props = ("<w:b/>" if b else "") + ("<w:i/>" if i else "")
        parts = t.split("\n")
        for k, part in enumerate(parts):
            if k:
                out.append("<w:r><w:br/></w:r>")
            if part:
                out.append(f"<w:r>{'<w:rPr>' + props + '</w:rPr>' if props else ''}<w:t xml:space=\"preserve\">{_x(part)}</w:t></w:r>")
    return "".join(out)


def _word_letterhead() -> tuple:
    """(paragraphs XML, logo png or None) for the top of a Word file: the uploaded logo, then the letterhead lines."""
    import company_brand
    conn = _conn()
    try:
        facts, logo = company_brand.letterhead(conn), company_brand.word_logo(conn)
    except Exception as x:
        log.info("Word letterhead unavailable: %s", type(x).__name__)
        facts, logo = {}, None
    finally:
        conn.close()
    out = []
    if logo:
        _, w, h = logo
        cy = 571500   # 0.625 in tall
        cx = min(int(cy * w / max(h, 1)), 2743200)   # at most 3 in wide
        cy = int(cx * h / max(w, 1)) if cx == 2743200 else cy
        out.append('<w:p><w:r><w:drawing><wp:inline distT="0" distB="0" distL="0" distR="0">'
                   f'<wp:extent cx="{cx}" cy="{cy}"/><wp:docPr id="1" name="Logo" descr="{_x(company_brand.COMPANY_NAME)}"/>'
                   '<a:graphic><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:pic>'
                   '<pic:nvPicPr><pic:cNvPr id="1" name="logo.png"/><pic:cNvPicPr/></pic:nvPicPr>'
                   '<pic:blipFill><a:blip r:embed="rIdLogo"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
                   f'<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr>'
                   '</pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r></w:p>')
    else:
        out.append(f'<w:p><w:r><w:rPr><w:b/><w:color w:val="B11E2E"/><w:sz w:val="28"/></w:rPr><w:t>{_x(company_brand.COMPANY_NAME.upper())}</w:t></w:r></w:p>')
    lines = company_brand.letterhead_lines(facts)
    if lines:
        out.append('<w:p><w:pPr><w:spacing w:after="0"/></w:pPr>' + '<w:r><w:br/></w:r>'.join(
            f'<w:r><w:rPr><w:color w:val="6B7180"/><w:sz w:val="17"/></w:rPr><w:t xml:space="preserve">{_x(t)}</w:t></w:r>' for t in lines) + '</w:p>')
    out.append('<w:p><w:pPr><w:pBdr><w:bottom w:val="single" w:sz="18" w:space="1" w:color="B11E2E"/></w:pBdr></w:pPr></w:p>')
    return "".join(out), (logo[0] if logo else None)


def docx_bytes(d: dict) -> bytes:
    p = _Blocks()
    p.feed(d["html"])
    p.close()
    head, logo_png = _word_letterhead()
    body = [head]
    for b in p.blocks:
        if b[0] == "h":
            body.append(f'<w:p><w:pPr><w:pStyle w:val="Heading{min(3, b[1])}"/></w:pPr>{_runs_xml(b[2])}</w:p>')
        elif b[0] == "p":
            body.append(f"<w:p>{_runs_xml(b[1])}</w:p>")
        elif b[0] == "li":
            mark = "•\t" if not b[2] else "–\t"
            body.append(f'<w:p><w:pPr><w:ind w:left="360" w:hanging="360"/></w:pPr><w:r><w:t xml:space="preserve">{mark}</w:t></w:r>{_runs_xml(b[1])}</w:p>')
        elif b[0] == "table":
            rows = []
            for i, row in enumerate(b[1]):
                cells = "".join(f'<w:tc><w:tcPr><w:tcW w:w="0" w:type="auto"/></w:tcPr><w:p>{_runs_xml(c) if not i else _runs_xml(c)}</w:p></w:tc>' for c in row)
                rows.append(f"<w:tr>{cells}</w:tr>")
            body.append('<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="5000" w:type="pct"/>'
                        '<w:tblBorders><w:top w:val="single" w:sz="4" w:color="BBBBBB"/><w:bottom w:val="single" w:sz="4" w:color="BBBBBB"/>'
                        '<w:insideH w:val="single" w:sz="4" w:color="DDDDDD"/></w:tblBorders></w:tblPr>' + "".join(rows) + "</w:tbl><w:p/>")
    ns = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
    dns = (ns + ' xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'
           ' xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"'
           ' xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"'
           ' xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture"')
    document = (f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document {dns}><w:body>{"".join(body)}'
                '<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1080" w:right="1080" w:bottom="1080" w:left="1080"/></w:sectPr></w:body></w:document>')
    styles = (f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:styles {ns}>'
              '<w:docDefaults><w:rPrDefault><w:rPr><w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"/><w:sz w:val="21"/></w:rPr></w:rPrDefault></w:docDefaults>'
              '<w:style w:type="paragraph" w:default="1" w:styleId="Normal"><w:name w:val="Normal"/><w:pPr><w:spacing w:after="120"/></w:pPr></w:style>'
              '<w:style w:type="paragraph" w:styleId="Heading1"><w:name w:val="heading 1"/><w:pPr><w:spacing w:before="240" w:after="120"/></w:pPr><w:rPr><w:b/><w:sz w:val="34"/></w:rPr></w:style>'
              '<w:style w:type="paragraph" w:styleId="Heading2"><w:name w:val="heading 2"/><w:pPr><w:spacing w:before="240" w:after="80"/></w:pPr><w:rPr><w:b/><w:color w:val="B11E2E"/><w:sz w:val="22"/></w:rPr></w:style>'
              '<w:style w:type="paragraph" w:styleId="Heading3"><w:name w:val="heading 3"/><w:rPr><w:b/><w:sz w:val="24"/></w:rPr></w:style>'
              '<w:style w:type="table" w:styleId="TableGrid"><w:name w:val="Table Grid"/></w:style></w:styles>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml",
                   '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                   '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                   '<Default Extension="xml" ContentType="application/xml"/><Default Extension="png" ContentType="image/png"/>'
                   '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
                   '<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/></Types>')
        z.writestr("_rels/.rels", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                   '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>')
        z.writestr("word/_rels/document.xml.rels", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                   '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>'
                   + ('<Relationship Id="rIdLogo" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="media/logo.png"/>'
                      if logo_png else '') + '</Relationships>')
        z.writestr("word/document.xml", document)
        z.writestr("word/styles.xml", styles)
        if logo_png:
            z.writestr("word/media/logo.png", logo_png)
    return buf.getvalue()


def file_name(d: dict, ext: str) -> str:
    return (re.sub(r'[\\/:*?"<>|]+', "", d["title"]).strip() or "Document")[:100] + ext


# ------------------------------------------------------------------ save to a job
def save_to_job(conn, uid, did: int, project_code: str, category: str) -> dict:
    """The PDF into a job's documents (server._projdoc_insert, the same path as an upload)."""
    from werkzeug.datastructures import FileStorage
    d = get(conn, uid, did)
    if not d:
        raise LookupError("not found")
    category = (category or "").strip().upper()
    if category not in CATEGORIES:
        raise ValueError("pick a folder: " + ", ".join(c.title() for c in CATEGORIES))
    if not _one(conn, "SELECT project_code FROM projects WHERE project_code = ?", (project_code,)):
        raise ValueError("that job doesn't exist")
    data = pdf_bytes(d)
    srv = sys.modules.get("server") or sys.modules.get("__main__")
    insert = getattr(srv, "_projdoc_insert", None)
    if not insert:
        raise ValueError("Saving to a job isn't available here.")
    fs = FileStorage(stream=io.BytesIO(data), filename=file_name(d, ".pdf"), content_type="application/pdf")
    new_id = insert(conn, project_code, fs, {"category": category, "title": d["title"], "notes": "Made with Claude"})
    conn.commit()
    return {"id": new_id, "project_code": project_code}


