"""Gmail suggestions — to-dos spotted in each person's email, one tap from their to-do list.

Prototype accepted 2026-10-07. A team member connects Gmail once (read-only). Every 10 minutes
(and on "Check now") new mail in their Gmail PRIMARY inbox is read: mail they sent, no-reply
senders and bulk mail are skipped. The AI (Anthropic; capped per day in-app) decides whether an
email asks for something to be done or sets a meeting / visit / inspection, and proposes a
title, task vs event, date, time and address. Keyword rules take over when there is no AI key
or the day's cap is used up. Suggestions are private to that person: "Add to my to-do" creates
a team item ASSIGNED TO THEM (so it reaches the team calendar and their Google Calendar);
"Dismiss" hides it (Undo). PMs and supers add only to their own to-do.

Least privilege + privacy
  * Google scopes: openid, email, gmail.readonly — the app cannot send, delete or change mail.
  * Kept per suggestion, ENCRYPTED (secret_box): sender, subject, a short excerpt, the proposed
    title / address / reason. The full email is never stored. For mail judged "not a to-do"
    only the Gmail message id is kept (so it is not read twice), pruned after 14 days.
  * Email text is untrusted: the model is told to treat it as data, and every field it returns
    is re-validated (dates, times, lengths). Never logged: tokens, addresses, subjects, bodies.
  * Off (status says why; connect 404s) until the Google OAuth client, a redirect URI and the
    field-encryption key are configured — same switch as Google Calendar sync.

  GET  /gmail/connect                       start (signed-in team member) -> Google consent
  GET  /gmail/callback                      Google sends the person back here
  GET  /api/gmail/status                    available? connected? last check, new count
  POST /api/gmail/check                     check now
  POST /api/gmail/disconnect                revoke + forget the connection and suggestions
  GET  /api/gmail/suggestions               this person's new (and just-decided) suggestions
  POST /api/gmail/suggestions/<id>/accept   {kind,title,date,time,address} -> their own task/event
  POST /api/gmail/suggestions/<id>/dismiss
  POST /api/gmail/suggestions/<id>/undo     a dismissed one back to new

Redirect URI: GMAIL_REDIRECT_URI, else the SSO redirect's origin + /gmail/callback (register it
on the OAuth client in Google Cloud). AI: ANTHROPIC_API_KEY; model GMAIL_SUGGEST_MODEL (default
Haiku 4.5); cap GMAIL_AI_DAILY_CAP emails per day, company-wide (default 200).
"""
