# ------------------------------------------------------------------ config (shared with Calendar sync)
def redirect_uri() -> str:
    explicit = (os.environ.get("GMAIL_REDIRECT_URI") or "").strip()
    if explicit:
        return explicit
    sso = (os.environ.get("GOOGLE_OAUTH_REDIRECT_URI") or "").strip()
    u = urllib.parse.urlsplit(sso) if sso else None
    return f"{u.scheme}://{u.netloc}/gmail/callback" if u and u.scheme and u.netloc else ""


def unavailable_reason() -> Optional[str]:
    if not (gcal_sync._client_id() and gcal_sync._client_secret() and redirect_uri()):
        return "google_not_configured"
    if not secret_box.is_configured():
        return "encryption_key_missing"
    return None


def ai_cap() -> int:
    try:
        return max(0, int(os.environ.get("GMAIL_AI_DAILY_CAP") or 200))
    except ValueError:
        return 200


