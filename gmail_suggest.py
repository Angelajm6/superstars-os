def _safe_next(v) -> str:
    v = str(v or "")
    return v if v.startswith("/") and not v.startswith("//") else "/projects"


def _back(next_url: str, outcome: str):
    base, _, frag = next_url.partition("#")
    resp = redirect(base + ("&" if "?" in base else "?") + "gmail=" + outcome + ("#" + frag if frag else ""))
    resp.set_cookie(STATE_COOKIE, "", max_age=0, httponly=True, samesite="Lax", path="/gmail/")
    return resp


@requires_role(*TEAM_ROLES)
def _connect():
    if unavailable_reason():
        return ("Not Found", 404)
    u = current_user() or {}
    nonce = secrets.token_urlsafe(24)
    params = {"client_id": gcal_sync._client_id(), "redirect_uri": redirect_uri(), "response_type": "code", "scope": SCOPES,
              "state": nonce + "." + urllib.parse.quote(_safe_next(request.args.get("next")), safe=""),
              "access_type": "offline", "prompt": "consent", "include_granted_scopes": "false",
              "hd": gcal_sync._allowed_domain(), "login_hint": u.get("email") or ""}
    resp = redirect(gcal_sync.AUTH_URL + "?" + urllib.parse.urlencode(params))
    import auth
    resp.set_cookie(STATE_COOKIE, nonce, max_age=600, httponly=True, secure=auth._request_is_https(), samesite="Lax", path="/gmail/")
    return resp


@requires_role(*TEAM_ROLES)
def _callback():
    if unavailable_reason():
        return ("Not Found", 404)
    u = current_user() or {}
    nonce, _, nxt = (request.args.get("state") or "").partition(".")
    next_url = _safe_next(urllib.parse.unquote(nxt))
    cookie = request.cookies.get(STATE_COOKIE) or ""
    if not nonce or not cookie or not secrets.compare_digest(nonce, cookie):
        return _back(next_url, "state")
    if request.args.get("error") or not request.args.get("code"):
        return _back(next_url, "denied")
    code, body = gcal_sync._http("POST", gcal_sync.TOKEN_URL, data={
        "code": request.args["code"], "client_id": gcal_sync._client_id(), "client_secret": gcal_sync._client_secret(),
        "redirect_uri": redirect_uri(), "grant_type": "authorization_code"})
    if code != 200 or not body.get("refresh_token") or not body.get("id_token"):
        log.info("gmail connect user=%s: token exchange failed (%s)", u.get("id"), code)
        return _back(next_url, "failed")
    if "gmail.readonly" not in (body.get("scope") or ""):
        return _back(next_url, "scope")
    claims = gcal_sync._verify_id_token(body["id_token"])
    email = ((claims or {}).get("email") or "").strip().lower()
    if (not claims or claims.get("email_verified") is not True or (claims.get("hd") or "").lower() != gcal_sync._allowed_domain()
            or email != (u.get("email") or "").strip().lower()):
        log.info("gmail connect user=%s: google account rejected", u.get("id"))
        return _back(next_url, "account")
    conn = db_layer.connect()
    try:
        enc = secret_box.encrypt_text(body["refresh_token"])
        if _one(conn, "SELECT id FROM gmail_link WHERE user_id = ?", (u["id"],)):
            conn.execute("UPDATE gmail_link SET google_email = ?, refresh_token_enc = ?, status = 'active', connected_at = ?, last_error = NULL "
                         "WHERE user_id = ?", (email, enc, _now(), u["id"]))
        else:
            conn.execute("INSERT INTO gmail_link (user_id, google_email, refresh_token_enc, status, connected_at) VALUES (?, ?, ?, 'active', ?)",
                         (u["id"], email, enc, _now()))
        conn.commit()
        if body.get("access_token"):
            _TOKENS[u["id"]] = (body["access_token"], time.time() + int(body.get("expires_in") or 3000))
        result = check_user(conn, u["id"])
    finally:
        conn.close()
    start_poller()
    log.info("gmail connected user=%s", u.get("id"))
    return _back(next_url, "connected" if not result.get("error") else "connected_retry")


def status_for(conn, uid) -> dict:
    reason = unavailable_reason()
    link = _one(conn, "SELECT * FROM gmail_link WHERE user_id = ?", (uid,)) if not reason else None
    new = conn.execute("SELECT COUNT(*) FROM gmail_suggestion WHERE user_id = ? AND status = 'new'", (uid,)).fetchone()[0] if link else 0
    return {"available": not reason, "reason": reason, "connected": bool(link), "status": link["status"] if link else None,
            "google_email": link["google_email"] if link else None, "last_check_at": link["last_check_at"] if link else None,
            "problem": link["last_error"] if link else None, "new_count": new,
            "ai": bool(os.environ.get("ANTHROPIC_API_KEY")) and ai_cap() > 0}


def _with_conn(fn):
    conn = db_layer.connect()
    try:
        return fn(conn)
    finally:
        conn.close()


@requires_role(*TEAM_ROLES)
def _status():
    uid = (current_user() or {}).get("id")
    return jsonify({"data": _with_conn(lambda c: status_for(c, uid))})


@requires_role(*TEAM_ROLES)
def _check():
    if unavailable_reason():
        return jsonify({"error": "Gmail suggestions are not switched on yet"}), 409
    uid = (current_user() or {}).get("id")

    def run(c):
        if not _one(c, "SELECT id FROM gmail_link WHERE user_id = ?", (uid,)):
            return None
        return {**check_user(c, uid), **status_for(c, uid)}
    data = _with_conn(run)
    if data is None:
        return jsonify({"error": "connect Gmail first"}), 409
    return jsonify({"data": data})


@requires_role(*TEAM_ROLES)
def _disconnect():
    uid = (current_user() or {}).get("id")

    def run(c):
        link = _one(c, "SELECT * FROM gmail_link WHERE user_id = ?", (uid,))
        if link and not unavailable_reason():
            try:
                gcal_sync._http("POST", gcal_sync.REVOKE_URL, data={"token": secret_box.decrypt_text(link["refresh_token_enc"])})
            except Exception as e:
                log.info("gmail disconnect user=%s: revoke skipped (%s)", uid, type(e).__name__)
        for t in ("gmail_suggestion", "gmail_seen", "gmail_link"):
            c.execute(f"DELETE FROM {t} WHERE user_id = ?", (uid,))
        c.commit()
        _TOKENS.pop(uid, None)
        log.info("gmail disconnected user=%s", uid)
        return {"connected": False}
    return jsonify({"data": _with_conn(run)})


@requires_role(*TEAM_ROLES)
def _list():
    uid = (current_user() or {}).get("id")
    if unavailable_reason():
        return jsonify({"data": []})
    return jsonify({"data": _with_conn(lambda c: suggestions_for(c, uid))})


def _act(fn):
    try:
        return fn()
    except LookupError as e:
        return jsonify({"error": str(e)}), 404
    except ValueError as e:
        return jsonify({"error": str(e)}), 400


@requires_role(*TEAM_ROLES)
def _accept(sid):
    uid = (current_user() or {}).get("id")
    body = request.get_json(silent=True) or {}
    return _act(lambda: jsonify({"data": {"item_id": _with_conn(lambda c: accept(c, uid, sid, body))}}))


@requires_role(*TEAM_ROLES)
def _dismiss(sid):
    uid = (current_user() or {}).get("id")
    return _act(lambda: (_with_conn(lambda c: _decide(c, uid, sid, "dismissed")), jsonify({"data": {"id": sid, "status": "dismissed"}}))[1])


@requires_role(*TEAM_ROLES)
def _undo(sid):
    uid = (current_user() or {}).get("id")
    return _act(lambda: (_with_conn(lambda c: _decide(c, uid, sid, "new")), jsonify({"data": {"id": sid, "status": "new"}}))[1])


def register(app) -> None:
    conn = db_layer.connect()
    try:
        ensure(conn)
        db_layer._PKMAP_CACHE.clear()
    except Exception as e:
        log.warning("gmail schema ensure skipped: %s", e)
        try:
            conn.rollback()
        except Exception:
            pass
    finally:
        conn.close()
    app.add_url_rule("/gmail/connect", "gmail_connect", _connect, methods=["GET"])
    app.add_url_rule("/gmail/callback", "gmail_callback", _callback, methods=["GET"])
    app.add_url_rule("/api/gmail/status", "gmail_status", _status, methods=["GET"])
    app.add_url_rule("/api/gmail/check", "gmail_check", _check, methods=["POST"])
    app.add_url_rule("/api/gmail/disconnect", "gmail_disconnect", _disconnect, methods=["POST"])
    app.add_url_rule("/api/gmail/suggestions", "gmail_suggestions", _list, methods=["GET"])
    app.add_url_rule("/api/gmail/suggestions/<int:sid>/accept", "gmail_accept", _accept, methods=["POST"])
    app.add_url_rule("/api/gmail/suggestions/<int:sid>/dismiss", "gmail_dismiss", _dismiss, methods=["POST"])
    app.add_url_rule("/api/gmail/suggestions/<int:sid>/undo", "gmail_undo", _undo, methods=["POST"])
    if not unavailable_reason():
        start_poller()   # every 10 minutes, connected mailboxes only
