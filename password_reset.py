"""Public password reset, with opaque single-use tokens and SMTP delivery.

Delivery is deliberately disabled until all SSC_RESET_SMTP_* settings are supplied.
The public request response is always identical, so the endpoint cannot enumerate users.
"""
import hashlib, os, secrets, smtplib, ssl
from datetime import timedelta
from email.message import EmailMessage
from urllib.parse import quote, urlsplit
from flask import jsonify, request, send_file
import auth

TTL = timedelta(minutes=30)
PAGE = auth.SCRIPT_DIR / "forgot_password.html"
RESET_PAGE = auth.SCRIPT_DIR / "reset_password.html"

def ensure_schema(conn):
    pk = "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if auth.db_layer.is_postgres() else "id INTEGER PRIMARY KEY AUTOINCREMENT"
    conn.execute(f"CREATE TABLE IF NOT EXISTS password_reset_token ({pk}, user_id INTEGER NOT NULL REFERENCES users(id), token_hash TEXT NOT NULL UNIQUE, requested_at TEXT NOT NULL, expires_at TEXT NOT NULL, used_at TEXT, request_ip TEXT)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_password_reset_token_lookup ON password_reset_token(token_hash, used_at, expires_at)")
    conn.commit()

def _config():
    keys = ("SSC_RESET_SMTP_HOST", "SSC_RESET_SMTP_USERNAME", "SSC_RESET_SMTP_PASSWORD", "SSC_RESET_EMAIL_FROM", "SSC_PUBLIC_BASE_URL")
    d = {k: (os.environ.get(k) or "").strip() for k in keys}
    p = urlsplit(d["SSC_PUBLIC_BASE_URL"] or "")
    return d if all(d.values()) and p.scheme == "https" and p.netloc else None

def _deliver(to, token):
    c = _config()
    if not c: return False
    url = c["SSC_PUBLIC_BASE_URL"].rstrip("/") + "/reset-password?token=" + quote(token, safe="")
    m = EmailMessage(); m["Subject"] = "Reset your Superstars Contracting password"; m["From"] = c["SSC_RESET_EMAIL_FROM"]; m["To"] = to
    m.set_content("Use this one-time link within 30 minutes to reset your password:\n\n" + url + "\n\nIf you did not request this, you can ignore this email.")
    try:
        with smtplib.SMTP(c["SSC_RESET_SMTP_HOST"], int(os.environ.get("SSC_RESET_SMTP_PORT", "587")), timeout=12) as s:
            s.starttls(context=ssl.create_default_context()); s.login(c["SSC_RESET_SMTP_USERNAME"], c["SSC_RESET_SMTP_PASSWORD"]); s.send_message(m)
        return True
    except Exception:
        return False

def _generic(): return jsonify({"ok": True, "message": "If an active account matches that email, a reset link has been sent."}), 202
def request_reset():
    email = (request.get_json(silent=True) or {}).get("email", "").strip(); user = auth.get_user_by_email(email)
    if not user or user.get("status") != "active" or not user.get("is_active") or user.get("force_sso") or not _config(): return _generic()
    token = secrets.token_urlsafe(32); h = hashlib.sha256(token.encode()).hexdigest(); now = auth._now_iso(); expiry = (auth.datetime.now() + TTL).isoformat(timespec="seconds")
    conn = auth._db()
    try:
        conn.execute("DELETE FROM password_reset_token WHERE user_id=? OR expires_at<?", (user["id"], now)); conn.execute("INSERT INTO password_reset_token (user_id,token_hash,requested_at,expires_at,request_ip) VALUES (?,?,?,?,?)", (user["id"],h,now,expiry,auth._client_ip())); conn.commit()
    finally: conn.close()
    if _deliver(user["email"], token): auth._login_audit(user["id"], "password_reset_requested", auth._client_ip())
    return _generic()
def confirm_reset():
    d=request.get_json(silent=True) or {}; token=d.get("token") or ""; pw=d.get("new_password") or ""; err=auth.password_strength_error(pw)
    if err: return jsonify({"error":err}),400
    h=hashlib.sha256(token.encode()).hexdigest(); now=auth._now_iso(); conn=auth._db()
    try:
        row=conn.execute("SELECT id,user_id FROM password_reset_token WHERE token_hash=? AND used_at IS NULL AND expires_at>?",(h,now)).fetchone()
        if not row: return jsonify({"error":"This reset link is invalid or has expired."}),400
        conn.execute("UPDATE password_reset_token SET used_at=? WHERE id=? AND used_at IS NULL",(now,row["id"])); conn.execute("UPDATE users SET password_hash=?,must_reset_password=0 WHERE id=?",(auth.hash_password(pw),row["user_id"])); conn.commit(); uid=row["user_id"]
    finally: conn.close()
    auth.destroy_all_user_sessions(uid); auth._login_audit(uid,"password_reset_completed",auth._client_ip()); return jsonify({"ok":True})
def register(app):
    c=auth._db()
    try: ensure_schema(c)
    finally: c.close()
    app.add_url_rule("/forgot-password","forgot_password",lambda:send_file(str(PAGE)),methods=["GET"])
    app.add_url_rule("/reset-password","reset_password",lambda:send_file(str(RESET_PAGE)),methods=["GET"])
    app.add_url_rule("/api/auth/password-reset/request","password_reset_request",request_reset,methods=["POST"])
    app.add_url_rule("/api/auth/password-reset/confirm","password_reset_confirm",confirm_reset,methods=["POST"])
