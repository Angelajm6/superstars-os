"""#318 — Company vault: vehicles + files on company documents.

ROADMAP Phase C "Company vault": extend `company_document` (#302) with the
company's vehicles (registration, insurance, inspection, plate, assigned driver),
tax returns by year, filing receipts and a generic company record with expiry,
all surfacing in the Compliance view's expiry buckets, plus file attachments on
company documents (until now the table was metadata only).

  vehicle                id, label, year, make, model, plate, vin, color,
                         driver_employee_id, status (active | retired), notes,
                         created_by, created_at, updated_at, archived_at
  company_document       + vehicle_id, + doc_year   (added here, idempotent)
  company_document_file  id, document_id, file_name, file_path, file_size, mime,
                         uploaded_by, uploaded_at

Files live under <data root>/data_room/company_vault/<document id>/<uuid>.<ext>
and are read ONLY through the gated route (`file_url`); `file_path` never enters
a JSON payload (CLAUDE.md PII rule, #229 pattern). The driver is a roster
reference (`employees.employee_id`), rendered as "W-#### — Name" on this
company-only surface.

Access: the company portal gate (admin / c_suite) is passed in by
`company_portal.register` — nothing here is reachable by any other role.
"""
from __future__ import annotations

import logging
import uuid
from datetime import date, datetime
from pathlib import Path
from typing import Optional

from flask import jsonify, request, send_file

import db_layer
import ssc_paths
from auth import current_user

log = logging.getLogger("ssc.company_vault")

VEHICLE_STATUSES = ("active", "retired")
VEHICLE_EDITABLE = ("label", "year", "make", "model", "plate", "vin", "color", "driver_employee_id", "status", "notes")
_FILE_BASE = ssc_paths.under_root("data_room", "company_vault")
_EXT_MIME = {
    ".pdf": "application/pdf",
    ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png",
    ".heic": "image/heic", ".heif": "image/heif",
    ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
}
MAX_FILE_BYTES = 25 * 1024 * 1024


# ---------------------------------------------------------------- helpers
def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _rows(cur) -> list:
    return [dict(r) for r in cur.fetchall()]


def _one(cur) -> Optional[dict]:
    r = cur.fetchone()
    return dict(r) if r else None


def _err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


def _wrap(data, **meta):
    m = {"generated_at": _now()}
    if isinstance(data, list):
        m["count"] = len(data)
    m.update(meta)
    return jsonify({"data": data, "meta": m})


def _uid():
    u = current_user()
    return u["id"] if u else None


def _has_column(conn, table: str, column: str) -> bool:
    if db_layer.is_postgres():
        return bool(conn.execute(
            "SELECT 1 AS x FROM information_schema.columns WHERE table_name = ? AND column_name = ?",
            (table, column)).fetchone())
    return any(r["name"] == column for r in conn.execute(f"PRAGMA table_info({table})").fetchall())


def _days_until(iso, today: Optional[date] = None) -> Optional[int]:
    if not iso:
        return None
    try:
        return (date.fromisoformat(str(iso)[:10]) - (today or date.today())).days
    except ValueError:
        return None


# ---------------------------------------------------------------- schema
def ensure_schema(conn) -> None:
    """Idempotent on both backends. Called from company_portal.ensure_schema (boot)
    and from apply_company_vault_318.py (ledger / fixture)."""
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS vehicle ("
        f"  {pk},"
        f"  label              TEXT NOT NULL,"
        f"  year               INTEGER,"
        f"  make               TEXT,"
        f"  model              TEXT,"
        f"  plate              TEXT,"
        f"  vin                TEXT,"
        f"  color              TEXT,"
        f"  driver_employee_id TEXT,"
        f"  status             TEXT NOT NULL DEFAULT 'active',"
        f"  notes              TEXT,"
        f"  created_by         INTEGER,"
        f"  created_at         TEXT NOT NULL,"
        f"  updated_at         TEXT NOT NULL,"
        f"  archived_at        TEXT"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_vehicle_status ON vehicle(archived_at, status)")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS company_document_file ("
        f"  {pk},"
        f"  document_id  INTEGER NOT NULL,"
        f"  file_name    TEXT NOT NULL,"
        f"  file_path    TEXT NOT NULL,"
        f"  file_size    INTEGER,"
        f"  mime         TEXT,"
        f"  uploaded_by  INTEGER,"
        f"  uploaded_at  TEXT NOT NULL"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_company_document_file_doc ON company_document_file(document_id)")
    for col, ddl in (("vehicle_id", "INTEGER"), ("doc_year", "INTEGER")):
        if not _has_column(conn, "company_document", col):
            conn.execute(f"ALTER TABLE company_document ADD COLUMN {col} {ddl}")
    conn.commit()


# ---------------------------------------------------------------- vehicles
_VSELECT = ("SELECT v.*, e.worker_id AS driver_worker_id, e.name AS driver_name "
            "FROM vehicle v LEFT JOIN employees e ON e.employee_id = v.driver_employee_id ")


def _vehicle_public(r: dict) -> dict:
    d = dict(r)
    wid, name = d.pop("driver_worker_id", None), d.pop("driver_name", None)
    d["driver"] = (f"{wid} — {name}" if wid and name else (name or wid)) if d.get("driver_employee_id") else None
    return d


def get_vehicle(conn, vehicle_id: int) -> Optional[dict]:
    r = _one(conn.execute(_VSELECT + "WHERE v.id = ?", (vehicle_id,)))
    return _vehicle_public(r) if r else None


def list_vehicles(conn, *, include_archived: bool = False, today: Optional[date] = None) -> list:
    """Vehicles with the state of the three documents every vehicle needs
    (registration / insurance / inspection): the newest non-archived document of
    each category, its expiry and days left; `missing` names the ones with no
    document at all. Retired vehicles keep their paper but are not flagged."""
    today = today or date.today()
    sql = _VSELECT + ("" if include_archived else "WHERE v.archived_at IS NULL ") + "ORDER BY v.status, v.label"
    out = [_vehicle_public(r) for r in _rows(conn.execute(sql))]
    if not out:
        return out
    ids = [v["id"] for v in out]
    marks = ",".join("?" * len(ids))
    docs: dict = {}
    for r in _rows(conn.execute(
            f"SELECT id, vehicle_id, category, title, expiry_date, doc_number FROM company_document "
            f"WHERE archived_at IS NULL AND vehicle_id IN ({marks}) ORDER BY COALESCE(expiry_date,'0000') DESC, id DESC",
            ids)):
        docs.setdefault(r["vehicle_id"], {}).setdefault(r["category"], r)   # newest expiry wins
    from company_portal import VEHICLE_DOC_CATEGORIES, COMPANY_DOC_CATEGORIES
    for v in out:
        mine = docs.get(v["id"], {})
        v["documents"] = {}
        v["missing"] = []
        for cat in VEHICLE_DOC_CATEGORIES:
            r = mine.get(cat)
            if r:
                v["documents"][cat] = {"id": r["id"], "title": r["title"], "number": r.get("doc_number"),
                                       "expiry_date": r.get("expiry_date"), "days_left": _days_until(r.get("expiry_date"), today)}
            elif v["status"] == "active":
                v["missing"].append(COMPANY_DOC_CATEGORIES.get(cat, cat))
        v["doc_count"] = len(mine)
        left = [d["days_left"] for d in v["documents"].values() if d["days_left"] is not None]
        v["next_expiry_days"] = min(left) if left else None
    return out


def _validate_vehicle(payload: dict, *, partial: bool) -> tuple:
    d = {k: payload.get(k) for k in VEHICLE_EDITABLE if k in payload}
    if not partial and not str(d.get("label") or "").strip():
        return None, "label is required (e.g. Van 2 — Ford Transit)"
    if "label" in d and not str(d.get("label") or "").strip():
        return None, "label cannot be blank"
    if "status" in d and d["status"] not in VEHICLE_STATUSES:
        return None, "status must be active or retired"
    if "year" in d:
        if d["year"] in (None, ""):
            d["year"] = None
        else:
            try:
                d["year"] = int(d["year"])
            except (TypeError, ValueError):
                return None, "year must be a whole number"
            if not (1950 <= d["year"] <= 2100):
                return None, "year must be a four-digit year"
    for k in ("label", "make", "model", "plate", "vin", "color", "notes", "driver_employee_id"):
        if k in d and d[k] is not None:
            d[k] = str(d[k]).strip()[:500 if k == "notes" else 80] or None
    if "plate" in d and d["plate"]:
        d["plate"] = d["plate"].upper().replace(" ", "")
    if "vin" in d and d["vin"]:
        d["vin"] = d["vin"].upper()
        if not (11 <= len(d["vin"]) <= 17):
            return None, "vin looks wrong (11–17 characters)"
    return d, None


def create_vehicle(conn, payload: dict, *, actor=None) -> tuple:
    d, err = _validate_vehicle(payload, partial=False)
    if err:
        return None, err
    if d.get("driver_employee_id") and not _one(conn.execute(
            "SELECT employee_id FROM employees WHERE employee_id = ? AND archived_at IS NULL", (d["driver_employee_id"],))):
        return None, "driver must be an active worker"
    now = _now()
    conn.execute(
        "INSERT INTO vehicle (label, year, make, model, plate, vin, color, driver_employee_id, status, notes, "
        "created_by, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
        (d["label"], d.get("year"), d.get("make"), d.get("model"), d.get("plate"), d.get("vin"), d.get("color"),
         d.get("driver_employee_id"), d.get("status") or "active", d.get("notes"), actor, now, now))
    conn.commit()
    return _one(conn.execute("SELECT MAX(id) AS m FROM vehicle"))["m"], None


def update_vehicle(conn, vehicle_id: int, payload: dict) -> tuple:
    d, err = _validate_vehicle(payload, partial=True)
    if err:
        return False, err
    if not d:
        return False, "nothing to update"
    if d.get("driver_employee_id") and not _one(conn.execute(
            "SELECT employee_id FROM employees WHERE employee_id = ? AND archived_at IS NULL", (d["driver_employee_id"],))):
        return False, "driver must be an active worker"
    sets = ", ".join(f"{k} = ?" for k in d)
    cur = conn.execute(f"UPDATE vehicle SET {sets}, updated_at = ? WHERE id = ? AND archived_at IS NULL",
                       [*d.values(), _now(), vehicle_id])
    conn.commit()
    return (cur.rowcount or 0) > 0, None


def archive_vehicle(conn, vehicle_id: int) -> bool:
    cur = conn.execute("UPDATE vehicle SET archived_at = ?, status = 'retired', updated_at = ? "
                       "WHERE id = ? AND archived_at IS NULL", (_now(), _now(), vehicle_id))
    conn.commit()
    return (cur.rowcount or 0) > 0


def driver_options(conn) -> list:
    """Active roster for the driver select — the canonical source (CLAUDE.md roster rule)."""
    try:
        rows = _rows(conn.execute("SELECT employee_id, worker_id, name FROM v_active_workers ORDER BY worker_id, name"))
    except Exception:
        rows = _rows(conn.execute("SELECT employee_id, worker_id, name FROM employees WHERE archived_at IS NULL "
                                  "ORDER BY worker_id, name"))
    return [{"employee_id": r["employee_id"], "label": f"{r.get('worker_id') or ''} — {r.get('name') or ''}".strip(" —")}
            for r in rows]


# ---------------------------------------------------------------- files
def _file_public(r: dict) -> dict:
    return {"id": r["id"], "document_id": r["document_id"], "file_name": r["file_name"], "file_size": r.get("file_size"),
            "mime": r.get("mime"), "uploaded_at": r.get("uploaded_at"),
            "file_url": f"/api/company/portal/company-documents/files/{r['id']}"}


def files_by_document(conn, doc_ids: list) -> dict:
    if not doc_ids:
        return {}
    marks = ",".join("?" * len(doc_ids))
    out: dict = {}
    for r in _rows(conn.execute(
            f"SELECT id, document_id, file_name, file_size, mime, uploaded_at FROM company_document_file "
            f"WHERE document_id IN ({marks}) ORDER BY uploaded_at DESC, id DESC", list(doc_ids))):
        out.setdefault(r["document_id"], []).append(_file_public(r))
    return out


def add_file(conn, doc_id: int, fs, *, uploaded_by=None) -> dict:
    doc = _one(conn.execute("SELECT id FROM company_document WHERE id = ? AND archived_at IS NULL", (doc_id,)))
    if not doc:
        raise LookupError("document not found")
    ext = Path(fs.filename or "file").suffix.lower()
    if ext not in _EXT_MIME:
        raise ValueError(f"unsupported file type: {ext or '(none)'} — use PDF, JPG, PNG, HEIC, XLSX or DOCX")
    base = _FILE_BASE.resolve()
    ddir = _FILE_BASE / str(int(doc_id))
    if not ddir.resolve().is_relative_to(base):
        raise ValueError("invalid path")
    ddir.mkdir(parents=True, exist_ok=True)
    fpath = ddir / (uuid.uuid4().hex + ext)
    fs.save(str(fpath))
    size = fpath.stat().st_size
    if size > MAX_FILE_BYTES:
        fpath.unlink(missing_ok=True)
        raise ValueError("file is larger than 25 MB")
    if size == 0:
        fpath.unlink(missing_ok=True)
        raise ValueError("file is empty")
    try:
        conn.execute("INSERT INTO company_document_file (document_id, file_name, file_path, file_size, mime, uploaded_by, "
                     "uploaded_at) VALUES (?,?,?,?,?,?,?)",
                     (doc_id, Path(fs.filename or "file").name[:200], ssc_paths.store_rel(fpath), size, _EXT_MIME[ext],
                      uploaded_by, _now()))
        conn.execute("UPDATE company_document SET updated_at = ? WHERE id = ?", (_now(), doc_id))
        conn.commit()
    except Exception:
        fpath.unlink(missing_ok=True)
        raise
    r = _one(conn.execute("SELECT id, document_id, file_name, file_size, mime, uploaded_at FROM company_document_file "
                          "WHERE document_id = ? ORDER BY id DESC", (doc_id,)))
    return _file_public(r)


def resolve_file(conn, file_id: int) -> Optional[tuple]:
    """(path, mime, file_name) for a gated read, or None. Path-contained under the vault base."""
    r = _one(conn.execute("SELECT file_path, mime, file_name FROM company_document_file WHERE id = ?", (file_id,)))
    if not r or not r["file_path"]:
        return None
    p = ssc_paths.resolve_data_path(r["file_path"])
    if not (p.resolve().is_relative_to(_FILE_BASE.resolve()) and p.exists()):
        return None
    return p, r["mime"], r["file_name"]


def delete_file(conn, file_id: int) -> bool:
    r = _one(conn.execute("SELECT id, file_path FROM company_document_file WHERE id = ?", (file_id,)))
    if not r:
        return False
    conn.execute("DELETE FROM company_document_file WHERE id = ?", (file_id,))
    conn.commit()
    try:
        p = ssc_paths.resolve_data_path(r["file_path"])
        if p.resolve().is_relative_to(_FILE_BASE.resolve()):
            p.unlink(missing_ok=True)
    except Exception as e:
        log.warning("#318 vault file not removed from disk: %s", e)
    return True


# ---------------------------------------------------------------- routes
def register_routes(app, gate) -> None:
    def _with_conn(fn):
        conn = db_layer.connect()
        try:
            return fn(conn)
        finally:
            conn.close()

    @app.route("/api/company/portal/vehicles", methods=["GET"])
    @gate
    def vault_vehicles_list():
        rows = _with_conn(lambda c: list_vehicles(c, include_archived=request.args.get("archived") == "1"))
        return _wrap(rows, drivers=_with_conn(driver_options))

    @app.route("/api/company/portal/vehicles", methods=["POST"])
    @gate
    def vault_vehicles_create():
        payload = request.get_json(silent=True) or {}
        new_id, err = _with_conn(lambda c: create_vehicle(c, payload, actor=_uid()))
        if err:
            return _err(err)
        return _wrap(_with_conn(lambda c: get_vehicle(c, new_id))), 201

    @app.route("/api/company/portal/vehicles/<int:vehicle_id>", methods=["PATCH"])
    @gate
    def vault_vehicles_update(vehicle_id):
        payload = request.get_json(silent=True) or {}
        ok, err = _with_conn(lambda c: update_vehicle(c, vehicle_id, payload))
        if err:
            return _err(err)
        if not ok:
            return _err("vehicle not found", 404)
        return _wrap(_with_conn(lambda c: get_vehicle(c, vehicle_id)))

    @app.route("/api/company/portal/vehicles/<int:vehicle_id>", methods=["DELETE"])
    @gate
    def vault_vehicles_archive(vehicle_id):
        if not _with_conn(lambda c: archive_vehicle(c, vehicle_id)):
            return _err("vehicle not found", 404)
        return _wrap({"id": vehicle_id, "archived": True})

    @app.route("/api/company/portal/company-documents/<int:doc_id>/files", methods=["POST"])
    @gate
    def vault_file_upload(doc_id):
        if "file" not in request.files:
            return _err("no file")
        conn = db_layer.connect()
        try:
            try:
                return _wrap(add_file(conn, doc_id, request.files["file"], uploaded_by=_uid())), 201
            except LookupError as e:
                return _err(str(e), 404)
            except ValueError as e:
                return _err(str(e))
        finally:
            conn.close()

    @app.route("/api/company/portal/company-documents/files/<int:file_id>", methods=["GET"])
    @gate
    def vault_file_read(file_id):
        """The ONLY way a vault file is read: inline, no-store, path-contained."""
        got = _with_conn(lambda c: resolve_file(c, file_id))
        if not got:
            return _err("file not found", 404)
        p, mime, name = got
        resp = send_file(str(p), mimetype=mime or "application/octet-stream", as_attachment=False,
                         download_name=name or f"file-{file_id}")
        resp.headers["Cache-Control"] = "no-store, no-cache, must-revalidate, max-age=0"
        return resp

    @app.route("/api/company/portal/company-documents/files/<int:file_id>", methods=["DELETE"])
    @gate
    def vault_file_delete(file_id):
        if not _with_conn(lambda c: delete_file(c, file_id)):
            return _err("file not found", 404)
        return _wrap({"id": file_id, "deleted": True})
