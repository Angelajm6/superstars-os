#!/usr/bin/env python3
"""#322 — project_assignments on both backends. Idempotent.

`apply_assignments_schema.py` (the original) opens superstars.db with sqlite3
directly, so it never ran on the preprod Postgres database: the Labor Rate
Tracker's /api/payroll/hours (which pools workers from ACTIVE assignments)
failed there with `relation "project_assignments" does not exist`. This script
creates the table + indexes through db_layer, honours SSC_DB_URL, and is a no-op
where the table already exists (every SQLite install, the CI fixture).

No FKs by design (boot-order on a fresh preprod DB; same rule as #304 / #307).

Usage:  python apply_assignments_322.py
"""
from __future__ import annotations

import db_layer


def ensure(conn) -> bool:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    if db_layer.is_postgres():
        existed = bool(conn.execute(
            "SELECT 1 AS x FROM information_schema.tables WHERE table_name = 'project_assignments'").fetchone())
    else:
        existed = bool(conn.execute(
            "SELECT 1 AS x FROM sqlite_master WHERE type = 'table' AND name = 'project_assignments'").fetchone())
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS project_assignments ("
        f"  {pk},"
        f"  project_code    TEXT NOT NULL,"
        f"  employee_id     TEXT NOT NULL,"
        f"  role_on_project TEXT,"
        f"  start_date      DATE,"
        f"  end_date        DATE,"
        f"  status          TEXT DEFAULT 'active',"
        f"  notes           TEXT,"
        f"  created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,"
        f"  updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
        f")")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_proj_assign_project ON project_assignments(project_code)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_proj_assign_employee ON project_assignments(employee_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_proj_assign_status ON project_assignments(status)")
    conn.commit()
    return not existed


def main() -> int:
    conn = db_layer.connect(pragma_fk=True)
    try:
        created = ensure(conn)
        try:
            db_layer._PKMAP_CACHE.clear()
        except Exception:
            pass
    finally:
        conn.close()
    print(f"[#322] project_assignments {'created' if created else 'already present'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
