"""Google Calendar -> the software: each person's calendars, private to that person
(revamped 2026-10-16, replacing the 2026-10-15 "work events onto the team calendar" import).

The other direction already exists (gcal_sync: the app's tasks / events / meetings go to a separate
"Superstars" calendar in each person's Google account). This module reads the person's own
primary calendar (scope calendar.events.readonly, asked for when they connect Google Calendar)
and keeps a private copy in `user_calendar_event`:

  * every SYNC_SECONDS (default 60) it pulls the events that changed: the first time, the last
    LOOKBACK_DAYS through the next IMPORT_DAYS; afterwards whatever Google reports as updated since the last pull
    (a 410 "gone" answer starts over)
  * every event is kept (work and personal alike); out-of-office, focus time, working location and
    birthdays are skipped. An edit in Google updates the copy; a cancelled event or one the person
    declined deletes it
  * times are stored in New York time (SSC_TIMEZONE). When Google says the event was set in another
    zone, that zone and its local start time are kept too, so the Inbox can show both
  * other calendars (2026-10-19): with calendar.calendarlist.readonly, the calendars the person has
    ticked in Google's list (calendarList selected=true) are read the same way, each with its own
    "changed since" mark. Their rows are keyed "<calendarId>:<eventId>" so ids never collide; an
    event there that the person is invited to is skipped (it already comes from the main calendar),
    and the app's own "Superstars" calendar is never read back. Unticking a calendar removes its
    copies. Connections from before this scope keep the main calendar only until they reconnect
  * deletes read back (2026-10-19): the app's tasks / events / meetings are copied onto each person's
    "Superstars" calendar (gcal_sync, meeting_invites). When the person deletes one of those copies in
    Google, the next round notices: admin / C-suite (who may delete items in the app) delete the item
    in the app too, exactly like the app's Delete; anyone else only loses their own Google copy, which
    is not put back
  * an expired / revoked Google sign-in marks the connection 'needs_reconnect' (the Inbox shows a
    Reconnect banner); reconnecting reads the whole window again. Disconnecting deletes the copies

PRIVACY (non-negotiable): a row belongs to exactly one user. The ONLY reader is `events_for(conn,
uid, ...)`, and every route passes the signed-in user's own id. Nothing here creates team items,
and nothing reads another person's rows — admins included. Event text is never logged (ids and
counts only).

Before this release, work events were copied onto the team calendar as crm_task rows with
source 'gcal'. `move_team_copies` (run at boot, idempotent) moves them into the private table and
removes the team copies.
"""
from __future__ import annotations

import logging
import os
import re
import threading
import time
import urllib.parse
from datetime import date, datetime, timedelta
from typing import Optional
from zoneinfo import ZoneInfo

import db_layer

log = logging.getLogger("ssc.calendar_import")

READ_SCOPE = "https://www.googleapis.com/auth/calendar.events.readonly"
LIST_SCOPE = "https://www.googleapis.com/auth/calendar.calendarlist.readonly"
API = "https://www.googleapis.com/calendar/v3"
EVENTS_URL = API + "/calendars/primary/events"
LIST_URL = API + "/users/me/calendarList"
IMPORT_DAYS = 120
LOOKBACK_DAYS = 60   # past events show too (2026-10-18: reading from yesterday on left the month's earlier days empty)
SKIP_TYPES = {"birthday", "outOfOffice", "focusTime", "workingLocation"}
MAX_TITLE, MAX_PLACE, MAX_DETAIL = 300, 300, 2000


def tz() -> ZoneInfo:
    return ZoneInfo((os.environ.get("SSC_TIMEZONE") or "America/New_York").strip())


def sync_seconds() -> int:
    try:
        return max(30, int(os.environ.get("SSC_CALENDAR_IMPORT_SECONDS") or 60))
    except ValueError:
        return 60


# ------------------------------------------------------------------ schema
def _has_column(conn, table, column) -> bool:
    if db_layer.is_postgres():
        return bool(conn.execute("SELECT 1 FROM information_schema.columns WHERE table_schema='public' "
                                 "AND table_name = ? AND column_name = ?", (table, column)).fetchone())
    return any(r[1] == column for r in conn.execute(f"PRAGMA table_info({table})").fetchall())


def ensure(conn) -> None:
    import gcal_sync
    import team_items
    gcal_sync.ensure(conn)
    team_items.ensure(conn)
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    for table, col, typ in (("google_calendar_link", "scopes", "TEXT"), ("google_calendar_link", "import_at", "TEXT"),
                            ("google_calendar_link", "import_error", "TEXT"), ("google_calendar_link", "app_cal_at", "TEXT"),
                            ("crm_task", "source", "TEXT")):
        if not _has_column(conn, table, col):
            conn.execute(f"ALTER TABLE {table} ADD COLUMN {col} {typ}")
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS user_calendar_event ({pk}, user_id INTEGER NOT NULL, google_event_id TEXT NOT NULL, "
        f"title TEXT, location TEXT, detail TEXT, start_date TEXT NOT NULL, start_time TEXT, end_date TEXT, end_time TEXT, "
        f"source_tz TEXT, source_start_time TEXT, html_link TEXT, google_updated TEXT, updated_at TEXT NOT NULL)")
    if not _has_column(conn, "user_calendar_event", "calendar_id"):   # NULL = the main calendar
        conn.execute("ALTER TABLE user_calendar_event ADD COLUMN calendar_id TEXT")
    # the other calendars each person reads, with their own "changed since" mark
    conn.execute(f"CREATE TABLE IF NOT EXISTS user_calendar_source ({pk}, user_id INTEGER NOT NULL, calendar_id TEXT NOT NULL, "
                 f"import_at TEXT)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_user_cal_source ON user_calendar_source(user_id, calendar_id)")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_user_cal_event ON user_calendar_event(user_id, google_event_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_user_cal_event_day ON user_calendar_event(user_id, start_date)")
    # the old import's bookkeeping (still read once by move_team_copies)
    conn.execute(
        f"CREATE TABLE IF NOT EXISTS gcal_import ({pk}, user_id INTEGER NOT NULL, google_event_id TEXT NOT NULL, "
        f"item_id INTEGER, decision TEXT NOT NULL, google_updated TEXT, checked_at TEXT NOT NULL)")
    conn.commit()


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _one(conn, sql, params=()) -> Optional[dict]:
    r = conn.execute(sql, params).fetchone()
    return dict(r) if r else None


def _rows(conn, sql, params=()) -> list:
    return [dict(r) for r in conn.execute(sql, params).fetchall()]


def can_read(link: Optional[dict]) -> bool:
    return bool(link) and READ_SCOPE in (link.get("scopes") or "")


def can_list(link: Optional[dict]) -> bool:
    return bool(link) and LIST_SCOPE in (link.get("scopes") or "")


# ------------------------------------------------------------------ an event's when, in New York time
def when(ev: dict) -> Optional[dict]:
    """{start_date, start_time, end_date, end_time, source_tz, source_start_time} in local time; None when unusable.
    source_* are set only when Google says the event was set in a different zone than ours."""
    s, e = ev.get("start") or {}, ev.get("end") or {}
    if s.get("date"):   # all-day: Google's end date is exclusive; all-day events have no zone
        start = s["date"]
        end = (date.fromisoformat(e["date"]) - timedelta(days=1)).isoformat() if e.get("date") else start
        return {"start_date": start, "start_time": None, "end_date": end if end > start else None, "end_time": None,
                "source_tz": None, "source_start_time": None}
    if not s.get("dateTime"):
        return None
    try:
        raw_a = datetime.fromisoformat(s["dateTime"].replace("Z", "+00:00"))
        a = raw_a.astimezone(tz())
        b = datetime.fromisoformat((e.get("dateTime") or s["dateTime"]).replace("Z", "+00:00")).astimezone(tz())
    except ValueError:
        return None
    out = {"start_date": a.date().isoformat(), "start_time": a.strftime("%H:%M"), "end_date": None, "end_time": None,
           "source_tz": None, "source_start_time": None}
    if b > a:
        if b.date() != a.date():
            out.update(end_date=b.date().isoformat(), end_time=b.strftime("%H:%M"))
        else:
            out["end_time"] = b.strftime("%H:%M")
    zone = (s.get("timeZone") or "").strip()
    if zone and zone != tz().key:
        try:
            there = raw_a.astimezone(ZoneInfo(zone))
        except Exception:
            there = None
        if there is not None and there.utcoffset() != a.utcoffset():   # same offset = same wall clock, nothing to show
            out.update(source_tz=zone, source_start_time=there.strftime("%H:%M"))
    return out


# ------------------------------------------------------------------ the private copy
def _clean(text, limit) -> Optional[str]:
    s = re.sub(r"<[^>]+>", " ", str(text or ""))
    s = re.sub(r"[ \t]+", " ", s).strip()
    return s[:limit] or None


def _store(conn, uid: int, gid: str, ev: dict, w: dict, cal: Optional[str]) -> str:
    row = {"title": _clean(ev.get("summary"), MAX_TITLE) or "(No title)", "location": _clean(ev.get("location"), MAX_PLACE),
           "detail": _clean(ev.get("description"), MAX_DETAIL), "html_link": (ev.get("htmlLink") or "")[:500] or None,
           "google_updated": ev.get("updated"), "calendar_id": cal, **w}
    cols = list(row)
    have = _one(conn, "SELECT id FROM user_calendar_event WHERE user_id = ? AND google_event_id = ?", (uid, gid))
    if have:
        conn.execute(f"UPDATE user_calendar_event SET {', '.join(c + ' = ?' for c in cols)}, updated_at = ? WHERE id = ?",
                     (*[row[c] for c in cols], _now(), have["id"]))
        result = "updated"
    else:
        conn.execute(f"INSERT INTO user_calendar_event (user_id, google_event_id, {', '.join(cols)}, updated_at) "
                     f"VALUES (?, ?, {', '.join('?' * len(cols))}, ?)", (uid, gid, *[row[c] for c in cols], _now()))
        result = "created"
    conn.commit()
    return result


def _drop(conn, uid: int, gid: str) -> bool:
    n = conn.execute("DELETE FROM user_calendar_event WHERE user_id = ? AND google_event_id = ?", (uid, gid)).rowcount
    conn.commit()
    return bool(n)


def apply_event(conn, uid: int, ev: dict, cal: Optional[str] = None, my_email: str = "") -> str:
    """One Google event -> created / updated / unchanged / deleted / skipped, in THIS user's private copy.
    `cal` is None for the main calendar, else the other calendar's id (the row is keyed "<cal>:<event id>")."""
    if not ev.get("id"):
        return "skipped"
    gid = f"{cal}:{ev['id']}" if cal else ev["id"]
    me = next((a for a in ev.get("attendees") or [] if a.get("self")), None)
    if ev.get("status") == "cancelled" or (me and me.get("responseStatus") == "declined"):
        return "deleted" if _drop(conn, uid, gid) else "skipped"
    mail = (my_email or "").strip().lower()
    if cal and mail and any((a.get("email") or "").strip().lower() == mail for a in ev.get("attendees") or []):
        _drop(conn, uid, gid)   # the person is invited: it already comes in from their main calendar
        return "skipped"
    if ((ev.get("extendedProperties") or {}).get("shared") or {}).get("ssc_item"):
        _drop(conn, uid, gid)   # a Superstars meeting invitation: the meeting already shows in the app (meeting_invites)
        return "skipped"
    if ev.get("eventType") in SKIP_TYPES:
        _drop(conn, uid, gid)   # e.g. an event turned into out-of-office
        return "skipped"
    w = when(ev)
    if not w:
        _drop(conn, uid, gid)
        return "skipped"
    seen = _one(conn, "SELECT google_updated FROM user_calendar_event WHERE user_id = ? AND google_event_id = ?", (uid, gid))
    if seen and ev.get("updated") and seen.get("google_updated") == ev.get("updated"):
        return "unchanged"
    return _store(conn, uid, gid, ev, w, cal)


def events_for(conn, uid: int, date_from: str, date_to: str) -> list:
    """THE reader: this user's own calendar events that touch [date_from, date_to]. `uid` must be the
    signed-in user's id — no route passes anyone else's."""
    if not uid:
        return []
    rows = _rows(conn, "SELECT id, title, location, detail, start_date, start_time, end_date, end_time, source_tz, "
                       "source_start_time, html_link FROM user_calendar_event WHERE user_id = ? AND start_date <= ? "
                       "AND COALESCE(end_date, start_date) >= ? ORDER BY start_date, COALESCE(start_time, '00:00'), id",
                 (uid, date_to, date_from))
    return [dict(r, kind="calendar", private=True) for r in rows]


def forget_user(conn, uid: int) -> None:
    """Disconnecting Google Calendar removes the private copies."""
    conn.execute("DELETE FROM user_calendar_event WHERE user_id = ?", (uid,))
    conn.execute("DELETE FROM user_calendar_source WHERE user_id = ?", (uid,))
    try:
        conn.execute("DELETE FROM gcal_import WHERE user_id = ?", (uid,))
    except Exception:
        conn.rollback()
    conn.commit()


# ------------------------------------------------------------------ the one-time move off the team calendar
def move_team_copies(conn) -> int:
    """Idempotent. crm_task rows with source 'gcal' (the old import) become private rows of the
    person they were assigned to, then leave the team calendar. Each moved person reads their
    whole window again on the next sync, which refreshes the copies with full detail."""
    rows = _rows(conn, "SELECT t.*, g.google_event_id FROM crm_task t LEFT JOIN gcal_import g ON g.item_id = t.id "
                       "AND g.user_id = t.assignee_user_id WHERE t.source = 'gcal'")
    if not rows:
        return 0
    users = set()
    for t in rows:
        uid = t.get("assignee_user_id") or t.get("created_by")
        start = t.get("start_date") or t.get("due_date")
        if uid and start and (t.get("status") or "open") != "cancelled":
            gid = t.get("google_event_id") or f"moved-{t['id']}"
            detail = (t.get("detail") or "").replace("From Google Calendar.", "", 1).strip() or None
            if not _one(conn, "SELECT 1 AS x FROM user_calendar_event WHERE user_id = ? AND google_event_id = ?", (uid, gid)):
                conn.execute("INSERT INTO user_calendar_event (user_id, google_event_id, title, location, detail, start_date, "
                             "start_time, end_date, end_time, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)",
                             (uid, gid, t.get("title") or "(No title)", t.get("address") or t.get("location"), detail, start,
                              t.get("start_time"), t.get("end_date"), t.get("end_time"), _now()))
        if uid:
            users.add(uid)
        conn.execute("DELETE FROM google_calendar_event WHERE item_id = ?", (t["id"],))
        conn.execute("DELETE FROM crm_task WHERE id = ?", (t["id"],))
    for uid in users:
        conn.execute("DELETE FROM gcal_import WHERE user_id = ?", (uid,))
        conn.execute("UPDATE google_calendar_link SET import_at = NULL WHERE user_id = ?", (uid,))
    conn.commit()
    log.info("calendar import: moved %s team copies of Google events to %s private calendars", len(rows), len(users))
    return len(rows)


# ------------------------------------------------------------------ pulling from Google
def _get(conn, link, url, params) -> tuple:
    """GET one page from Google. A 401 (access token revoked early) refreshes the token once."""
    import gcal_sync
    url = url + "?" + urllib.parse.urlencode(params)
    code, body = gcal_sync._http("GET", url, token=gcal_sync._access_token(conn, link))
    if code == 401:
        gcal_sync._TOKENS.pop(link["user_id"], None)
        code, body = gcal_sync._http("GET", url, token=gcal_sync._access_token(conn, link))
        if code == 401:
            raise gcal_sync.NeedsReconnect()
    return code, body


def _other_calendars(conn, link) -> list:
    """Ids of the calendars the person ticked in Google, minus the main one and the app's own Superstars calendar."""
    ids, page = [], None
    while True:
        code, body = _get(conn, link, LIST_URL, dict({"maxResults": "250"}, **({"pageToken": page} if page else {})))
        if code != 200:
            raise RuntimeError(f"calendar list failed ({code})")
        for c in body.get("items") or []:
            cid = c.get("id")
            if cid and c.get("selected") and not c.get("primary") and not c.get("deleted") and cid != link.get("calendar_id"):
                ids.append(cid)
        page = body.get("nextPageToken")
        if not page:
            return ids


def _pull(conn, link, url, since: Optional[str], started, counts, cal=None, on_event=None) -> int:
    """Read one calendar's events (the window, or what changed since `since`) into the private copy
    (or hand each to `on_event`). Returns Google's status: 200, or the code that stopped it (410 = start this calendar over)."""
    base = {"singleEvents": "true", "showDeleted": "true", "maxResults": "250",
            "timeMin": (started - timedelta(days=LOOKBACK_DAYS)).replace(hour=0, minute=0, second=0, microsecond=0).isoformat()}
    if since:
        base["updatedMin"] = (datetime.fromisoformat(since).replace(tzinfo=tz()) - timedelta(minutes=5)).isoformat()
    else:
        base["timeMax"] = (started + timedelta(days=IMPORT_DAYS)).isoformat()
    page = None
    while True:
        code, body = _get(conn, link, url, dict(base, **({"pageToken": page} if page else {})))
        if code != 200:
            return code
        for ev in body.get("items") or []:
            r = on_event(ev) if on_event else apply_event(conn, link["user_id"], ev, cal, link.get("google_email") or "")
            if r:
                counts[r] = counts.get(r, 0) + 1
        page = body.get("nextPageToken")
        if not page:
            return 200


def _import_others(conn, link, started, counts) -> None:
    """The person's other ticked calendars. Without the list permission (connected before it existed) none are
    read, and copies from calendars no longer ticked are removed."""
    uid = link["user_id"]
    want = _other_calendars(conn, link) if can_list(link) else []
    marks = {r["calendar_id"]: r["import_at"] for r in _rows(conn, "SELECT calendar_id, import_at FROM user_calendar_source WHERE user_id = ?", (uid,))}
    for cid in set(marks) | {r["calendar_id"] for r in _rows(conn, "SELECT DISTINCT calendar_id FROM user_calendar_event "
                                                                    "WHERE user_id = ? AND calendar_id IS NOT NULL", (uid,))}:
        if cid not in want:
            n = conn.execute("DELETE FROM user_calendar_event WHERE user_id = ? AND calendar_id = ?", (uid, cid)).rowcount
            conn.execute("DELETE FROM user_calendar_source WHERE user_id = ? AND calendar_id = ?", (uid, cid))
            counts["deleted"] = counts.get("deleted", 0) + max(n or 0, 0)
    conn.commit()
    for cid in want:
        since = marks.get(cid) if link.get("import_at") else None   # a full re-read of the main calendar re-reads these too
        code = _pull(conn, link, f"{API}/calendars/{urllib.parse.quote(cid, safe='')}/events", since, started, counts, cal=cid)
        if code in (403, 404):   # unshared or gone since the list was read: try again next round
            continue
        if code not in (200, 410):
            raise RuntimeError(f"events failed ({code})")
        mark = started.replace(tzinfo=None).isoformat(timespec="seconds") if code == 200 else None
        if cid in marks:
            conn.execute("UPDATE user_calendar_source SET import_at = ? WHERE user_id = ? AND calendar_id = ?", (mark, uid, cid))
        else:
            conn.execute("INSERT INTO user_calendar_source (user_id, calendar_id, import_at) VALUES (?, ?, ?)", (uid, cid, mark))
        conn.commit()


def _deleted_in_google(conn, uid: int, gid: str, wanted: dict) -> Optional[str]:
    """One of the app's copies was deleted in this person's Superstars calendar. Returns 'removed' / 'dropped' / None."""
    import team_items
    row = _one(conn, "SELECT item_id FROM google_calendar_event WHERE user_id = ? AND google_event_id = ? "
                     "AND COALESCE(dropped, 0) = 0", (uid, gid))
    meeting = None if row else _one(conn, "SELECT item_id FROM meeting_invite WHERE owner_id = ? AND google_event_id = ?", (uid, gid))
    item_id = (row or meeting or {}).get("item_id")
    item = _one(conn, "SELECT id, status, invite_owner_id FROM crm_task WHERE id = ?", (item_id,)) if item_id else None
    if not item or (item.get("status") or "open") == "cancelled":
        return None
    if row:
        if "ids" not in wanted:   # the app itself may be taking it off their calendar this very moment
            import gcal_sync
            wanted["ids"] = set(gcal_sync._wanted(conn, uid))
        if item_id not in wanted["ids"]:
            return None
    elif item.get("invite_owner_id") != uid:
        return None
    me = _one(conn, "SELECT role FROM users WHERE id = ?", (uid,)) or {}
    if me.get("role") in team_items.EDIT_ROLES:
        team_items.cancel(conn, item_id, actor=uid)   # the same as Delete in the app: off everyone's calendar
        log.info("calendar import user=%s: item %s deleted in Google, deleted in the app", uid, item_id)
        return "removed"
    if row:   # may not delete team items: only their own Google copy goes, and stays gone
        conn.execute("UPDATE google_calendar_event SET dropped = 1 WHERE user_id = ? AND item_id = ?", (uid, item_id))
        conn.commit()
        log.info("calendar import user=%s: item %s removed from their Google only", uid, item_id)
        return "dropped"
    return None


def read_back(conn, link, started, counts) -> None:
    """Deletes on the person's Superstars calendar (the app's copies) come back to the app."""
    cal = link.get("calendar_id")
    if not cal:
        return
    uid, wanted = link["user_id"], {}

    def on_event(ev):
        if ev.get("status") == "cancelled" and ev.get("id"):
            return _deleted_in_google(conn, uid, ev["id"], wanted)
        return None
    since = link.get("app_cal_at") if link.get("import_at") else None
    code = _pull(conn, link, f"{API}/calendars/{urllib.parse.quote(cal, safe='')}/events", since, started, counts, on_event=on_event)
    if code in (403, 404):   # the Superstars calendar itself was removed: gcal_sync makes a new one
        return
    if code not in (200, 410):
        raise RuntimeError(f"superstars calendar read failed ({code})")
    conn.execute("UPDATE google_calendar_link SET app_cal_at = ? WHERE user_id = ?",
                 (started.replace(tzinfo=None).isoformat(timespec="seconds") if code == 200 else None, uid))
    conn.commit()


def import_user(conn, uid) -> dict:
    import gcal_sync
    link = gcal_sync._link(conn, uid)
    if not link or link.get("status") != "active" or not can_read(link):
        return {"skipped": True}
    started = datetime.now(tz=tz())
    counts = {}
    try:
        code = _pull(conn, link, EVENTS_URL, link.get("import_at"), started, counts)
        if code == 410:   # Google forgot what changed: read the window again (every calendar)
            conn.execute("UPDATE google_calendar_link SET import_at = NULL WHERE user_id = ?", (uid,))
            conn.commit()
            return {"reset": True}
        if code != 200:
            raise RuntimeError(f"events failed ({code})")
        _import_others(conn, link, started, counts)
        read_back(conn, link, started, counts)
        conn.execute("UPDATE google_calendar_link SET import_at = ?, import_error = NULL WHERE user_id = ?",
                     (started.replace(tzinfo=None).isoformat(timespec="seconds"), uid))
        conn.commit()
        if counts.get("created") or counts.get("updated") or counts.get("deleted") or counts.get("removed") or counts.get("dropped"):
            log.info("calendar import user=%s %s", uid, {k: v for k, v in counts.items() if k in ("created", "updated", "deleted", "removed", "dropped")})
        return counts
    except gcal_sync.NeedsReconnect:
        gcal_sync._TOKENS.pop(uid, None)
        conn.execute("UPDATE google_calendar_link SET status = 'needs_reconnect', last_error = ? WHERE user_id = ?",
                     ("Google sign-in expired", uid))
        conn.commit()
        log.info("calendar import user=%s: Google sign-in expired, waiting for reconnect", uid)
        return {"needs_reconnect": True}
    except Exception as e:
        try:
            conn.rollback()
        except Exception:
            pass
        conn.execute("UPDATE google_calendar_link SET import_error = ? WHERE user_id = ?",
                     ("The last calendar read did not finish; it retries by itself", uid))
        conn.commit()
        log.warning("calendar import user=%s failed: %s", uid, type(e).__name__)
        return {"error": True}


_LOOP = {"started": False}


def _loop() -> None:
    import gcal_sync
    time.sleep(25)
    while True:
        try:
            if not gcal_sync.unavailable_reason():
                conn = db_layer.connect()
                try:
                    for r in _rows(conn, "SELECT user_id FROM google_calendar_link WHERE status = 'active' AND scopes LIKE ?",
                                   (f"%{READ_SCOPE}%",)):
                        import_user(conn, r["user_id"])
                    for r in _rows(conn, "SELECT user_id FROM google_calendar_link WHERE status = 'active' AND last_error IS NOT NULL"):
                        gcal_sync.sync_user(conn, r["user_id"])   # a failed push retries by itself, not only on the next app edit
                    import meeting_invites
                    meeting_invites.refresh_all(conn)   # guests' answers to the meetings people organized
                finally:
                    conn.close()
        except Exception as e:
            log.warning("calendar import round failed: %s", type(e).__name__)
        time.sleep(sync_seconds())


def start() -> None:
    if _LOOP["started"] or os.environ.get("SSC_GMAIL_POLL", "1") != "1":
        return
    _LOOP["started"] = True
    threading.Thread(target=_loop, name="calendar-import", daemon=True).start()


def register(app) -> None:
    conn = db_layer.connect()
    try:
        ensure(conn)
        move_team_copies(conn)
        db_layer._PKMAP_CACHE.clear()   # tables created at boot after the pk-map cache filled (#290 lesson)
    except Exception as e:
        log.warning("calendar import schema ensure skipped: %s", type(e).__name__)
        try:
            conn.rollback()
        except Exception:
            pass
    finally:
        conn.close()
    import gcal_sync
    if not gcal_sync.unavailable_reason():
        start()
