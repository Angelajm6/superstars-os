#!/usr/bin/env python3
"""Hours over 8 in a day need a reason and an admin or PM's approval (2026-10-30).

  hours_overtime    one row per (worker, date) whose hours across every job pass
                    payroll_hours.DAY_LIMIT: the reason, who asked (the office or
                    the worker app), and the decision. Payroll pays the limit
                    until the row is approved, then up to approved_hours.

Idempotent + dual-backend. Ensured at SERVER BOOT (#289 pattern) — no manual
step on deploy. Run standalone:  python apply_hours_overtime.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

import db_layer  # noqa: E402
from apply_crm_266 import _table_exists  # noqa: E402


def ensure_hours_overtime_schema(conn) -> dict:
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
          if db_layer.is_postgres() else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    changed = {"hours_overtime": not _table_exists(conn, "hours_overtime")}
    conn.execute(
        f"""CREATE TABLE IF NOT EXISTS hours_overtime (
              {pk},
              employee_id       TEXT NOT NULL,
              date              TEXT NOT NULL,      -- YYYY-MM-DD (local)
              logged_hours      REAL NOT NULL,      -- the day's hours when asked
              approved_hours    REAL,               -- set on approve
              reason            TEXT,
              status            TEXT NOT NULL DEFAULT 'pending',   -- pending | approved | rejected
              requested_by_uid  INTEGER,
              requested_by_role TEXT,               -- 'worker' when asked from the worker app
              requested_at      TEXT,               -- LOCAL ISO (never UTC)
              decided_by_uid    INTEGER,
              decided_by_role   TEXT,
              decided_at        TEXT,
              decision_note     TEXT
            )""")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_hours_overtime_day "
                 "ON hours_overtime(employee_id, date)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_hours_overtime_status "
                 "ON hours_overtime(status, date)")
    conn.commit()
    return changed


def main() -> int:
    conn = db_layer.connect()
    backend = "postgres" if db_layer.is_postgres() else "sqlite"
    try:
        changed = ensure_hours_overtime_schema(conn)
        ok = _table_exists(conn, "hours_overtime")
        print(f"[overtime] backend={backend}  changed={changed}")
        print(f"[overtime] verify: table -> {'OK' if ok else 'FAIL'}")
        return 0 if ok else 1
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
