"""Ask someone to review a proposal before it goes to the client (accepted prototype 2026-11-11:
https://claude.ai/artifact/E3AZ6ytnir14NxaBCnQgK6).

Optional: a draft can always be sent without one, and sending closes any open review. One open review per proposal.

  proposal_review(id, proposal_id, requested_by, reviewer_id, note, status, answer_note, fingerprint, total,
                  requested_at, answered_at, reopened_at, reminded_at, closed_at)

  status   pending  -> approved | changes          (the reviewer answers)
           approved -> pending                     (reopened: a price or a line changed after the approval)
           pending | approved | changes -> cancelled | replaced | sent

The approval holds for the exact lines and total it was given on (`fingerprint`). A change after it sends the proposal
back to the reviewer the next time anyone reads it (`state` / `bell`), so every edit path is covered without each one
reporting anything.

The bell (activity_feed) reads these rows: the reviewer is told about a request, a reminder and a reopen; the requester
about the answer. Each person sends from their own Gmail; the review email goes from the requester's Gmail to the
reviewer, never to the client.
"""
from __future__ import annotations

import hashlib
import json
import logging
from datetime import datetime
from typing import Optional

log = logging.getLogger("ssc.proposal_review")

OPEN = ("pending", "approved", "changes")
NOTE_MAX = 1000
REVIEWER_ROLES = ("admin",)   # the bell, where a request pops up, is for admins


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _rows(conn, sql, params=()) -> list:
    return [dict(r) for r in conn.execute(sql, params).fetchall()]


def _one(conn, sql, params=()) -> Optional[dict]:
    r = conn.execute(sql, params).fetchone()
    return dict(r) if r else None


def ensure(conn) -> None:
    """Idempotent."""
    import db_layer
    pk = ("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db_layer.is_postgres()
          else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(f"CREATE TABLE IF NOT EXISTS proposal_review ({pk}, proposal_id INTEGER NOT NULL, requested_by INTEGER NOT NULL, "
                 "reviewer_id INTEGER NOT NULL, note TEXT, status TEXT NOT NULL DEFAULT 'pending', answer_note TEXT, "
                 "fingerprint TEXT, total REAL, requested_at TEXT NOT NULL, answered_at TEXT, reopened_at TEXT, "
                 "reminded_at TEXT, closed_at TEXT)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_proposal_review_p ON proposal_review(proposal_id, status)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_proposal_review_r ON proposal_review(reviewer_id, status)")
    conn.commit()


def _name(conn, uid) -> str:
    r = _one(conn, "SELECT full_name, email FROM users WHERE id = ?", (uid,)) or {}
    return (str(r.get("full_name") or "").split() or [str(r.get("email") or "Someone").split("@")[0]])[0]


def fingerprint(conn, r: dict) -> tuple:
    """(hash, total) of what the client would get priced: every line and the total."""
    import proposals
    total = proposals.amounts(conn, r)["total"]
    lines = [[li.get("description"), li.get("lead"), li.get("qty"), li.get("unit"), li.get("unit_price"), li.get("amount")]
             for li in proposals.lines(conn, r["id"])]
    raw = json.dumps({"t": round(float(total or 0), 2), "l": lines}, sort_keys=True, default=str)
    return hashlib.sha256(raw.encode()).hexdigest(), round(float(total or 0), 2)


def reviewers(conn, uid) -> list:
    """Who can be asked: active admins other than you; the one you asked last comes first."""
    last = _one(conn, "SELECT reviewer_id FROM proposal_review WHERE requested_by = ? ORDER BY id DESC LIMIT 1", (uid,)) or {}
    ph = ",".join("?" * len(REVIEWER_ROLES))
    people = _rows(conn, f"SELECT id, full_name, email FROM users WHERE role IN ({ph}) AND status = 'active' AND id <> ? "
                         "ORDER BY full_name", (*REVIEWER_ROLES, uid))
    out = [{"id": p["id"], "name": p["full_name"] or p["email"].split("@")[0]} for p in people]
    out.sort(key=lambda p: 0 if p["id"] == last.get("reviewer_id") else 1)
    return out


def _open(conn, pid: int) -> Optional[dict]:
    return _one(conn, "SELECT * FROM proposal_review WHERE proposal_id = ? AND status IN ('pending','approved','changes') "
                      "ORDER BY id DESC LIMIT 1", (pid,))


def _refresh(conn, row: Optional[dict], r: Optional[dict]) -> Optional[dict]:
    """An approval whose lines or total changed goes back to the reviewer (once, at the moment it is noticed)."""
    if not row or row["status"] != "approved" or not r or r.get("status") != "draft":
        return row
    fp, total = fingerprint(conn, r)
    if fp == row.get("fingerprint"):
        return row
    import proposals
    now = _now()
    cur = conn.execute("UPDATE proposal_review SET status = 'pending', reopened_at = ? WHERE id = ? AND status = 'approved'",
                       (now, row["id"]))
    if (getattr(cur, "rowcount", 0) or 0) > 0:
        proposals._event(conn, r["id"], "review_reopened", detail=f"changed after approval: ${row.get('total') or 0:,.2f} -> ${total:,.2f}")
    conn.commit()
    return _one(conn, "SELECT * FROM proposal_review WHERE id = ?", (row["id"],))


def public(conn, row: Optional[dict], uid) -> Optional[dict]:
    if not row:
        return None
    return {"id": row["id"], "status": row["status"], "reopened": bool(row.get("reopened_at")) and row["status"] == "pending",
            "note": row.get("note") or "", "answer_note": row.get("answer_note") or "", "total": row.get("total"),
            "requested_at": row["requested_at"], "answered_at": row.get("answered_at"), "reminded_at": row.get("reminded_at"),
            "requested_by": {"id": row["requested_by"], "name": _name(conn, row["requested_by"])},
            "reviewer": {"id": row["reviewer_id"], "name": _name(conn, row["reviewer_id"])},
            "mine_to_answer": row["reviewer_id"] == uid and row["status"] == "pending",
            "i_asked": row["requested_by"] == uid}


def state(conn, pid: int, uid) -> dict:
    """What the Studio shows: the open review (refreshed), and who can be asked."""
    import proposals
    r = proposals.get(conn, pid)
    row = _refresh(conn, _open(conn, pid), r)
    return {"review": public(conn, row, uid), "reviewers": reviewers(conn, uid) if r and r.get("status") == "draft" else []}


def _draft(conn, pid: int) -> dict:
    import proposals
    r = proposals.get(conn, pid)
    if not r:
        raise LookupError("proposal not found")
    if r["status"] != "draft":
        raise ValueError("Only a draft can be reviewed. This proposal was already sent.")
    return r


def _note(v) -> str:
    return str(v or "").strip()[:NOTE_MAX]


def request(conn, pid: int, uid, reviewer_id, note=None) -> dict:
    import proposal_engine
    import proposals
    r = _draft(conn, pid)
    try:
        reviewer_id = int(reviewer_id or 0)
    except (TypeError, ValueError):
        reviewer_id = 0
    if not any(p["id"] == reviewer_id for p in reviewers(conn, uid)):
        raise ValueError("Pick who should review it.")
    now = _now()
    old = _open(conn, pid)
    if old:   # asking again (after changes, or someone else): the earlier one is replaced
        conn.execute("UPDATE proposal_review SET status = 'replaced', closed_at = ? WHERE id = ?", (now, old["id"]))
    conn.execute("INSERT INTO proposal_review (proposal_id, requested_by, reviewer_id, note, status, requested_at) "
                 "VALUES (?,?,?,?, 'pending', ?)", (pid, uid, reviewer_id, _note(note), now))
    proposals._event(conn, pid, "review_requested", actor=uid, detail=f"to user {reviewer_id}")
    conn.commit()
    proposals._activity(conn, r, f"Proposal {proposal_engine.label(r)} sent for review", actor=uid)
    return _open(conn, pid)


def answer(conn, pid: int, uid, verb: str, note=None) -> dict:
    import proposal_engine
    import proposals
    r = _draft(conn, pid)
    row = _refresh(conn, _open(conn, pid), r)
    if not row or row["status"] != "pending":
        raise ValueError("There's no review waiting on this proposal.")
    if row["reviewer_id"] != uid:
        raise PermissionError("Only the person asked can answer this review.")
    now, note = _now(), _note(note)
    if verb == "approve":
        fp, total = fingerprint(conn, r)
        conn.execute("UPDATE proposal_review SET status = 'approved', answer_note = ?, fingerprint = ?, total = ?, answered_at = ?, "
                     "reopened_at = NULL WHERE id = ?", (note or None, fp, total, now, row["id"]))
        proposals._event(conn, pid, "review_approved", actor=uid, detail=f"${total:,.2f}")
        what = "approved"
    elif verb == "changes":
        if not note:
            raise ValueError("Say what should change.")
        conn.execute("UPDATE proposal_review SET status = 'changes', answer_note = ?, answered_at = ?, reopened_at = NULL WHERE id = ?",
                     (note, now, row["id"]))
        proposals._event(conn, pid, "review_changes", actor=uid)
        what = "sent back with changes"
    else:
        raise ValueError("answer = approve or changes")
    conn.commit()
    proposals._activity(conn, r, f"Proposal {proposal_engine.label(r)} review: {what}", actor=uid)
    return _open(conn, pid)


def cancel(conn, pid: int, uid) -> None:
    import proposals
    _draft(conn, pid)
    row = _open(conn, pid)
    if not row:
        raise ValueError("There's no review on this proposal.")
    if uid not in (row["requested_by"], row["reviewer_id"]):
        raise PermissionError("Only the person who asked, or the reviewer, can cancel it.")
    conn.execute("UPDATE proposal_review SET status = 'cancelled', closed_at = ? WHERE id = ?", (_now(), row["id"]))
    proposals._event(conn, pid, "review_cancelled", actor=uid)
    conn.commit()


def remind(conn, pid: int, uid) -> None:
    _draft(conn, pid)
    row = _open(conn, pid)
    if not row or row["status"] != "pending":
        raise ValueError("There's no review waiting on this proposal.")
    if row["requested_by"] != uid:
        raise PermissionError("Only the person who asked can send a reminder.")
    conn.execute("UPDATE proposal_review SET reminded_at = ? WHERE id = ?", (_now(), row["id"]))
    conn.commit()


def close_on_send(conn, pid: int, uid) -> Optional[dict]:
    """The proposal went to the client: an open review closes. Returns it (for the send's Cc and history)."""
    import proposals
    row = _open(conn, pid)
    if not row:
        return None
    conn.execute("UPDATE proposal_review SET status = 'sent', closed_at = ? WHERE id = ?", (_now(), row["id"]))
    if row["status"] == "pending":
        proposals._event(conn, pid, "review_closed", actor=uid, detail="sent before the review was answered")
    conn.commit()
    return row


def cc_for(conn, pid: int, uid) -> str:
    """Sending someone else's reviewed proposal: they're copied, so they see it went out."""
    row = _open(conn, pid)
    if not row or row["requested_by"] == uid:
        return ""
    u = _one(conn, "SELECT email FROM users WHERE id = ?", (row["requested_by"],)) or {}
    return u.get("email") or ""


def email_reviewer(conn, pid: int, uid, row: dict) -> dict:
    """The review email, from the requester's own Gmail to the reviewer, with the PDF and a link to the Studio. Best
    effort: the request already stands in the app (the bell) whether or not this goes out."""
    import inbox
    import proposal_engine
    import proposals
    import proposal_studio
    rv = _one(conn, "SELECT email FROM users WHERE id = ?", (row["reviewer_id"],)) or {}
    if not rv.get("email"):
        return {"sent": False, "why": "The reviewer has no email address."}
    r = proposals.get(conn, pid)
    label = proposal_engine.label(r)
    link = f"{proposals._base_url()}/proposal-studio#p/{pid}"
    total = proposals.amounts(conn, r)["total"]
    body = ((row.get("note") or "Can you review this proposal before it goes out?") +
            f"\n\nProposal {label} · {r.get('client_name') or ''} · ${total:,.2f}\nOpen it in Proposal Studio to approve it or ask for changes:\n{link}\n")
    att = []
    try:
        res = proposals.render_pdf(conn, pid, actor=uid)
        pdf = proposals.pdf_file(conn, pid) if res.get("ok") else None
        if pdf:
            att = [(proposal_studio.attachment_name(r), pdf.read_bytes(), "application/pdf")]
    except Exception as e:
        log.info("review email without the PDF: %s", type(e).__name__)
    try:
        inbox.compose(conn, uid, rv["email"], "", f"Review: Proposal {label} · {r.get('client_name') or ''}".strip(" ·"), body, attachments=att)
    except ValueError as e:
        return {"sent": False, "why": str(e)}
    return {"sent": True, "pdf": bool(att)}


# ------------------------------------------------------------------ the bell
def _proposal_bits(conn, pid: int) -> dict:
    import proposal_engine
    import proposals
    r = proposals.get(conn, pid) or {}
    return {"r": r, "label": proposal_engine.label(r) if r else str(pid), "client": r.get("client_name") or "",
            "href": f"/proposal-studio#p/{pid}"}


def bell(conn, uid: int, since: str) -> tuple:
    """(items, for_you) for this person: a request, reminder or reopen for the reviewer; the answer for the requester.
    Items pop up once as banners (the activity marks decide that); For you keeps what still waits on this person."""
    items, you = [], []
    rows = _rows(conn, "SELECT * FROM proposal_review WHERE (reviewer_id = ? OR requested_by = ?) AND status IN ('pending','approved','changes') "
                       "AND requested_at >= ? ORDER BY id DESC LIMIT 40", (uid, uid, since[:10]))
    for row in rows:
        b = _proposal_bits(conn, row["proposal_id"])
        r = b["r"]
        if not r or r.get("status") != "draft":
            continue
        row = _refresh(conn, row, r) or row
        who_asked, reviewer = _name(conn, row["requested_by"]), _name(conn, row["reviewer_id"])
        base = {"proposal_id": row["proposal_id"], "href": b["href"], "open_label": "Open proposal"}
        total = f"${float(row.get('total') or 0):,.2f}" if row.get("total") else ""
        if row["reviewer_id"] == uid and row["status"] == "pending":
            if row.get("reopened_at"):   # a reminder after the reopen pops it again
                at = max(row["reopened_at"], row.get("reminded_at") or "")
                title = f"Proposal {b['label']} changed after you approved it"
                sub = "Review it again" + (f" · you approved {total}" if total else "")
            else:
                at = max(row["requested_at"], row.get("reminded_at") or "")
                title = f"{who_asked} asked you to review Proposal {b['label']}"
                sub = row.get("note") or b["client"]
            items.append(dict(base, id=f"review:{row['id']}:{at}", kind="review", icon="doc", tint="blue", title=title,
                              sub=sub[:160], at=at, banner=True, sticky=True, open_label="Review it"))
            you.append({"id": f"review:{row['id']}", "kind": "review", "group": "review", "icon": "doc", "tint": "blue",
                        "title": title if row.get("reopened_at") else f"Review Proposal {b['label']} for {who_asked}",
                        "sub": (row.get("note") or b["client"])[:160], "pill": "Waiting on you", "href": b["href"], "urgency": "today"})
        elif row["requested_by"] == uid and row["status"] in ("approved", "changes") and row.get("answered_at"):
            ok = row["status"] == "approved"
            title = (f"{reviewer} approved Proposal {b['label']}" if ok else f"{reviewer} asked for changes on Proposal {b['label']}")
            sub = (f"{total} · ready to send" if ok else (row.get("answer_note") or ""))[:160]
            items.append(dict(base, id=f"review:{row['id']}:{row['answered_at']}", kind="review", icon="check" if ok else "doc",
                              tint="ok" if ok else "warn", title=title, sub=sub, at=row["answered_at"], banner=True, sticky=True,
                              open_label="Send it" if ok else "Open proposal"))
            you.append({"id": f"review:{row['id']}", "kind": "review", "group": "review", "icon": "check" if ok else "doc",
                        "tint": "ok" if ok else "warn",
                        "title": f"Proposal {b['label']} is approved and ready to send" if ok else title,
                        "sub": sub, "pill": "Approved" if ok else "Changes asked", "href": b["href"], "urgency": "today"})
    return items, you
